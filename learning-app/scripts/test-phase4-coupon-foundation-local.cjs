/* eslint-disable @typescript-eslint/no-require-imports */
const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const path = require('node:path');
const { PGlite } = require(process.env.PGLITE_PACKAGE_PATH || '@electric-sql/pglite');

const migrationPath = path.resolve(__dirname,
  '../supabase/migrations/20261016000000_add_private_learning_coupon_foundation.sql');
const migration = readFileSync(migrationPath, 'utf8');
const adminId = '00000000-0000-4000-8000-000000000001';
const learnerId = '00000000-0000-4000-8000-000000000002';
const anotherLearnerId = '00000000-0000-4000-8000-000000000003';

async function main() {
  const db = new PGlite();
  try {
    await db.exec([
      'create role anon;',
      'create role authenticated;',
      'create role service_role;',
      'create schema auth;',
      'create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting(\'request.jwt.claim.sub\', true), \'\')::uuid $$;',
      'create function auth.role() returns text language sql stable as $$ select nullif(current_setting(\'request.jwt.claim.role\', true), \'\') $$;',
      'create function public.is_growvelt_learning_admin() returns boolean language sql stable as $$ select auth.uid() = \'' + adminId + '\'::uuid $$;',
      'create function public.is_paystack_test_fixture_course(p_course_id bigint) returns boolean language sql stable as $$ select p_course_id = 99 $$;',
      'create table public.profiles(id uuid primary key);',
      'create table public.learning_courses(' +
        'id bigint generated by default as identity primary key, title text not null, status text not null, ' +
        'is_free boolean not null default false, is_limited_time_free boolean not null default false, ' +
        'company_test_mode_only boolean not null default false, organization_id bigint, ' +
        'price_currency text not null default \'NGN\', price_amount numeric(10,2), instructor_id uuid);',
      'create table public.learning_commercial_terms(' +
        'version text primary key, scope_type text not null, instructor_id uuid, course_id bigint, ' +
        'commission_basis_points integer not null, active boolean not null, effective_at timestamptz not null default now(), id bigint generated by default as identity);',
      'create function public.resolve_learning_commercial_terms_version(p_course_id bigint,p_instructor_id uuid) returns text language sql stable as $$ select version from public.learning_commercial_terms where active order by id desc limit 1 $$;',
      'create table public.learning_orders(id bigint generated by default as identity primary key);',
      'create table public.learning_audit_events(' +
        'id bigint generated by default as identity primary key, actor_user_id uuid, actor_role text, ' +
        'action text, entity_type text, entity_id text, metadata jsonb);',
      'insert into public.profiles values (\'' + adminId + '\'),(\'' + learnerId + '\'),(\'' + anotherLearnerId + '\');',
      'insert into public.learning_courses(id,title,status,price_amount,instructor_id,is_free,is_limited_time_free,company_test_mode_only,organization_id) values ' +
        '(1,\'Real published course\',\'published\',100,\'' + adminId + '\',false,false,false,null), ' +
        '(2,\'Private company test course\',\'published\',100,\'' + adminId + '\',false,false,true,null), ' +
        '(3,\'Organization course\',\'published\',100,\'' + adminId + '\',false,false,false,7), ' +
        '(99,\'Provider test fixture\',\'published\',100,\'' + adminId + '\',false,false,false,null);',
      'insert into public.learning_commercial_terms(version,scope_type,commission_basis_points,active) values (\'growvelt-v1\',\'platform\',2500,true);',
    ].join('\n'));

    await db.exec(migration);
    await db.exec('select set_config(\'request.jwt.claim.sub\',\'' + adminId + '\',false);');
    const created = await db.query(
      'select public.create_learning_promotion_coupon_for_admin(' +
      '\'OCT10\',\'fixed\',1000,1000,100,now()-interval \'1 hour\',now()+interval \'1 day\',1,array[1]::bigint[]) as id');
    const couponId = created.rows[0].id;
    const adminList = await db.query('select * from public.list_learning_promotion_coupons_for_admin()');
    assert.equal(adminList.rows.length, 1);
    assert.equal(adminList.rows[0].code, 'OCT10');
    assert.deepEqual(adminList.rows[0].course_ids, [1]);
    const options = await db.query('select course_id from public.list_learning_promotion_course_options_for_admin()');
    assert.deepEqual(options.rows.map((row) => row.course_id), [1]);

    await assert.rejects(
      db.query('select public.create_learning_promotion_coupon_for_admin(' +
        '\'PRIVATE\',\'fixed\',1000,1000,100,now()-interval \'1 hour\',now()+interval \'1 day\',1,array[2]::bigint[])'),
      /Choose only currently eligible public paid courses/,
    );
    await assert.rejects(
      db.query('select public.create_learning_promotion_coupon_for_admin(' +
        '\'FIXTURE\',\'fixed\',1000,1000,100,now()-interval \'1 hour\',now()+interval \'1 day\',1,array[99]::bigint[])'),
      /Choose only currently eligible public paid courses/,
    );
    await db.exec('select set_config(\'request.jwt.claim.sub\',\'' + learnerId + '\',false);');
    await assert.rejects(
      db.query('select public.create_learning_promotion_coupon_for_admin(' +
        '\'NOTADMIN\',\'fixed\',1000,1000,100,now()-interval \'1 hour\',now()+interval \'1 day\',1,array[1]::bigint[])'),
      /Learning Admin capability required/,
    );
    await db.exec('select set_config(\'request.jwt.claim.sub\',\'' + adminId + '\',false);');
    await assert.rejects(
      db.query('update public.learning_promotion_coupons set max_discount_minor=2000 where id=' + couponId),
      /Coupon terms are immutable/,
    );

    await db.exec('select set_config(\'request.jwt.claim.sub\',\'\',false); select set_config(\'request.jwt.claim.role\',\'service_role\',false);');
    const reservationKey = '10000000-0000-4000-8000-000000000001';
    const reserved = await db.query(
      'select * from public.reserve_learning_promotion_coupon_for_test(\'oct10\',\'' + learnerId + '\',1,\'' + reservationKey + '\')');
    assert.equal(reserved.rows[0].discount_minor, 1000);
    assert.equal(reserved.rows[0].customer_charge_minor, 9000);
    assert.equal(reserved.rows[0].seller_share_minor, 7500);
    assert.equal(reserved.rows[0].platform_share_minor, 1500);
    const retry = await db.query(
      'select * from public.reserve_learning_promotion_coupon_for_test(\'OCT10\',\'' + learnerId + '\',1,\'' + reservationKey + '\')');
    assert.equal(retry.rows[0].redemption_id, reserved.rows[0].redemption_id);
    await assert.rejects(
      db.query('select * from public.reserve_learning_promotion_coupon_for_test(\'OCT10\',\'' + learnerId + '\',1,\'10000000-0000-4000-8000-000000000002\')'),
      /Coupon is invalid or unavailable/,
    );
    await assert.rejects(
      db.query('select * from public.reserve_learning_promotion_coupon_for_test(\'OCT10\',\'' + anotherLearnerId + '\',1,\'10000000-0000-4000-8000-000000000003\')'),
      /Coupon is invalid or unavailable/,
    );

    await db.exec('reset role; select set_config(\'request.jwt.claim.sub\',\'' + adminId + '\',false); select public.disable_learning_promotion_coupon_for_admin(' + couponId + ');');
    const disabledList = await db.query('select active from public.list_learning_promotion_coupons_for_admin()');
    assert.equal(disabledList.rows[0].active, false);
    assert.equal((await db.query('select count(*)::integer as events from public.learning_audit_events')).rows[0].events, 2);
    await db.exec('set role authenticated');
    await assert.rejects(db.query('select * from public.learning_promotion_coupons'), /permission denied/);
    await db.exec('reset role');
    await db.exec('set role service_role');
    await assert.rejects(db.query('select * from public.learning_promotion_redemptions'), /permission denied/);
    await db.exec('reset role');
    assert.match(migration, /payment_mode text not null default 'test' check \(payment_mode = 'test'\)/);
    assert.doesNotMatch(migration, /alter table public\.learning_orders/i);
    console.log('PASS private coupon access, admin create/disable audit, eligible-course rules, atomic capacity and seller-share-preserving Test Mode reservation');
  } finally {
    await db.close();
  }
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
