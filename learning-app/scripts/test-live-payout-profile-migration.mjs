import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";

const db = new PGlite();
const owner = "11111111-1111-4111-8111-111111111111";
const other = "22222222-2222-4222-8222-222222222222";
try {
  await db.exec(`
    create role anon; create role authenticated; create role service_role;
    create table public.profiles(id uuid primary key);
    create table public.account_capabilities(user_id uuid,capability text,status text);
    create table public.instructor_profiles(user_id uuid,approval_status text);
    create table public.learning_audit_events(actor_user_id uuid,actor_role text,action text,entity_type text,entity_id text,metadata jsonb);
    create table public.learning_instructor_payout_profiles(
      id bigint generated by default as identity primary key,instructor_id uuid references public.profiles(id),
      provider text,provider_domain text,status text,recipient_code text,provider_recipient_id text,
      currency text,bank_code text,bank_name text,account_name text,account_last4 text,
      created_by uuid references public.profiles(id),created_at timestamptz default now(),disabled_at timestamptz);
    create unique index one_active on public.learning_instructor_payout_profiles(instructor_id,provider,provider_domain) where status='active';
    create unique index one_recipient on public.learning_instructor_payout_profiles(provider_domain,recipient_code);
    create table public.learning_instructor_payout_profile_events(
      payout_profile_id bigint,instructor_id uuid,event_type text,actor_user_id uuid,metadata jsonb);
    create function public.assert_learning_approved_instructor(p_instructor_id uuid)
      returns void language plpgsql as $f$ begin
        if not exists(select 1 from public.account_capabilities c join public.instructor_profiles i on i.user_id=c.user_id
          where c.user_id=p_instructor_id and c.capability='instructor' and c.status='active' and i.approval_status='approved')
        then raise exception 'Not approved' using errcode='42501'; end if;
      end;$f$;
    insert into public.profiles(id) values ('${owner}'),('${other}');
    insert into public.account_capabilities values ('${owner}','instructor','active');
    insert into public.instructor_profiles values ('${owner}','approved');
  `);
  const migration = await readFile(new URL("../supabase/migrations/20261114000000_add_instructor_live_payout_profile_setup.sql", import.meta.url), "utf8");
  await db.exec(migration);
  const args = [owner,"RCP_liveone1","100001","058","Example Bank","Instructor Name","1234",owner];
  const create = "select * from public.create_learning_instructor_paystack_live_payout_profile($1,$2,$3,$4,$5,$6,$7,$8)";
  const first = await db.query(create, args);
  assert.equal(first.rows[0].provider_domain,"live");
  assert.equal(first.rows[0].status,"active");
  const repeat = await db.query(create,args);
  assert.equal(repeat.rows[0].payout_profile_id,first.rows[0].payout_profile_id);
  const eventCount = await db.query("select count(*)::int as n from public.learning_instructor_payout_profile_events");
  assert.equal(eventCount.rows[0].n,1);
  await assert.rejects(() => db.query(create,[other,"RCP_wrongone","100002","058","Example Bank","Other","5678",owner]));
  const second = await db.query(create,[owner,"RCP_livetwo2","100003","058","Example Bank","Instructor Name","5678",owner]);
  assert.notEqual(second.rows[0].payout_profile_id,first.rows[0].payout_profile_id);
  const rows = await db.query("select status,provider_domain,account_last4 from public.learning_instructor_payout_profiles order by id");
  assert.deepEqual(rows.rows.map(({status}) => status),["disabled","active"]);
  assert(rows.rows.every(({provider_domain}) => provider_domain === "live"));
  assert.equal(await db.query("select public.disable_own_learning_instructor_paystack_live_payout_profile($1,$2) as disabled",[owner,owner]).then(r => r.rows[0].disabled),true);
  assert.equal(await db.query("select public.disable_own_learning_instructor_paystack_live_payout_profile($1,$2) as disabled",[owner,owner]).then(r => r.rows[0].disabled),false);
  const privileges = await db.query("select has_function_privilege('authenticated','public.create_learning_instructor_paystack_live_payout_profile(uuid,text,text,text,text,text,text,uuid)','execute') as allowed");
  assert.equal(privileges.rows[0].allowed,false);
  console.log("PASS Live payout profile migration in isolated PGlite database");
} finally {
  await db.close();
}
