const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const path = require('node:path');
const { PGlite } = require(process.env.PGLITE_PACKAGE_PATH || '@electric-sql/pglite');

const migrations = [
  '20261016000000_add_private_learning_coupon_foundation.sql',
  '20261017000000_integrate_test_coupon_checkout.sql',
].map((name) => readFileSync(path.resolve(__dirname, '../supabase/migrations', name), 'utf8'));
const commercialMigration = readFileSync(path.resolve(__dirname, '../supabase/migrations/20260903000000_add_commercial_allocation_instructor_earnings_foundation.sql'), 'utf8');
const finalizeStart = commercialMigration.indexOf('create or replace function public.finalize_paystack_test_charge(');
const finalizeEnd = commercialMigration.indexOf('$function$;', finalizeStart);
if (finalizeStart < 0 || finalizeEnd < 0) throw new Error('Could not load the established Paystack Test Mode callback finalizer');
const finalizeTestCharge = commercialMigration.slice(finalizeStart, finalizeEnd + '$function$;'.length);
const reverseStart = commercialMigration.indexOf('create or replace function public.reverse_learning_order_commercial_allocation(');
const reverseEnd = commercialMigration.indexOf('$function$;', reverseStart);
if (reverseStart < 0 || reverseEnd < 0) throw new Error('Could not load the established commercial-allocation reversal function');
const reverseCommercialAllocation = commercialMigration.slice(reverseStart, reverseEnd + '$function$;'.length);
const adminId = '00000000-0000-4000-8000-000000000001';
const instructorId = '00000000-0000-4000-8000-000000000002';
const learnerId = '00000000-0000-4000-8000-000000000003';
const otherId = '00000000-0000-4000-8000-000000000004';
const firstKey = '10000000-0000-4000-8000-000000000001';
const secondKey = '10000000-0000-4000-8000-000000000002';

async function main() {
  const db = new PGlite();
  try {
    await db.exec(`
      create role anon;
      create role authenticated;
      create role service_role;
      create schema auth;
      create function auth.uid() returns uuid language sql stable as $$
        select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
      $$;
      create function auth.role() returns text language sql stable as $$
        select nullif(current_setting('request.jwt.claim.role', true), '')
      $$;
      create table public.profiles(id uuid primary key, full_name text, email text);
      create table public.learning_courses(
        id bigint primary key, title text not null, summary text, description text, category text, level text,
        status text not null, is_free boolean not null default false, is_limited_time_free boolean not null default false,
        company_test_mode_only boolean not null default false, organization_id bigint,
        price_currency text not null default 'NGN', price_amount numeric(10,2), instructor_id uuid
      );
      create table public.learning_paystack_test_fixtures(
        id bigint generated by default as identity primary key, course_id bigint, tester_id uuid,
        status text not null, expires_at timestamptz not null
      );
      create function public.is_paystack_test_fixture_course(p_course_id bigint) returns boolean
        language sql stable as $$ select exists(select 1 from public.learning_paystack_test_fixtures where course_id=p_course_id) $$;
      create table public.learning_commercial_terms(
        version text primary key, commission_basis_points integer not null, earnings_hold_days integer not null
      );
      create function public.resolve_learning_commercial_terms_version(p_course_id bigint,p_instructor_id uuid)
        returns text language sql stable as $$ select 'terms-v1'::text $$;
      create sequence public.learning_orders_order_reference_seq;
      create table public.learning_orders(
        id bigint generated by default as identity primary key,
        learner_id uuid, course_id bigint, instructor_id uuid, course_title_snapshot text,
        instructor_name_snapshot text, gross_amount_minor bigint, currency text, status text,
        commercial_terms_version text, order_reference text not null unique default ('TEST-' || nextval('public.learning_orders_order_reference_seq')),
        created_at timestamptz not null default now(), paid_at timestamptz, cancelled_at timestamptz
      );
      create table public.learning_payment_attempts(
        id bigint generated by default as identity primary key, order_id bigint, provider text,
        provider_reference text, amount_minor bigint, currency text, status text, paystack_domain text,
        initialized_at timestamptz not null default now(), verified_at timestamptz, failed_at timestamptz,
        failure_code text, failure_message text, provider_transaction_id text
      );
      create table public.learning_payment_provider_events(
        id bigint generated by default as identity primary key, provider text, provider_event_id text,
        event_type text, payload_digest text, payload jsonb, signature_valid boolean,
        processing_status text not null default 'received', processed_at timestamptz, processing_error text,
        order_id bigint, payment_attempt_id bigint, unique(provider,provider_event_id)
      );
      create table public.learning_payment_cases(
        id bigint generated by default as identity primary key, order_id bigint,
        case_type text, status text, provider_status text, provider_resolution text,
        amount_minor bigint, processed_amount_minor bigint
      );
      create table public.enrollments(
        id bigint generated by default as identity primary key, learner_id uuid, course_id bigint,
        status text, completed_at timestamptz, unique(learner_id,course_id)
      );
      create table public.learning_course_entitlements(
        id bigint generated by default as identity primary key, learner_id uuid, course_id bigint,
        order_id bigint, enrollment_id bigint, status text
      );
      create table public.learning_audit_events(
        id bigint generated by default as identity primary key, actor_user_id uuid, actor_role text,
        action text, entity_type text, entity_id text, metadata jsonb
      );
      create table public.learning_ledger_transactions(
        id bigint generated by default as identity primary key, order_id bigint, transaction_type text,
        currency text, description text, created_by uuid, payment_case_id bigint
      );
      create table public.learning_ledger_entries(
        transaction_id bigint, line_number integer, account_code text, amount_minor bigint,
        currency text, counterparty_type text, counterparty_reference text
      );
      create table public.learning_commercial_allocations(
        id bigint generated by default as identity primary key, order_id bigint unique,
        commercial_terms_version text, instructor_id uuid, course_id bigint, gross_amount_minor bigint,
        platform_commission_minor bigint, instructor_gross_minor bigint, currency text,
        allocation_ledger_transaction_id bigint, status text not null default 'allocated',
        reversal_ledger_transaction_id bigint, reversed_at timestamptz, reversed_by_case_id bigint
      );
      create table public.learning_instructor_earnings(
        id bigint generated by default as identity primary key, allocation_id bigint, instructor_id uuid,
        gross_amount_minor bigint, currency text, status text, available_at timestamptz,
        hold_reason text, reversed_at timestamptz
      );
      create table public.learning_instructor_earning_events(
        id bigint generated by default as identity primary key, earning_id bigint, event_type text,
        from_status text, to_status text, ledger_transaction_id bigint,
        payment_case_id bigint, actor_user_id uuid, metadata jsonb
      );
      create function public.is_growvelt_learning_admin() returns boolean language sql stable as $$
        select auth.uid() = '${adminId}'::uuid
      $$;
      insert into public.profiles(id,full_name,email) values
        ('${adminId}','Admin','admin@example.test'),
        ('${instructorId}','Instructor','instructor@example.test'),
        ('${learnerId}','Tester','tester@example.test'),
        ('${otherId}','Other','other@example.test');
      insert into public.learning_courses(id,title,status,price_amount,instructor_id,company_test_mode_only,organization_id) values
        (99,'Active fixture course','published',100,'${instructorId}',false,null),
        (100,'Second active fixture','published',100,'${instructorId}',false,null),
        (101,'Company-only course','published',100,'${instructorId}',true,null),
        (102,'Organization course','published',100,'${instructorId}',false,7);
      insert into public.learning_paystack_test_fixtures(course_id,tester_id,status,expires_at) values
        (99,'${learnerId}','active',now()+interval '1 day'),
        (100,'${learnerId}','active',now()+interval '1 day');
      insert into public.learning_commercial_terms values ('terms-v1',2500,14);
    `);

    await db.exec(migrations[0]);
    await db.exec(migrations[1]);
    await db.exec(finalizeTestCharge);
    await db.exec(reverseCommercialAllocation);
    await db.exec(`select set_config('request.jwt.claim.sub','${adminId}',false);`);
    const fixtureOptions = await db.query('select course_id from public.list_learning_promotion_course_options_for_admin() order by course_id');
    assert.deepEqual(fixtureOptions.rows.map((row) => row.course_id), [99, 100]);
    const created = await db.query(`select public.create_learning_promotion_coupon_for_admin(
      'TEST10','fixed',1000,1000,100,now()-interval '1 hour',now()+interval '1 day',5,array[99]::bigint[]) as id`);
    const couponId = created.rows[0].id;
    await assert.rejects(
      db.query(`select public.create_learning_promotion_coupon_for_admin(
        'PRIVATE','fixed',1000,1000,100,now()-interval '1 hour',now()+interval '1 day',5,array[101]::bigint[])`),
      /Choose only currently eligible published paid courses/,
    );

    await db.exec(`select set_config('request.jwt.claim.sub','',false); select set_config('request.jwt.claim.role','service_role',false);`);
    const order = (await db.query(`select * from public.initialize_paystack_test_learning_order_with_coupon(
      '${learnerId}','99','test10','${firstKey}')`)).rows[0];
    assert.equal(order.amount_minor, 9000);
    assert.equal(order.list_price_minor, 10000);
    assert.equal(order.discount_minor, 1000);
    const retry = (await db.query(`select * from public.initialize_paystack_test_learning_order_with_coupon(
      '${learnerId}','99','TEST10','${firstKey}')`)).rows[0];
    assert.equal(retry.order_id, order.order_id);
    await db.exec(`update public.learning_promotion_redemptions set expires_at=now()-interval '1 minute' where reservation_key='${firstKey}';`);
    await db.exec(`select set_config('request.jwt.claim.sub','${adminId}',false); select set_config('request.jwt.claim.role','',false);`);
    const reservedCount = await db.query(`select redeemed_count from public.list_learning_promotion_coupons_for_admin() where code='TEST10'`);
    assert.equal(reservedCount.rows[0].redeemed_count, 1);
    await db.exec(`select set_config('request.jwt.claim.sub','',false); select set_config('request.jwt.claim.role','service_role',false);`);
    const attached = await db.query(`select status,order_id,customer_charge_minor,seller_share_minor,platform_share_minor
      from public.learning_promotion_redemptions where reservation_key='${firstKey}'`);
    assert.equal(attached.rows[0].status, 'reserved');
    assert.equal(attached.rows[0].order_id, order.order_id);
    assert.equal(attached.rows[0].customer_charge_minor, 9000);

    await assert.rejects(
      db.query(`select * from public.initialize_paystack_test_learning_order_with_coupon(
        '${otherId}','99','TEST10','10000000-0000-4000-8000-000000000003')`),
      /Learner is not eligible for this controlled test checkout/,
    );

    const payload = { domain: 'test', amount: 9000 };
    const callbackArgs = `'evt-coupon-success-1','${'a'.repeat(64)}','${order.order_reference}','txn-coupon-success-1',9000,'NGN','test','${JSON.stringify(payload)}'::jsonb`;
    const callback = await db.query(`select * from public.finalize_paystack_test_charge(${callbackArgs})`);
    assert.equal(callback.rows[0].outcome, 'paid_and_enrolled');
    const duplicateCallback = await db.query(`select * from public.finalize_paystack_test_charge(${callbackArgs})`);
    assert.equal(duplicateCallback.rows[0].outcome, 'already_processed');
    const firstAllocation = await db.query(`select id from public.learning_commercial_allocations where order_id=${order.order_id}`);
    assert.equal(firstAllocation.rows.length, 1);
    const allocationSideEffects = await db.query(`select
      (select count(*) from public.learning_commercial_allocations where order_id=${order.order_id}) as allocations,
      (select count(*) from public.learning_instructor_earnings where allocation_id=${firstAllocation.rows[0].id}) as earnings,
      (select count(*) from public.learning_ledger_transactions where order_id=${order.order_id} and transaction_type='commercial_allocation') as allocation_ledgers,
      (select count(*) from public.learning_ledger_transactions where order_id=${order.order_id} and transaction_type='payment_capture') as captures,
      (select count(*) from public.learning_payment_provider_events where provider_event_id='evt-coupon-success-1') as callback_events`);
    assert.deepEqual(allocationSideEffects.rows[0], { allocations: 1, earnings: 1, allocation_ledgers: 1, captures: 1, callback_events: 1 });
    const allocation = await db.query(`select gross_amount_minor,platform_commission_minor,instructor_gross_minor
      from public.learning_commercial_allocations where order_id=${order.order_id}`);
    assert.deepEqual(allocation.rows[0], { gross_amount_minor: 9000, platform_commission_minor: 1500, instructor_gross_minor: 7500 });
    const consumed = await db.query(`select status,consumed_at from public.learning_promotion_redemptions where reservation_key='${firstKey}'`);
    assert.equal(consumed.rows[0].status, 'consumed');
    assert.ok(consumed.rows[0].consumed_at);

    const refundCase = await db.query(`insert into public.learning_payment_cases(
      order_id,case_type,status,provider_status,amount_minor,processed_amount_minor
    ) values(${order.order_id},'refund','processed','processed',9000,9000) returning id`);
    const reverse = await db.query(`select public.reverse_learning_order_commercial_allocation(
      ${order.order_id},${refundCase.rows[0].id},'processed Test Mode refund',null) as id`);
    const duplicateReverse = await db.query(`select public.reverse_learning_order_commercial_allocation(
      ${order.order_id},${refundCase.rows[0].id},'duplicate processed Test Mode refund',null) as id`);
    assert.equal(duplicateReverse.rows[0].id, reverse.rows[0].id);
    const reversal = await db.query(`select
      allocation.status as allocation_status, allocation.platform_commission_minor,
      allocation.instructor_gross_minor, earning.status as earning_status, earning.gross_amount_minor,
      (select count(*) from public.learning_ledger_transactions where payment_case_id=${refundCase.rows[0].id} and transaction_type='instructor_earnings_reversal') as reversal_ledgers,
      (select coalesce(sum(entry.amount_minor),0)::integer from public.learning_ledger_entries entry where entry.transaction_id=${reverse.rows[0].id}) as reversal_balance
      from public.learning_commercial_allocations allocation
      join public.learning_instructor_earnings earning on earning.allocation_id=allocation.id
      where allocation.order_id=${order.order_id}`);
    assert.deepEqual(reversal.rows[0], {
      allocation_status: 'reversed', platform_commission_minor: 1500, instructor_gross_minor: 7500,
      earning_status: 'reversed', gross_amount_minor: 7500, reversal_ledgers: 1, reversal_balance: 0,
    });

    await db.exec(`select set_config('request.jwt.claim.sub','${adminId}',false);`);
    await db.query(`select public.create_learning_promotion_coupon_for_admin(
      'CANCEL10','fixed',1000,1000,100,now()-interval '1 hour',now()+interval '1 day',5,array[100]::bigint[])`);
    await db.exec(`select set_config('request.jwt.claim.sub','',false); select set_config('request.jwt.claim.role','service_role',false);`);
    const cancelledOrder = (await db.query(`select * from public.initialize_paystack_test_learning_order_with_coupon(
      '${learnerId}','100','CANCEL10','${secondKey}')`)).rows[0];
    await db.exec(`update public.learning_orders set status='cancelled',cancelled_at=now() where id=${cancelledOrder.order_id};`);
    const released = await db.query(`select status,order_id,released_at from public.learning_promotion_redemptions where reservation_key='${secondKey}'`);
    assert.equal(released.rows[0].status, 'released');
    assert.equal(released.rows[0].order_id, null);
    assert.ok(released.rows[0].released_at);

    await db.exec('reset role;');
    assert.ok(Number(couponId) > 0);
    console.log('PASS Test Mode coupon checkout callback/idempotency, seller allocation/reversal, redemption lifecycle, and terminal release');
  } finally {
    await db.close();
  }
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
