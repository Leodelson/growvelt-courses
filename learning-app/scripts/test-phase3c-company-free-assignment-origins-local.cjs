const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const path = require('node:path');
const { PGlite } = require(process.env.PGLITE_PACKAGE_PATH || '@electric-sql/pglite');

const migration = readFileSync(path.resolve(__dirname,
  '../supabase/migrations/20260950000000_record_company_free_assignment_origins.sql'), 'utf8');
const manager = '00000000-0000-4000-8000-000000000001';
const employee1 = '00000000-0000-4000-8000-000000000002';
const employee2 = '00000000-0000-4000-8000-000000000003';
const employee3 = '00000000-0000-4000-8000-000000000004';

async function main() {
  const db = new PGlite();
  try {
    await db.exec(`
      create role anon;
      create role authenticated;
      create role service_role;
      create schema auth;
      create function auth.uid() returns uuid language sql stable as $$
        select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid
      $$;
      create table public.profiles(id uuid primary key);
      create table public.learning_company_workspaces(id bigint primary key,status text);
      create table public.learning_company_memberships(
        workspace_id bigint,user_id uuid,status text,role text);
      create table public.learning_courses(
        id bigint primary key,status text,is_free boolean,price_amount bigint,
        is_limited_time_free boolean);
      create table public.enrollments(
        id bigint generated by default as identity primary key,
        learner_id uuid not null,course_id bigint not null,status text not null,
        completed_at timestamptz,unique(learner_id,course_id));
      create table public.learning_company_course_assignments(
        id bigint generated by default as identity primary key,
        workspace_id bigint,course_id bigint,assigned_user_id uuid,
        assigned_by uuid,status text not null default 'active');
      create unique index one_active_assignment on public.learning_company_course_assignments(
        workspace_id,course_id,assigned_user_id) where status='active';
      create table public.learning_audit_events(
        actor_user_id uuid,actor_role text,action text,entity_type text,
        entity_id text,metadata jsonb);
      create function public.prevent_learning_company_sale_mutation()
      returns trigger language plpgsql as $$ begin raise exception 'Immutable origin'; end $$;
      insert into public.profiles values ('${manager}'),('${employee1}'),('${employee2}'),('${employee3}');
      insert into public.learning_company_workspaces values (1,'active');
      insert into public.learning_company_memberships values
        (1,'${manager}','active','owner'),
        (1,'${employee1}','active','member'),
        (1,'${employee2}','active','member'),
        (1,'${employee3}','active','member');
      insert into public.learning_courses values
        (10,'published',true,0,false),(11,'published',false,101,false);
      insert into public.learning_company_course_assignments(
        workspace_id,course_id,assigned_user_id,assigned_by)
      values(1,10,'${employee1}','${manager}'),(1,10,'${employee3}','${manager}');
      insert into public.enrollments(learner_id,course_id,status)
      values('${employee1}',10,'completed');
      select set_config('request.jwt.claim.sub','${manager}',false);
    `);
    await db.exec(migration);
    const existing = (await db.query(`select * from public.assign_learning_company_course(1,10,'${employee1}')`)).rows[0];
    assert.equal(existing.access_state,'already_assigned');
    const origin = (await db.query('select * from public.learning_company_free_assignment_origins where assignment_id=1')).rows[0];
    assert.equal(origin.enrollment_id,existing.enrollment_id);
    assert.equal((await db.query(`select status from public.enrollments where learner_id='${employee1}'`)).rows[0].status,'completed');
    await db.exec(`select * from public.assign_learning_company_course(1,10,'${employee1}')`);
    assert.equal((await db.query('select count(*) as n from public.learning_company_free_assignment_origins where assignment_id=1')).rows[0].n,1);
    assert.equal((await db.query('select recorded_at from public.learning_company_free_assignment_origins where assignment_id=1')).rows[0].recorded_at.getTime(),origin.recorded_at.getTime());
    const fresh = (await db.query(`select * from public.assign_learning_company_course(1,10,'${employee2}')`)).rows[0];
    assert.equal(fresh.access_state,'assigned');
    assert.equal((await db.query('select enrollment_id from public.learning_company_free_assignment_origins where assignment_id=$1',[fresh.assignment_id])).rows[0].enrollment_id,fresh.enrollment_id);
    const missingEnrollment = (await db.query(`select * from public.assign_learning_company_course(1,10,'${employee3}')`)).rows[0];
    assert.equal(missingEnrollment.enrollment_id,null);
    assert.equal((await db.query('select count(*) as n from public.learning_company_free_assignment_origins where assignment_id=$1',[missingEnrollment.assignment_id])).rows[0].n,0);
    let paidRejected = false;
    try { await db.exec(`select * from public.assign_learning_company_course(1,11,'${employee2}')`); }
    catch { paidRejected = true; }
    assert.equal(paidRejected,true);
    let mutationRejected = false;
    try { await db.exec('delete from public.learning_company_free_assignment_origins where assignment_id=1'); }
    catch { mutationRejected = true; }
    assert.equal(mutationRejected,true);
    const privileges = (await db.query(`select
      has_table_privilege('authenticated','public.learning_company_free_assignment_origins','SELECT') as member_read,
      has_table_privilege('authenticated','public.learning_company_free_assignment_origins','INSERT') as member_insert,
      has_function_privilege('authenticated','public.assign_learning_company_course(bigint,bigint,uuid)','EXECUTE') as member_assign`)).rows[0];
    assert.deepEqual(privileges,{member_read:false,member_insert:false,member_assign:true});
    await db.exec(`select set_config('request.jwt.claim.sub','${employee1}',false)`);
    let unauthorizedRejected = false;
    try { await db.exec(`select * from public.assign_learning_company_course(1,10,'${employee2}')`); }
    catch { unauthorizedRejected = true; }
    assert.equal(unauthorizedRejected,true);
    console.log('PASS free company assignment origin capture, replay, privacy, authorization, and paid-course rejection');
  } finally {
    await db.close();
  }
}

main().catch(error => { console.error(error); process.exitCode = 1; });
