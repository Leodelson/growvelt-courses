/* eslint-disable @typescript-eslint/no-require-imports */
const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const path = require('node:path');
const { PGlite } = require(process.env.PGLITE_PACKAGE_PATH || '@electric-sql/pglite');

const migration = readFileSync(path.resolve(__dirname,
  '../supabase/migrations/20261101000000_add_learning_enterprise_contract_register.sql'), 'utf8');
const adminId = '00000000-0000-4000-8000-000000000001';
const learnerId = '00000000-0000-4000-8000-000000000002';

async function main() {
  const db = new PGlite();
  try {
    await db.exec(`
      create role anon;
      create role authenticated;
      create role service_role;
      create schema auth;
      create function auth.uid() returns uuid language sql stable as
        $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
      create function public.is_growvelt_learning_admin() returns boolean language sql stable as
        $$ select auth.uid() = '${adminId}'::uuid $$;
      create table public.profiles(id uuid primary key, full_name text);
      create table public.learning_company_workspaces(
        id bigint generated by default as identity primary key,
        name text not null, slug text not null unique, status text not null,
        seat_limit integer not null
      );
      create table public.learning_audit_events(
        id bigint generated by default as identity primary key,
        actor_user_id uuid, actor_role text, action text, entity_type text,
        entity_id text, metadata jsonb
      );
      insert into public.profiles values ('${adminId}', 'Learning Admin');
      insert into public.learning_company_workspaces(name, slug, status, seat_limit)
        values ('Example Company', 'example-company', 'active', 25);
    `);

    await db.exec(migration);
    await db.exec(`select set_config('request.jwt.claim.sub','${adminId}',false); set role authenticated;`);

    const workspaces = await db.query('select * from public.list_learning_enterprise_contract_workspaces_for_admin()');
    assert.equal(workspaces.rows.length, 1);
    assert.equal(workspaces.rows[0].workspace_slug, 'example-company');

    const term = await db.query('select current_date::text as starts, (current_date + 30)::text as ends');
    const created = await db.query(
      'select * from public.record_learning_enterprise_contract_for_admin($1,$2,$3,$4,$5,$6,$7)',
      [workspaces.rows[0].workspace_id, 'GV-ENT-2026-001', term.rows[0].starts, term.rows[0].ends, 120,
        'Annual learning access for support staff.', true],
    );
    assert.equal(created.rows.length, 1);
    assert.equal(created.rows[0].contract_reference, 'GV-ENT-2026-001');

    const listed = await db.query('select * from public.list_learning_enterprise_contract_records_for_admin()');
    assert.equal(listed.rows.length, 1);
    assert.equal(listed.rows[0].contract_state, 'in_term');
    assert.equal(listed.rows[0].seat_cap, 120);
    await db.exec('reset role;');
    assert.equal((await db.query('select count(*)::integer as count from public.learning_audit_events')).rows[0].count, 1);
    await db.exec('set role authenticated;');

    await assert.rejects(
      db.query('select * from public.record_learning_enterprise_contract_for_admin($1,$2,$3,$4,$5,$6,$7)',
        [workspaces.rows[0].workspace_id, 'gv-ent-2026-001', term.rows[0].starts, term.rows[0].ends, 120,
          'Duplicate contract reference test.', true]),
      /duplicate key value violates unique constraint/,
      'references are unique case-insensitively within a workspace',
    );
    await assert.rejects(
      db.query('select * from public.record_learning_enterprise_contract_for_admin($1,$2,$3,$4,$5,$6,$7)',
        [workspaces.rows[0].workspace_id, 'GV-ENT-2026-002', term.rows[0].starts, term.rows[0].ends, 120,
          'Must be externally executed first.', false]),
      /already executed outside Growvelt/,
    );
    await assert.rejects(db.query('select * from public.learning_company_enterprise_contract_records'),
      /permission denied/, 'authenticated users cannot read records directly, including admins');

    await db.exec('reset role;');
    await assert.rejects(db.query('update public.learning_company_enterprise_contract_records set seat_cap=121'),
      /append-only/, 'the record-level guard prevents owner-side edits too');

    await db.exec(`select set_config('request.jwt.claim.sub','${learnerId}',false); set role authenticated;`);
    await assert.rejects(db.query('select * from public.list_learning_enterprise_contract_records_for_admin()'),
      /Learning Admin access required/);
    await db.exec('reset role; set role anon;');
    await assert.rejects(db.query('select * from public.list_learning_enterprise_contract_workspaces_for_admin()'),
      /permission denied/, 'anonymous users cannot invoke admin workspace RPCs');
    await db.exec('reset role; set role service_role;');
    await assert.rejects(db.query('select * from public.learning_company_enterprise_contract_records'),
      /permission denied/, 'service role does not receive a direct-table bypass');

    console.log('PASS Phase 4 enterprise contract register: SQL execution, admin-only RPCs, append-only behavior, duplicate rejection, and no direct access');
  } finally {
    await db.close();
  }
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
