const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const path = require('node:path');
const { PGlite } = require(process.env.PGLITE_PACKAGE_PATH || '@electric-sql/pglite');

const migration = readFileSync(path.resolve(__dirname,
  '../supabase/migrations/20260949000000_record_free_learning_enrollment_claims.sql'), 'utf8');
const learner = '00000000-0000-4000-8000-000000000003';

async function main() {
  const db = new PGlite();
  try {
    await db.exec(`
      create role anon;
      create role authenticated;
      create role service_role;
      create schema auth;
      create function auth.uid() returns uuid language sql stable as $$
        select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid
      $$;
      create table public.profiles(id uuid primary key);
      create table public.learning_courses(
        id bigint primary key,status text,is_free boolean,price_amount bigint,
        price_currency text,is_limited_time_free boolean);
      create table public.enrollments(
        id bigint generated by default as identity primary key,
        learner_id uuid not null references public.profiles(id),
        course_id bigint not null references public.learning_courses(id),
        status text not null,completed_at timestamptz,
        unique(learner_id,course_id));
      create function public.prevent_learning_company_sale_mutation()
      returns trigger language plpgsql as $$ begin
        raise exception 'Immutable claim';
      end $$;
      insert into public.profiles values ('${learner}');
      insert into public.learning_courses values
        (10,'published',true,0,'NGN',false),
        (11,'published',false,101,'NGN',false),
        (12,'published',true,0,'NGN',false),
        (13,'published',true,0,'NGN',false);
      insert into public.enrollments(learner_id,course_id,status)
        values('${learner}',10,'completed'),('${learner}',13,'cancelled');
      select set_config('request.jwt.claim.sub','${learner}',false);
    `);
    await db.exec(migration);
    const preexisting = (await db.query('select * from public.enroll_in_free_learning_course(10)')).rows[0];
    assert.equal(preexisting.enrollment_status,'completed');
    const originalClaim = (await db.query('select * from public.learning_free_enrollment_claims where course_id=10')).rows[0];
    assert.equal(originalClaim.enrollment_id,preexisting.enrollment_id);
    await db.exec('select * from public.enroll_in_free_learning_course(10)');
    assert.equal((await db.query('select count(*) as n from public.learning_free_enrollment_claims where course_id=10')).rows[0].n,1);
    assert.equal((await db.query('select claimed_at from public.learning_free_enrollment_claims where course_id=10')).rows[0].claimed_at.getTime(),originalClaim.claimed_at.getTime());
    assert.equal((await db.query('select * from public.enroll_in_free_learning_course(12)')).rows[0].enrollment_status,'active');
    assert.equal((await db.query('select * from public.enroll_in_free_learning_course(13)')).rows[0].enrollment_status,'active');
    assert.equal((await db.query('select count(*) as n from public.learning_free_enrollment_claims')).rows[0].n,3);
    let paidRejected = false;
    try { await db.exec('select * from public.enroll_in_free_learning_course(11)'); }
    catch { paidRejected = true; }
    assert.equal(paidRejected,true);
    assert.equal((await db.query('select count(*) as n from public.learning_free_enrollment_claims where course_id=11')).rows[0].n,0);
    let mutationRejected = false;
    try { await db.exec('update public.learning_free_enrollment_claims set claimed_at=now() where course_id=10'); }
    catch { mutationRejected = true; }
    assert.equal(mutationRejected,true);
    const privileges = (await db.query(`select
      has_table_privilege('authenticated','public.learning_free_enrollment_claims','SELECT') as member_read,
      has_table_privilege('authenticated','public.learning_free_enrollment_claims','INSERT') as member_insert,
      has_function_privilege('authenticated','public.enroll_in_free_learning_course(bigint)','EXECUTE') as member_enroll`)).rows[0];
    assert.deepEqual(privileges,{member_read:false,member_insert:false,member_enroll:true});
    console.log('PASS free enrollment claim capture, replay, preservation, paid-course rejection, and privacy');
  } finally {
    await db.close();
  }
}

main().catch(error => { console.error(error); process.exitCode = 1; });
