/* eslint-disable @typescript-eslint/no-require-imports */
const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const path = require('node:path');
const { PGlite } = require(process.env.PGLITE_PACKAGE_PATH || '@electric-sql/pglite');

const migration = readFileSync(path.resolve(__dirname,
  '../supabase/migrations/20261021000000_add_editorial_learning_campaigns.sql'), 'utf8');
const adminId = '00000000-0000-4000-8000-000000000001';
const instructorId = '00000000-0000-4000-8000-000000000002';
const otherId = '00000000-0000-4000-8000-000000000003';

async function main() {
  const db = new PGlite();
  try {
    await db.exec(`
      create role anon;
      create role authenticated;
      create role service_role;
      create schema auth;
      create function auth.uid() returns uuid language sql stable as
        $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
      create function public.is_growvelt_learning_admin() returns boolean language sql stable as
        $$ select auth.uid() = '${adminId}'::uuid $$;
      create table public.profiles(id uuid primary key, full_name text);
      create table public.learning_courses(
        id bigint primary key, instructor_id uuid, title text not null, slug text not null,
        summary text, description text, category text, level text, is_free boolean not null,
        price_amount numeric(10,2), price_currency text, status text not null,
        published_at timestamptz, company_test_mode_only boolean not null default false,
        organization_id bigint
      );
      create table public.learning_paystack_test_fixtures(course_id bigint, status text);
      create function public.is_paystack_test_fixture_course(p_course_id bigint)
        returns boolean language sql stable security definer set search_path to '' as
        $$ select exists(select 1 from public.learning_paystack_test_fixtures fixture where fixture.course_id = p_course_id) $$;
      alter function public.is_paystack_test_fixture_course(bigint) owner to postgres;
      grant execute on function public.is_paystack_test_fixture_course(bigint) to anon, authenticated;
      create table public.course_modules(id bigint primary key, course_id bigint, title text, position integer);
      create table public.lessons(id bigint primary key, course_id bigint, module_id bigint, title text,
        lesson_type text, is_preview boolean, content text, video_provider text, video_reference text,
        video_visibility text, duration_seconds integer, position integer);
      create table public.learning_provider_organizations(id bigint primary key, name text, slug text, status text);
      create table public.learning_provider_organization_verifications(organization_id bigint, status text);
      alter table public.learning_courses enable row level security;
      alter table public.course_modules enable row level security;
      alter table public.lessons enable row level security;
      grant select on public.learning_courses, public.course_modules, public.lessons to anon, authenticated;
      create table public.learning_audit_events(
        id bigint generated by default as identity primary key, actor_user_id uuid,
        actor_role text, action text, entity_type text, entity_id text, metadata jsonb
      );
      insert into public.profiles values
        ('${adminId}', 'Campaign Admin'), ('${instructorId}', 'Course Instructor'), ('${otherId}', 'Other User');
      insert into public.learning_courses(id,instructor_id,title,slug,summary,description,category,level,is_free,
        price_amount,price_currency,status,published_at,company_test_mode_only,organization_id) values
        (1,'${instructorId}','Owned paid course','owned-paid','A real course','Course detail','Data','Beginner',false,50,'NGN','published',now(),false,null),
        (2,'${instructorId}','Owned free course','owned-free','A free course','Course detail','Data','Beginner',true,null,'NGN','published',now(),false,null),
        (3,null,'Unowned sample','unowned-sample','Legacy sample','Legacy detail','Data','Beginner',false,50,'NGN','published',now(),false,null),
        (4,'${instructorId}','Draft course','draft-course','Draft','Draft detail','Data','Beginner',false,50,'NGN','draft',null,false,null),
        (5,'${instructorId}','Company-only course','company-only','Private test','Private detail','Data','Beginner',false,50,'NGN','published',now(),true,null),
        (6,'${instructorId}','Paystack fixture','paystack-fixture','Private fixture','Private detail','Data','Beginner',false,50,'NGN','published',now(),false,null),
        (7,'${instructorId}','Organization course','organization-course','Public provider course','Provider detail','Data','Beginner',false,50,'NGN','published',now(),false,20);
      insert into public.learning_paystack_test_fixtures values (6,'closed');
      insert into public.learning_provider_organizations values (20,'Public Provider','public-provider','active');
      insert into public.learning_provider_organization_verifications values (20,'verified');
      insert into public.course_modules values (1,1,'Real module',1),(3,3,'Legacy sample module',1);
      insert into public.lessons values
        (1,1,1,'Real preview','text',true,'Safe preview',null,null,null,null,1),
        (3,3,3,'Legacy preview','text',true,'Legacy sample content',null,null,null,null,1);
    `);

    await db.exec(migration);
    await db.exec(`select set_config('request.jwt.claim.sub','${adminId}',false)`);

    const options = await db.query('select course_id from public.list_learning_editorial_courses_for_admin() order by course_id');
    assert.deepEqual(options.rows.map((row) => row.course_id), [1, 2, 7],
      'only published instructor-owned courses without test restrictions are eligible');

    const catalog = await db.query('select course_id from public.search_public_published_learning_courses() order by course_id');
    assert.deepEqual(catalog.rows.map((row) => row.course_id), [1, 2, 7],
      'the public catalog excludes legacy courses with neither an instructor nor provider organization');
    const published = await db.query('select course_id from public.list_published_learning_courses(24,0) order by course_id');
    assert.deepEqual(published.rows.map((row) => row.course_id), [1, 2, 7]);
    const unownedDetail = await db.query("select * from public.get_published_learning_course_by_slug('unowned-sample')");
    assert.equal(unownedDetail.rows.length, 0, 'legacy unowned course details are not publicly exposed by slug');

    const created = await db.query(`select public.create_learning_editorial_campaign_for_admin(
      'Featured learning', 'A short editorial introduction.', now() - interval '1 minute',
      now() + interval '1 hour', array[1,7]::bigint[]) as id`);
    const campaignId = created.rows[0].id;
    const active = await db.query('select * from public.list_active_learning_editorial_campaign() order by course_id');
    assert.equal(active.rows.length, 2);
    assert.deepEqual(active.rows.map((row) => row.course_id), [1, 7]);
    assert.equal(active.rows[0].campaign_title, 'Featured learning');
    assert.equal(active.rows[1].provider_name, 'Public Provider');

    await assert.rejects(db.query(`select public.create_learning_editorial_campaign_for_admin(
      'Overlapping campaign', 'This should be rejected.', now(), now() + interval '1 hour', array[1]::bigint[])`),
    /overlaps this schedule/);
    await assert.rejects(db.query(`select public.create_learning_editorial_campaign_for_admin(
      'Test-only course', 'This must be rejected.', now(), now() + interval '1 hour', array[6]::bigint[])`),
    /Only published instructor-owned public courses/);
    await assert.rejects(db.query(`select public.create_learning_editorial_campaign_for_admin(
      'Too many', 'This must be rejected.', now(), now() + interval '1 hour', array[1,2,7,1,2,7,1]::bigint[])`),
    /Invalid featured campaign details/);

    const adminRows = await db.query('select * from public.list_learning_editorial_campaigns_for_admin()');
    assert.equal(adminRows.rows.length, 1);
    assert.equal(adminRows.rows[0].campaign_id, campaignId);
    assert.deepEqual(adminRows.rows[0].course_ids, [1, 7]);

    await db.exec(`select set_config('request.jwt.claim.sub','${otherId}',false)`);
    await assert.rejects(db.query('select * from public.list_learning_editorial_campaigns_for_admin()'),
      /Learning Admin capability required/);
    await assert.rejects(db.query(`select public.create_learning_editorial_campaign_for_admin(
      'Not admin', 'Must be rejected.', now(), now() + interval '1 hour', array[1]::bigint[])`),
    /Learning Admin capability required/);

    await db.exec(`select set_config('request.jwt.claim.sub','${adminId}',false)`);
    await db.query('select public.disable_learning_editorial_campaign_for_admin($1)', [campaignId]);
    const hidden = await db.query('select * from public.list_active_learning_editorial_campaign()');
    assert.equal(hidden.rows.length, 0, 'disabled campaigns are immediately removed from the public shelf');

    const scheduled = await db.query(`select public.create_learning_editorial_campaign_for_admin(
      'Future campaign', 'This campaign starts later.', now() + interval '2 days',
      now() + interval '3 days', array[2]::bigint[]) as id`);
    const scheduledPublic = await db.query('select * from public.list_active_learning_editorial_campaign()');
    assert.equal(scheduledPublic.rows.length, 0, 'future campaigns are not visible early');
    const scheduledAdmin = await db.query('select campaign_state from public.list_learning_editorial_campaigns_for_admin() where campaign_id=$1', [scheduled.rows[0].id]);
    assert.equal(scheduledAdmin.rows[0].campaign_state, 'scheduled');
    await db.query('select public.disable_learning_editorial_campaign_for_admin($1)', [scheduled.rows[0].id]);

    const audit = await db.query("select action from public.learning_audit_events order by id");
    assert.deepEqual(audit.rows.map((row) => row.action), [
      'editorial_campaign.scheduled', 'editorial_campaign.disabled',
      'editorial_campaign.scheduled', 'editorial_campaign.disabled',
    ]);

    await db.exec('set role authenticated');
    await assert.rejects(db.query('select * from public.learning_editorial_campaigns'), /permission denied/,
      'authenticated users cannot read campaign administration tables directly');
    await db.exec('reset role; set role anon');
    const publicEmpty = await db.query('select * from public.list_active_learning_editorial_campaign()');
    assert.equal(publicEmpty.rows.length, 0);
    const rawCourses = await db.query('select id from public.learning_courses order by id');
    assert.deepEqual(rawCourses.rows.map((row) => row.id), [1, 2, 7],
      'RLS hides unowned samples and private test courses from raw public reads');
    const publicModuleIds = await db.query('select id from public.course_modules order by id');
    assert.deepEqual(publicModuleIds.rows.map((row) => row.id), [1],
      'public curriculum reads remain limited to catalog-eligible courses');
    const publicLessonIds = await db.query('select id from public.lessons order by id');
    assert.deepEqual(publicLessonIds.rows.map((row) => row.id), [1],
      'public preview lesson reads remain limited to catalog-eligible courses');
    await db.exec('reset role');

    console.log('PASS Phase 4 editorial campaigns: eligibility, scheduling conflicts, public visibility, admin authorization, disable, and audit');
  } finally {
    await db.close();
  }
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
