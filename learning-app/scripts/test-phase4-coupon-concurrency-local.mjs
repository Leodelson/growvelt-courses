function startDocker(args, input) {
  const child = spawn(docker, args, { cwd: root, stdio: ["pipe", "pipe", "pipe"], shell: false });
  let stdout = "";
  let stderr = "";
  child.stdout.on("data", (chunk) => { stdout += chunk; });
  child.stderr.on("data", (chunk) => { stderr += chunk; });
  if (input !== undefined) child.stdin.end(input);
  const done = new Promise((resolve, reject) => {
    child.once("error", reject);
    child.once("exit", (code) => resolve({ code, stdout: stdout.trim(), stderr: stderr.trim() }));
  });
  return { child, done, output: () => `${stdout}\n${stderr}` };
}

async function runDocker(args, input) {
  const result = await startDocker(args, input).done;
  if (result.code !== 0) throw new Error((result.stderr || result.stdout).trim());
  return result.stdout;
}

