const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const path = require('node:path');
const { PGlite } = require(process.env.PGLITE_PACKAGE_PATH || '@electric-sql/pglite');

const migration = [
  '20261015000000_allow_company_test_mode_courses.sql',
  '20261113000000_allow_public_paid_course_submissions.sql',
].map((file) => readFileSync(path.resolve(__dirname, `../supabase/migrations/${file}`), 'utf8')).join('\n');
const instructor = '00000000-0000-4000-8000-000000000001';
const admin = '00000000-0000-4000-8000-000000000002';
const manager = '00000000-0000-4000-8000-000000000003';
const employee = '00000000-0000-4000-8000-000000000004';

async function main() {
  const db = new PGlite();
  try {
    await db.exec(`
      create role anon;
      create role authenticated;
      create role service_role;
      create schema auth;
      create function auth.uid() returns uuid language sql stable as $$
        select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
      $$;
      create function public.is_approved_growvelt_instructor() returns boolean
        language sql stable as $$ select auth.uid() = '${instructor}'::uuid $$;
      create function public.is_growvelt_learning_admin() returns boolean
        language sql stable as $$ select auth.uid() = '${admin}'::uuid $$;
      create function public.is_paystack_test_fixture_course(p_course_id bigint) returns boolean
        language sql stable as $$ select false $$;
      create function public.resolve_learning_commercial_terms_version(p_course_id bigint, p_instructor_id uuid) returns text
        language sql stable as $$ select 'terms-v1'::text $$;
      create table public.profiles(id uuid primary key, full_name text);
      create table public.learning_courses(
        id bigint generated by default as identity primary key,
        instructor_id uuid, title text not null, slug text not null unique, summary text,
        description text, category text, level text, organization_id bigint,
        price_amount numeric, price_currency text default 'NGN', is_free boolean not null default false,
        is_limited_time_free boolean not null default false, status text not null default 'draft',
        submitted_at timestamptz, published_at timestamptz, reviewed_at timestamptz,
        reviewed_by uuid, review_note text, updated_at timestamptz default now(),
        course_video_cover_storage_path text
      );
      alter table public.learning_courses enable row level security;
      create table public.course_modules(
        id bigint generated by default as identity primary key, course_id bigint, title text, position integer
      );
      alter table public.course_modules enable row level security;
      create table public.lessons(
        id bigint generated by default as identity primary key, course_id bigint, module_id bigint,
        title text, lesson_type text, content text, video_provider text, video_reference text,
        video_visibility text, duration_seconds integer, video_url text, duration_minutes integer,
        is_preview boolean default false, position integer
      );
      alter table public.lessons enable row level security;
      create table public.course_rights_declarations(
        id bigint generated by default as identity primary key, course_id bigint, instructor_id uuid,
        declaration_version text, rights_basis text, accepted_at timestamptz default now()
      );
      create table public.learning_paystack_test_fixtures(
        course_id bigint, status text, expires_at timestamptz, tester_id uuid
      );
      create table public.learning_provider_organizations(id bigint, name text, slug text, status text);
      create table public.learning_provider_organization_verifications(organization_id bigint, status text);
      create table public.enrollments(course_id bigint, learner_id uuid, status text);
      create table public.learning_course_entitlements(course_id bigint, learner_id uuid, status text);
      create table public.learning_orders(
        id bigint generated by default as identity primary key, order_reference text not null unique default 'paid-order-1',
        learner_id uuid, course_id bigint, instructor_id uuid, course_title_snapshot text,
        instructor_name_snapshot text, gross_amount_minor bigint, currency text, status text,
        commercial_terms_version text
      );
      create table public.learning_payment_attempts(
        id bigint generated by default as identity primary key, order_id bigint, provider text,
        provider_reference text, amount_minor bigint, currency text, status text, paystack_domain text
      );
      create table public.learning_company_workspaces(id bigint, status text);
      create table public.learning_company_memberships(workspace_id bigint, user_id uuid, status text, role text);
      create table public.learning_company_paid_course_purchases(id bigint, course_id bigint);
      grant select on public.learning_courses, public.course_modules, public.lessons to anon, authenticated;
      insert into public.profiles(id, full_name) values
        ('${instructor}', 'Test Instructor'), ('${admin}', 'Test Admin'), ('${manager}', 'Test Company Manager'), ('${employee}', 'Test Employee');
      insert into public.learning_company_workspaces values (1, 'active');
      insert into public.learning_company_memberships values (1, '${manager}', 'active', 'owner');
    `);

    await db.exec(migration);

    const created = (await db.query(`
      insert into public.learning_courses(instructor_id,title,slug,summary,description,category,level,price_amount,price_currency,is_free)
      values ('${instructor}','Test Mode Course','test-mode-course','Practical company test course','A sufficiently long course description for submission checks.','Data Analytics','Beginner',50,'NGN',false)
      returning id
    `)).rows[0];
    const coverPath = `${instructor}/${created.id}/course-video-cover`;
    await db.exec(`
      update public.learning_courses set course_video_cover_storage_path='${coverPath}' where id=${created.id};
      insert into public.course_modules(course_id,title,position) values (${created.id},'Getting started',1);
      insert into public.lessons(course_id,module_id,title,lesson_type,content,is_preview,position)
      values (${created.id},1,'Read the sales spreadsheet','text','A short test lesson.',false,1);
      select set_config('request.jwt.claim.sub','${instructor}',false);
    `);

    const enabled = await db.query(`select public.set_own_learning_course_company_test_mode(${created.id},true) as enabled`);
    assert.equal(enabled.rows[0].enabled, true);
    const submission = await db.query(`select * from public.submit_learning_course_for_review(${created.id},'2026-08-v1','original')`);
    assert.equal(submission.rows[0].submission_status, 'pending_review');

    await db.exec(`select set_config('request.jwt.claim.sub','${admin}',false)`);
    const reviewFlag = await db.query(`select public.get_learning_course_test_mode_for_review(${created.id}) as test_only`);
    assert.equal(reviewFlag.rows[0].test_only, true);
    const published = await db.query(`select * from public.review_learning_course(${created.id},'published',null)`);
    assert.equal(published.rows[0].review_status, 'published');

    const anonymousCourse = await db.query(`select * from public.get_published_learning_course_by_slug('test-mode-course')`);
    const catalogCourse = await db.query(`select * from public.search_public_published_learning_courses(null,null,null,null,'newest',24,0) where course_id=${created.id}`);
    assert.equal(anonymousCourse.rows.length, 0);
    assert.equal(catalogCourse.rows.length, 0);

    const publicPaidCourse = (await db.query(`
      insert into public.learning_courses(instructor_id,title,slug,summary,description,category,level,price_amount,price_currency,is_free)
      values ('${instructor}','Public Paid Course','public-paid-course','A public paid course','A sufficiently long paid course description for submission checks.','Programming','Beginner',4900,'NGN',false)
      returning id
    `)).rows[0];
    const paidModule = (await db.query(`
      insert into public.course_modules(course_id,title,position) values (${publicPaidCourse.id},'Paid course module',1) returning id
    `)).rows[0];
    await db.exec(`
      insert into public.lessons(course_id,module_id,title,lesson_type,content,is_preview,position)
      values (${publicPaidCourse.id},${paidModule.id},'Paid course lesson','text','A paid course lesson.',false,1);
      select set_config('request.jwt.claim.sub','${instructor}',false);
    `);
    const paidSubmission = await db.query(`select * from public.submit_learning_course_for_review(${publicPaidCourse.id},'2026-08-v1','original')`);
    assert.equal(paidSubmission.rows[0].submission_status, 'pending_review');
    await db.exec(`select set_config('request.jwt.claim.sub','${admin}',false)`);
    const publicPaidReviewFlag = await db.query(`select public.get_learning_course_test_mode_for_review(${publicPaidCourse.id}) as test_only`);
    assert.equal(publicPaidReviewFlag.rows[0].test_only, false);
    const publicPaidReview = await db.query(`select * from public.review_learning_course(${publicPaidCourse.id},'published',null)`);
    assert.equal(publicPaidReview.rows[0].review_status, 'published');
    const publicPaidDetail = await db.query(`select * from public.get_published_learning_course_by_slug('public-paid-course')`);
    const publicPaidSearch = await db.query(`select * from public.search_public_published_learning_courses(null,null,null,false,'newest',24,0) where course_id=${publicPaidCourse.id}`);
    assert.equal(publicPaidDetail.rows.length, 1);
    assert.equal(publicPaidDetail.rows[0].is_free, false);
    assert.equal(publicPaidDetail.rows[0].price_amount, '4900');
    assert.equal(publicPaidSearch.rows.length, 1);
    await assert.rejects(
      db.query(`select * from public.initialize_paystack_live_learning_order('${employee}',${created.id})`),
      /Company Sandbox Mode-only courses cannot be purchased with Live payments/,
    );
    const liveOrder = await db.query(`select * from public.initialize_paystack_live_learning_order('${employee}',${publicPaidCourse.id})`);
    assert.equal(String(liveOrder.rows[0].amount_minor), '490000');

    const organizationPaidCourse = (await db.query(`
      insert into public.learning_courses(instructor_id,title,slug,summary,description,category,level,organization_id,price_amount,price_currency,is_free)
      values ('${instructor}','Organization Paid Course','organization-paid-course','Organization course','A sufficiently long organization course description.','Programming','Beginner',99,4900,'NGN',false)
      returning id
    `)).rows[0];
    await db.exec(`select set_config('request.jwt.claim.sub','${instructor}',false)`);
    await assert.rejects(
      db.query(`select * from public.submit_learning_course_for_review(${organizationPaidCourse.id},'2026-08-v1','original')`),
      /Paid courses must be personal instructor courses/,
    );

    const freeCourse = (await db.query(`
      insert into public.learning_courses(instructor_id,title,slug,summary,description,category,level,price_amount,price_currency,is_free)
      values ('${instructor}','Public Free Course','public-free-course','A public free course','A sufficiently long free course description for submission checks.','Data Analytics','Beginner',0,'NGN',true)
      returning id
    `)).rows[0];
    const freeModule = (await db.query(`
      insert into public.course_modules(course_id,title,position) values (${freeCourse.id},'Free module',1) returning id
    `)).rows[0];
    await db.exec(`
      insert into public.lessons(course_id,module_id,title,lesson_type,content,is_preview,position)
      values (${freeCourse.id},${freeModule.id},'Free preview','text','Public preview lesson.',true,1);
      select set_config('request.jwt.claim.sub','${instructor}',false);
    `);
    const freeSubmission = await db.query(`select * from public.submit_learning_course_for_review(${freeCourse.id},'2026-08-v1','original')`);
    assert.equal(freeSubmission.rows[0].submission_status, 'pending_review');
    await db.exec(`select set_config('request.jwt.claim.sub','${admin}',false)`);
    await db.query(`select * from public.review_learning_course(${freeCourse.id},'published',null)`);
    const publicFreeDetail = await db.query(`select * from public.get_published_learning_course_by_slug('public-free-course')`);
    const publicFreeSearch = await db.query(`select * from public.search_public_published_learning_courses(null,null,null,true,'newest',24,0) where course_id=${freeCourse.id}`);
    assert.equal(publicFreeDetail.rows.length, 1);
    assert.equal(publicFreeSearch.rows.length, 1);

    await db.exec(`select set_config('request.jwt.claim.sub','',false)`);
    assert.equal((await db.query(`select public.can_read_learning_course_video_cover('${coverPath}') as can_read`)).rows[0].can_read, false);
    assert.equal((await db.query(`select * from public.get_own_or_published_learning_course_video_cover(${created.id})`)).rows.length, 0);
    await db.exec(`
      insert into public.enrollments(course_id,learner_id,status) values (${created.id},'${employee}','active');
      select set_config('request.jwt.claim.sub','${employee}',false);
    `);
    assert.equal((await db.query(`select public.can_read_learning_course_video_cover('${coverPath}') as can_read`)).rows[0].can_read, true);
    assert.equal((await db.query(`select * from public.get_own_or_published_learning_course_video_cover(${created.id})`)).rows.length, 1);

    await db.exec(`select set_config('request.jwt.claim.sub','${manager}',false)`);
    const courseManagerList = await db.query('select * from public.list_own_learning_company_paid_courses(1)');
    const companySandboxCourse = courseManagerList.rows.find((course) => course.course_id === created.id);
    assert.equal(companySandboxCourse.company_test_mode_only, true);
    await db.exec(`insert into public.learning_company_paid_course_purchases values (1,${created.id})`);
    const serviceResult = await db.query(`select public.is_learning_company_purchase_test_only(1) as test_only`);
    assert.equal(serviceResult.rows[0].test_only, true);

    await db.exec(`set role anon`);
    const publicModules = await db.query(`select * from public.course_modules where course_id in (${created.id},${publicPaidCourse.id},${freeCourse.id})`);
    const publicLessons = await db.query(`select * from public.lessons where course_id in (${created.id},${publicPaidCourse.id},${freeCourse.id})`);
    const publicCourseRows = await db.query(`select id from public.learning_courses where id in (${created.id},${publicPaidCourse.id},${freeCourse.id})`);
    assert.equal(publicModules.rows.length, 2);
    assert.equal(publicLessons.rows.length, 1);
    assert.deepEqual(publicCourseRows.rows.map((row) => row.id).sort((a, b) => a - b), [publicPaidCourse.id, freeCourse.id].sort((a, b) => a - b));
    console.log('PASS public and company-sandbox paid review paths, live-order isolation, organization-owned paid-course guard, public-content isolation, and free-course continuity');
  } finally {
    await db.close();
  }
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
