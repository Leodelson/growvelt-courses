assert.equal(parsePaystackCompanyReversalNotice({ ...refund, data: { ...refund.data, status: "pending" } }, "test"), null);
assert.equal(isPaystackCompanyReversalEvent({ ...refund, data: { ...refund.data, transaction_reference: `GL-${"A".repeat(32)}` } }), false);
