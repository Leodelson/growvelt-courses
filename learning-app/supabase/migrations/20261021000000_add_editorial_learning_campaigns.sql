-- Phase 4: schedule admin-curated featured course campaigns without introducing
-- paid placement, checkout, seller-share, or transfer behavior.
begin;

create table public.learning_editorial_campaigns (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(btrim(title)) between 3 and 80),
  message text not null check (char_length(btrim(message)) between 3 and 240),
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  enabled boolean not null default true,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  disabled_at timestamptz,
  disabled_by uuid references public.profiles(id) on delete set null,
  constraint learning_editorial_campaigns_window_check check (ends_at > starts_at),
  constraint learning_editorial_campaigns_disable_state_check check (
    (enabled and disabled_at is null and disabled_by is null)
    or (not enabled and disabled_at is not null)
  )
);

create table public.learning_editorial_campaign_courses (
  campaign_id bigint not null references public.learning_editorial_campaigns(id) on delete cascade,
  course_id bigint not null references public.learning_courses(id) on delete restrict,
  position smallint not null check (position between 1 and 6),
  primary key (campaign_id, course_id),
  unique (campaign_id, position)
);

create index learning_editorial_campaigns_schedule_idx
  on public.learning_editorial_campaigns (starts_at, ends_at)
  where enabled;
create index learning_editorial_campaign_courses_course_idx
  on public.learning_editorial_campaign_courses (course_id, campaign_id);

-- Close the previously reported public-catalog leak for legacy sample courses
-- that have neither an instructor nor a provider organization. Keep published
-- instructor and organization courses visible, while applying the same boundary
-- to raw public reads, catalog RPCs, and course-detail RPCs.
drop policy if exists "Published courses are public" on public.learning_courses;
create policy "Published courses are public" on public.learning_courses
  for select to anon, authenticated
  using (
    status = 'published'
    and coalesce(company_test_mode_only, false) = false
    and (instructor_id is not null or organization_id is not null)
    and not public.is_paystack_test_fixture_course(learning_courses.id)
  );

drop policy if exists "Published course modules are public" on public.course_modules;
create policy "Published course modules are public" on public.course_modules
  for select to anon, authenticated using (exists (
    select 1 from public.learning_courses course
    where course.id = course_modules.course_id and course.status = 'published'
      and coalesce(course.company_test_mode_only, false) = false
      and (course.instructor_id is not null or course.organization_id is not null)
      and not public.is_paystack_test_fixture_course(course.id)
  ));

drop policy if exists "Published course preview lessons are public" on public.lessons;
create policy "Published course preview lessons are public" on public.lessons
  for select to anon, authenticated using (is_preview = true and exists (
    select 1 from public.learning_courses course
    where course.id = lessons.course_id and course.status = 'published'
      and coalesce(course.company_test_mode_only, false) = false
      and (course.instructor_id is not null or course.organization_id is not null)
      and not public.is_paystack_test_fixture_course(course.id)
  ));

create or replace function public.get_published_learning_course_by_slug(p_slug text)
returns table(course_id bigint, slug text, course_title text, summary text, description text, category text, level text,
  is_free boolean, price_amount numeric, price_currency text, instructor_name text, provider_name text, provider_slug text,
  provider_verified boolean, published_at timestamptz, module_id bigint, module_title text, module_position integer,
  lesson_id bigint, lesson_title text, lesson_type text, is_preview boolean, preview_text_content text,
  preview_video_provider text, preview_video_reference text, preview_video_visibility text,
  preview_duration_seconds integer, lesson_position integer)
language plpgsql stable security definer set search_path to '' as $function$
declare normalized_slug text := lower(btrim(p_slug));
begin
  if normalized_slug is null or normalized_slug = '' or char_length(normalized_slug) > 220 then
    raise exception 'Invalid published course reference' using errcode = '22023';
  end if;

  return query
  select course.id, course.slug, course.title, course.summary, course.description, course.category, course.level,
    course.is_free, course.price_amount, course.price_currency, profile.full_name,
    case when verification.status = 'verified' then organization.name end,
    case when verification.status = 'verified' then organization.slug end,
    coalesce(verification.status = 'verified', false), course.published_at,
    module.id, module.title, module.position, lesson.id, lesson.title, lesson.lesson_type, lesson.is_preview,
    case when lesson.is_preview then lesson.content end,
    case when lesson.is_preview then lesson.video_provider end,
    case when lesson.is_preview then lesson.video_reference end,
    case when lesson.is_preview then lesson.video_visibility end,
    case when lesson.is_preview then lesson.duration_seconds end, lesson.position
  from public.learning_courses course
  left join public.profiles profile on profile.id = course.instructor_id
  left join public.learning_provider_organizations organization
    on organization.id = course.organization_id and organization.status = 'active'
  left join public.learning_provider_organization_verifications verification
    on verification.organization_id = organization.id
  left join public.course_modules module on module.course_id = course.id
  left join public.lessons lesson on lesson.course_id = course.id and lesson.module_id = module.id
  where course.slug = normalized_slug and course.status = 'published'
    and coalesce(course.company_test_mode_only, false) = false
    and (course.instructor_id is not null or course.organization_id is not null)
    and not exists (
      select 1 from public.learning_paystack_test_fixtures fixture where fixture.course_id = course.id
    )
  order by module.position nulls last, module.id, lesson.position nulls last, lesson.id;
end;
$function$;

create or replace function public.list_published_learning_courses(p_limit integer default 24,p_offset integer default 0)
returns table(course_id bigint, slug text, title text, summary text, category text, level text, is_free boolean,
  price_amount numeric, price_currency text, instructor_name text, provider_name text, provider_slug text,
  provider_verified boolean, published_at timestamptz)
language plpgsql stable security definer set search_path to '' as $function$
begin
  if p_limit not between 1 and 36 or p_offset < 0 then
    raise exception 'Invalid published-course pagination' using errcode = '22023';
  end if;
  return query
  select course.id, course.slug, course.title, course.summary, course.category, course.level,
    course.is_free, course.price_amount, course.price_currency, profile.full_name,
    case when verification.status = 'verified' then organization.name end,
    case when verification.status = 'verified' then organization.slug end,
    coalesce(verification.status = 'verified', false), course.published_at
  from public.learning_courses course
  left join public.profiles profile on profile.id = course.instructor_id
  left join public.learning_provider_organizations organization
    on organization.id = course.organization_id and organization.status = 'active'
  left join public.learning_provider_organization_verifications verification
    on verification.organization_id = organization.id
  where course.status = 'published' and coalesce(course.company_test_mode_only, false) = false
    and (course.instructor_id is not null or course.organization_id is not null)
    and not exists (
      select 1 from public.learning_paystack_test_fixtures fixture where fixture.course_id = course.id
    )
  order by course.published_at desc nulls last, course.id desc
  limit p_limit offset p_offset;
end;
$function$;

create or replace function public.search_public_published_learning_courses(
  p_query text default null, p_category text default null, p_level text default null,
  p_is_free boolean default null, p_sort text default 'newest', p_limit integer default 12, p_offset integer default 0
)
returns table(course_id bigint, slug text, title text, summary text, category text, level text, is_free boolean,
  price_amount numeric, price_currency text, instructor_name text, provider_name text, provider_slug text,
  provider_verified boolean, published_at timestamptz, total_courses integer)
language plpgsql stable security definer set search_path to '' as $function$
declare
  q text := nullif(lower(btrim(p_query)), '');
  cat text := nullif(lower(btrim(p_category)), '');
  lvl text := nullif(lower(btrim(p_level)), '');
  sort_key text := lower(btrim(coalesce(p_sort, 'newest')));
begin
  if (q is not null and char_length(q) > 120)
    or (cat is not null and char_length(cat) > 100)
    or (lvl is not null and char_length(lvl) > 100) then
    raise exception 'Invalid catalog filter' using errcode = '22023';
  end if;
  if sort_key not in ('newest', 'title_asc', 'title_desc') or p_limit not between 1 and 24 or p_offset < 0 then
    raise exception 'Invalid catalog pagination or sort' using errcode = '22023';
  end if;

  return query
  select course.id, course.slug, course.title, course.summary, course.category, course.level, course.is_free,
    course.price_amount, course.price_currency, profile.full_name,
    case when verification.status = 'verified' then organization.name end,
    case when verification.status = 'verified' then organization.slug end,
    coalesce(verification.status = 'verified', false), course.published_at, count(*) over()::integer
  from public.learning_courses course
  left join public.profiles profile on profile.id = course.instructor_id
  left join public.learning_provider_organizations organization
    on organization.id = course.organization_id and organization.status = 'active'
  left join public.learning_provider_organization_verifications verification
    on verification.organization_id = organization.id
  where course.status = 'published' and coalesce(course.company_test_mode_only, false) = false
    and (course.instructor_id is not null or course.organization_id is not null)
    and not exists (
      select 1 from public.learning_paystack_test_fixtures fixture where fixture.course_id = course.id
    )
    and (q is null or position(q in lower(concat_ws(' ', course.title, course.summary, course.category,
      course.level, organization.name))) > 0)
    and (cat is null or lower(course.category) = cat)
    and (lvl is null or lower(course.level) = lvl)
    and (p_is_free is null or course.is_free = p_is_free)
  order by case when sort_key = 'title_asc' then lower(course.title) end asc nulls last,
    case when sort_key = 'title_desc' then lower(course.title) end desc nulls last,
    case when sort_key = 'newest' then course.published_at end desc nulls last,
    course.id desc
  limit p_limit offset p_offset;
end;
$function$;

