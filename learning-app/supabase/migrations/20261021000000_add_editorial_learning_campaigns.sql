create or replace function public.list_learning_editorial_courses_for_admin()
returns table(course_id bigint, title text, summary text, category text, is_free boolean,
  price_amount numeric, price_currency text)
language plpgsql stable security definer set search_path to '' as $function$
begin
  if not public.is_growvelt_learning_admin() then
    raise exception 'Learning Admin capability required' using errcode = '42501';
  end if;

  return query
  select course.id, course.title, course.summary, course.category, course.is_free,
    course.price_amount, course.price_currency
  from public.learning_courses course
  where public.is_learning_editorial_course_eligible(course.id)
  order by course.published_at desc nulls last, course.id desc
  limit 500;
end;
$function$;

create or replace function public.list_learning_editorial_campaigns_for_admin()
returns table(campaign_id bigint, campaign_title text, campaign_message text,
  starts_at timestamptz, ends_at timestamptz, enabled boolean, created_at timestamptz,
  campaign_state text, course_ids bigint[], course_titles text)
language plpgsql stable security definer set search_path to '' as $function$
begin
  if not public.is_growvelt_learning_admin() then
    raise exception 'Learning Admin capability required' using errcode = '42501';
  end if;

  return query
  select campaign.id, campaign.title, campaign.message, campaign.starts_at,
    campaign.ends_at, campaign.enabled, campaign.created_at,
    case when not campaign.enabled then 'disabled'
      when campaign.ends_at <= now() then 'ended'
      when campaign.starts_at > now() then 'scheduled'
      else 'live' end,
    coalesce(array_agg(link.course_id order by link.position)
      filter (where link.course_id is not null), array[]::bigint[]),
    coalesce(string_agg(coalesce(course.title, 'Unavailable course #' || link.course_id::text),
      ' · ' order by link.position), '')
  from public.learning_editorial_campaigns campaign
  left join public.learning_editorial_campaign_courses link on link.campaign_id = campaign.id
  left join public.learning_courses course on course.id = link.course_id
  group by campaign.id
  order by campaign.created_at desc, campaign.id desc
  limit 30;
end;
$function$;

create or replace function public.create_learning_editorial_campaign_for_admin(
  p_title text,
  p_message text,
  p_starts_at timestamptz,
  p_ends_at timestamptz,
  p_course_ids bigint[]
)
returns bigint
language plpgsql security definer set search_path to '' as $function$
declare
  campaign_key bigint;
  actor_id uuid := auth.uid();
begin
  if not public.is_growvelt_learning_admin() then
    raise exception 'Learning Admin capability required' using errcode = '42501';
  end if;
  if nullif(btrim(p_title), '') is null or char_length(btrim(p_title)) > 80
    or nullif(btrim(p_message), '') is null or char_length(btrim(p_message)) > 240
    or p_starts_at is null or p_ends_at is null or p_ends_at <= p_starts_at
    or p_ends_at <= now()
    or p_course_ids is null or cardinality(p_course_ids) not between 1 and 6
    or exists (select 1 from unnest(p_course_ids) selected(course_id) where selected.course_id is null)
    or (select count(distinct selected.course_id) from unnest(p_course_ids) selected(course_id)) <> cardinality(p_course_ids) then
    raise exception 'Invalid featured campaign details' using errcode = '22023';
  end if;

  if exists (
    select 1 from unnest(p_course_ids) selected(course_id)
    where not public.is_learning_editorial_course_eligible(selected.course_id)
  ) then
    raise exception 'Only published instructor-owned public courses can be featured' using errcode = '22023';
  end if;

  -- Serialize schedule checks so two concurrent admin requests cannot create
  -- overlapping enabled campaigns.
  perform pg_advisory_xact_lock(7246102101001::bigint);
  if exists (
    select 1 from public.learning_editorial_campaigns campaign
    where campaign.enabled
      and campaign.ends_at > now()
      and campaign.starts_at < p_ends_at
      and campaign.ends_at > p_starts_at
  ) then
    raise exception 'Another featured campaign overlaps this schedule' using errcode = '23P01';
  end if;

  insert into public.learning_editorial_campaigns(title, message, starts_at, ends_at, created_by)
  values (btrim(p_title), btrim(p_message), p_starts_at, p_ends_at, actor_id)
  returning id into campaign_key;

  insert into public.learning_editorial_campaign_courses(campaign_id, course_id, position)
  select campaign_key, selected.course_id, selected.position::smallint
  from unnest(p_course_ids) with ordinality as selected(course_id, position);

  insert into public.learning_audit_events(actor_user_id, actor_role, action, entity_type, entity_id, metadata)
  values (actor_id, 'admin_operator', 'editorial_campaign.scheduled', 'editorial_campaign',
    campaign_key::text, jsonb_build_object('course_ids', p_course_ids,
      'starts_at', p_starts_at, 'ends_at', p_ends_at));

  return campaign_key;
end;
$function$;

create or replace function public.disable_learning_editorial_campaign_for_admin(p_campaign_id bigint)
returns boolean
language plpgsql security definer set search_path to '' as $function$
declare actor_id uuid := auth.uid();
begin
  if not public.is_growvelt_learning_admin() then
    raise exception 'Learning Admin capability required' using errcode = '42501';
  end if;
  if p_campaign_id is null or p_campaign_id <= 0 then
    raise exception 'Invalid featured campaign' using errcode = '22023';
  end if;

  update public.learning_editorial_campaigns campaign
  set enabled = false, disabled_at = now(), disabled_by = actor_id
  where campaign.id = p_campaign_id and campaign.enabled;
  if not found then
    raise exception 'Enabled campaign not found' using errcode = 'P0002';
  end if;

  insert into public.learning_audit_events(actor_user_id, actor_role, action, entity_type, entity_id, metadata)
  values (actor_id, 'admin_operator', 'editorial_campaign.disabled', 'editorial_campaign',
    p_campaign_id::text, '{}'::jsonb);
  return true;
end;
$function$;

create or replace function public.list_active_learning_editorial_campaign()
returns table(campaign_id bigint, campaign_title text, campaign_message text,
  course_id bigint, slug text, title text, summary text, category text, level text,
  is_free boolean, price_amount numeric, price_currency text, instructor_name text,
  provider_name text, provider_slug text, provider_verified boolean)
language plpgsql stable security definer set search_path to '' as $function$
declare
  selected_campaign_id bigint;
  selected_campaign_title text;
  selected_campaign_message text;
begin
  select campaign.id, campaign.title, campaign.message
  into selected_campaign_id, selected_campaign_title, selected_campaign_message
  from public.learning_editorial_campaigns campaign
  where campaign.enabled and campaign.starts_at <= now() and campaign.ends_at > now()
  order by campaign.starts_at desc, campaign.id desc
  limit 1;
  if not found then return; end if;

  return query
  select selected_campaign_id, selected_campaign_title, selected_campaign_message,
    course.id, course.slug, course.title, course.summary, course.category, course.level,
    course.is_free, course.price_amount, course.price_currency, instructor.full_name,
    case when verification.status = 'verified' then organization.name end,
    case when verification.status = 'verified' then organization.slug end,
    coalesce(verification.status = 'verified', false)
  from public.learning_editorial_campaign_courses link
  join public.learning_courses course on course.id = link.course_id
  left join public.profiles instructor on instructor.id = course.instructor_id
  left join public.learning_provider_organizations organization
    on organization.id = course.organization_id and organization.status = 'active'
  left join public.learning_provider_organization_verifications verification
    on verification.organization_id = organization.id
  where link.campaign_id = selected_campaign_id
    and public.is_learning_editorial_course_eligible(course.id)
  order by link.position;
end;
$function$;

