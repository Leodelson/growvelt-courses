-- Phase 3C: retain private evidence of repayments that an active admin has
-- independently confirmed. This records no collection, deduction, or payout.
begin;

create table public.learning_company_seller_recovery_receipts (
  id bigint generated by default as identity primary key,
  purchase_id bigint not null references public.learning_company_commercial_sales(purchase_id) on delete restrict,
  seller_payee_id uuid not null references public.profiles(id) on delete restrict,
  amount_minor bigint not null check (amount_minor > 0),
  currency text not null default 'NGN' check (currency = 'NGN'),
  payment_method text not null check (payment_method in ('bank_transfer','other')),
  payment_reference text not null check (
    char_length(btrim(payment_reference)) between 6 and 160
    and btrim(payment_reference) ~ '^[A-Za-z0-9][A-Za-z0-9._:/ -]{5,159}$'),
  recorded_by uuid not null references public.profiles(id) on delete restrict,
  recorded_at timestamptz not null default now()
);

create unique index learning_company_seller_recovery_receipts_reference_uidx
  on public.learning_company_seller_recovery_receipts(lower(btrim(payment_reference)));
create index learning_company_seller_recovery_receipts_purchase_idx
  on public.learning_company_seller_recovery_receipts(purchase_id,recorded_at,id);

create table public.learning_company_seller_recovery_receipt_ledger_entries (
  id bigint generated by default as identity primary key,
  receipt_id bigint not null references public.learning_company_seller_recovery_receipts(id) on delete restrict,
  line_number smallint not null check (line_number in (1,2)),
  account_code text not null check (account_code in (
    'asset.company_seller_recovery_cash_clearing',
    'asset.company_seller_recovery_receivable')),
  amount_minor bigint not null check (amount_minor <> 0),
  currency text not null default 'NGN' check (currency = 'NGN'),
  unique(receipt_id,line_number),
  unique(receipt_id,account_code)
);

create index learning_company_seller_recovery_receipt_ledger_receipt_idx
  on public.learning_company_seller_recovery_receipt_ledger_entries(receipt_id,id);

alter table public.learning_company_seller_recovery_receipts enable row level security;
alter table public.learning_company_seller_recovery_receipt_ledger_entries enable row level security;
revoke all on public.learning_company_seller_recovery_receipts
  from public,anon,authenticated,service_role;
revoke all on public.learning_company_seller_recovery_receipt_ledger_entries
  from public,anon,authenticated,service_role;
grant select on public.learning_company_seller_recovery_receipts to service_role;
grant select on public.learning_company_seller_recovery_receipt_ledger_entries to service_role;

create trigger prevent_learning_company_seller_recovery_receipt_mutation
before update or delete on public.learning_company_seller_recovery_receipts
for each row execute function public.prevent_learning_company_sale_mutation();

create trigger prevent_learning_company_seller_recovery_receipt_ledger_mutation
before update or delete on public.learning_company_seller_recovery_receipt_ledger_entries
for each row execute function public.prevent_learning_company_sale_mutation();

create function public.validate_learning_company_seller_recovery_receipt_ledger_entry()
returns trigger language plpgsql security definer set search_path to '' as $function$
declare receipt_row public.learning_company_seller_recovery_receipts%rowtype;
begin
  select * into receipt_row from public.learning_company_seller_recovery_receipts receipt
  where receipt.id = new.receipt_id for update;
  if not found or new.currency <> receipt_row.currency
     or (new.line_number = 1
       and (new.account_code <> 'asset.company_seller_recovery_cash_clearing'
         or new.amount_minor <> receipt_row.amount_minor))
     or (new.line_number = 2
       and (new.account_code <> 'asset.company_seller_recovery_receivable'
         or new.amount_minor <> -receipt_row.amount_minor)) then
    raise exception 'Seller recovery receipt ledger entry does not match its confirmed receipt'
      using errcode = '23514';
  end if;
  return new;
end;$function$;

create trigger validate_learning_company_seller_recovery_receipt_ledger_entry
before insert on public.learning_company_seller_recovery_receipt_ledger_entries
for each row execute function public.validate_learning_company_seller_recovery_receipt_ledger_entry();

create function public.reconcile_learning_company_seller_recovery_receipts()
returns table(purchase_id bigint,issue_type text)
language sql stable security definer set search_path to '' as $function$
  select receipt.purchase_id,'company_seller_recovery_receipt_identity_mismatch'::text
  from public.learning_company_seller_recovery_receipts receipt
  join public.learning_company_commercial_sales sale on sale.purchase_id = receipt.purchase_id
  where receipt.seller_payee_id <> sale.seller_payee_id
    or receipt.currency <> sale.currency
    or receipt.amount_minor <= 0
  union all
  select receipt.purchase_id,'company_seller_recovery_receipt_without_receivable'::text
  from public.learning_company_seller_recovery_receipts receipt
  where not exists(
    select 1 from public.learning_company_commercial_reversals reversal
    join public.learning_company_commercial_reversal_ledger_entries entry
      on entry.reversal_id = reversal.id
      and entry.account_code = 'asset.company_seller_recovery_receivable'
    where reversal.purchase_id = receipt.purchase_id)
  union all
  select receivable.purchase_id,'company_seller_recovery_receipts_exceed_receivable'::text
  from (
    select reversal.purchase_id,sum(entry.amount_minor)::bigint as booked_minor
    from public.learning_company_commercial_reversals reversal
    join public.learning_company_commercial_reversal_ledger_entries entry
      on entry.reversal_id = reversal.id
      and entry.account_code = 'asset.company_seller_recovery_receivable'
    group by reversal.purchase_id
  ) receivable
  join (
    select receipt.purchase_id,sum(receipt.amount_minor)::bigint as received_minor
    from public.learning_company_seller_recovery_receipts receipt
    group by receipt.purchase_id
  ) receipts on receipts.purchase_id = receivable.purchase_id
  where receipts.received_minor > receivable.booked_minor
  union all
  select receipt.purchase_id,'company_seller_recovery_receipt_ledger_mismatch'::text
  from public.learning_company_seller_recovery_receipts receipt
  where (select count(*) from public.learning_company_seller_recovery_receipt_ledger_entries entry
      where entry.receipt_id = receipt.id) <> 2
    or (select coalesce(sum(entry.amount_minor),0)
      from public.learning_company_seller_recovery_receipt_ledger_entries entry
      where entry.receipt_id = receipt.id) <> 0
    or (select coalesce(sum(entry.amount_minor),0)
      from public.learning_company_seller_recovery_receipt_ledger_entries entry
      where entry.receipt_id = receipt.id
        and entry.account_code = 'asset.company_seller_recovery_cash_clearing') <> receipt.amount_minor
    or (select coalesce(sum(entry.amount_minor),0)
      from public.learning_company_seller_recovery_receipt_ledger_entries entry
      where entry.receipt_id = receipt.id
        and entry.account_code = 'asset.company_seller_recovery_receivable') <> -receipt.amount_minor;
$function$;

create function public.validate_learning_company_seller_recovery_receipt()
returns trigger language plpgsql security definer set search_path to '' as $function$
declare purchase_row public.learning_company_paid_course_purchases%rowtype;
  sale_row public.learning_company_commercial_sales%rowtype;
  receivable_minor bigint; received_minor bigint;
begin
  select * into purchase_row from public.learning_company_paid_course_purchases purchase
  where purchase.id = new.purchase_id for update;
  if not found or purchase_row.status <> 'paid' then
    raise exception 'Paid company purchase is required for seller recovery' using errcode = '22023';
  end if;
  select * into sale_row from public.learning_company_commercial_sales sale
  where sale.purchase_id = new.purchase_id;
  if not found or sale_row.seller_payee_id <> new.seller_payee_id
     or sale_row.currency <> new.currency then
    raise exception 'Seller recovery receipt identity mismatch' using errcode = '22023';
  end if;
  if not exists(select 1 from public.account_capabilities capability
      where capability.user_id = new.recorded_by
        and capability.capability = 'admin' and capability.status = 'active') then
    raise exception 'Active Learning Admin required to confirm seller recovery' using errcode = '42501';
  end if;
  if exists(select 1 from public.reconcile_learning_company_commercial_reversals() issue
      join public.learning_company_commercial_reversals reversal
        on reversal.id = issue.reversal_id
      where reversal.purchase_id = new.purchase_id)
     or exists(select 1 from public.reconcile_learning_company_seller_recovery_receipts() issue
      where issue.purchase_id = new.purchase_id) then
    raise exception 'Company seller recovery ledger requires manual reconciliation' using errcode = '23514';
  end if;

  select coalesce(sum(entry.amount_minor),0)::bigint into receivable_minor
  from public.learning_company_commercial_reversals reversal
  join public.learning_company_commercial_reversal_ledger_entries entry
    on entry.reversal_id = reversal.id
    and entry.account_code = 'asset.company_seller_recovery_receivable'
  where reversal.purchase_id = new.purchase_id;
  select coalesce(sum(receipt.amount_minor),0)::bigint into received_minor
  from public.learning_company_seller_recovery_receipts receipt
  where receipt.purchase_id = new.purchase_id;
  if receivable_minor <= 0 or new.amount_minor > receivable_minor - received_minor then
    raise exception 'Confirmed recovery exceeds the outstanding seller receivable' using errcode = '23514';
  end if;
  return new;
end;$function$;

create trigger validate_learning_company_seller_recovery_receipt
before insert on public.learning_company_seller_recovery_receipts
for each row execute function public.validate_learning_company_seller_recovery_receipt();

create function public.record_learning_company_seller_recovery_receipt(
  p_purchase_id bigint,p_seller_payee_id uuid,p_amount_minor bigint,
  p_payment_method text,p_payment_reference text,p_operator_id uuid)
returns bigint language plpgsql security definer set search_path to '' as $function$
declare receipt_id bigint;
begin
  if p_purchase_id is null or p_seller_payee_id is null or p_amount_minor is null
     or p_amount_minor <= 0 or p_payment_method not in ('bank_transfer','other')
     or p_payment_reference is null or char_length(btrim(p_payment_reference)) not between 6 and 160
     or btrim(p_payment_reference) !~ '^[A-Za-z0-9][A-Za-z0-9._:/ -]{5,159}$'
     or p_operator_id is null then
    raise exception 'Invalid seller recovery receipt details' using errcode = '22023';
  end if;
  if not exists(select 1 from public.account_capabilities capability
      where capability.user_id = p_operator_id
        and capability.capability = 'admin' and capability.status = 'active') then
    raise exception 'Active Learning Admin required to confirm seller recovery' using errcode = '42501';
  end if;
  insert into public.learning_company_seller_recovery_receipts(
    purchase_id,seller_payee_id,amount_minor,currency,payment_method,payment_reference,recorded_by)
  values(p_purchase_id,p_seller_payee_id,p_amount_minor,'NGN',p_payment_method,
    btrim(p_payment_reference),p_operator_id)
  returning id into receipt_id;

  insert into public.learning_company_seller_recovery_receipt_ledger_entries(
    receipt_id,line_number,account_code,amount_minor,currency)
  values(receipt_id,1,'asset.company_seller_recovery_cash_clearing',p_amount_minor,'NGN'),
    (receipt_id,2,'asset.company_seller_recovery_receivable',-p_amount_minor,'NGN');

  insert into public.learning_audit_events(
    actor_user_id,actor_role,action,entity_type,entity_id,metadata)
  values(p_operator_id,'admin_operator','company_seller_recovery.receipt_confirmed',
    'learning_company_paid_course_purchase',p_purchase_id::text,
    jsonb_build_object('receipt_id',receipt_id,'amount_minor',p_amount_minor,
      'currency','NGN','payment_method',p_payment_method));
  return receipt_id;
end;$function$;

create function public.list_learning_company_seller_recovery_balances()
returns table(
  purchase_id bigint,seller_payee_id uuid,booked_minor bigint,
  recovered_minor bigint,outstanding_minor bigint,currency text)
language sql stable security definer set search_path to '' as $function$
  with receivables as (
    select reversal.purchase_id,sale.seller_payee_id,sale.currency,
      sum(entry.amount_minor)::bigint as booked_minor
    from public.learning_company_commercial_reversals reversal
    join public.learning_company_commercial_reversal_ledger_entries entry
      on entry.reversal_id = reversal.id
      and entry.account_code = 'asset.company_seller_recovery_receivable'
    join public.learning_company_commercial_sales sale on sale.purchase_id = reversal.purchase_id
    group by reversal.purchase_id,sale.seller_payee_id,sale.currency
  ), receipts as (
    select receipt.purchase_id,sum(receipt.amount_minor)::bigint as recovered_minor
    from public.learning_company_seller_recovery_receipts receipt
    group by receipt.purchase_id
  )
  select receivable.purchase_id,receivable.seller_payee_id,receivable.booked_minor,
    coalesce(receipt.recovered_minor,0)::bigint,
    (receivable.booked_minor - coalesce(receipt.recovered_minor,0))::bigint,
    receivable.currency
  from receivables receivable
  left join receipts receipt on receipt.purchase_id = receivable.purchase_id;
$function$;

