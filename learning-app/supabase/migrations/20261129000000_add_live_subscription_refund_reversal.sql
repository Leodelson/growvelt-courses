create table public.learning_subscription_refund_cases (
  id bigint generated by default as identity primary key,
  case_reference uuid not null unique default gen_random_uuid(),
  invoice_id uuid not null references public.learning_subscription_invoices(id) on delete restrict,
  status text not null default 'requested' check (status in (
    'requested','submitting','pending','processing','needs_attention','processed','failed','cancelled'
  )),
  amount_minor bigint not null check (amount_minor > 0),
  currency text not null check (currency='NGN'),
  reason_code text not null check (reason_code ~ '^[a-z][a-z0-9_]{1,60}$'),
  operator_note text not null check (char_length(operator_note) between 3 and 2000),
  idempotency_key uuid not null unique,
  initiated_by uuid references public.profiles(id) on delete set null,
  provider text not null default 'paystack' check (provider='paystack'),
  provider_transaction_id text not null check (provider_transaction_id ~ '^[1-9][0-9]{0,39}$'),
  provider_transaction_reference text not null check (char_length(btrim(provider_transaction_reference)) between 1 and 100),
  provider_case_id text,
  provider_case_reference text,
  provider_status text check (provider_status is null or provider_status in ('requested','pending','processing','needs-attention','failed','processed')),
  provider_refunded_amount_minor bigint check (provider_refunded_amount_minor is null or provider_refunded_amount_minor > 0),
  requested_at timestamptz not null default now(),
  provider_submitted_at timestamptz,
  last_verified_at timestamptz,
  processed_at timestamptz,
  failed_at timestamptz,
  resolved_at timestamptz,
  failure_message text check (failure_message is null or char_length(failure_message) <= 2000),
  updated_at timestamptz not null default now(),
  constraint learning_subscription_refund_case_resolution_check check (
    (status in ('requested','submitting','pending','processing','needs_attention') and resolved_at is null)
    or (status in ('processed','failed','cancelled') and resolved_at is not null)
  )
);

