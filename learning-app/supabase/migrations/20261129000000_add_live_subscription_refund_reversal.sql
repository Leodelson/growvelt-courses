create or replace function public.prevent_learning_commercial_allocation_mutation()
returns trigger language plpgsql security definer set search_path to '' as $function$
begin
  if tg_op='DELETE' then raise exception 'Commercial allocation history is retained and cannot be deleted' using errcode='42501'; end if;
  if old.order_id is distinct from new.order_id
    or old.subscription_invoice_id is distinct from new.subscription_invoice_id
    or old.commercial_terms_version is distinct from new.commercial_terms_version
    or old.instructor_id is distinct from new.instructor_id or old.course_id is distinct from new.course_id
    or old.gross_amount_minor is distinct from new.gross_amount_minor or old.platform_commission_minor is distinct from new.platform_commission_minor
    or old.instructor_gross_minor is distinct from new.instructor_gross_minor or old.currency is distinct from new.currency
    or old.allocation_ledger_transaction_id is distinct from new.allocation_ledger_transaction_id then
    raise exception 'Commercial allocation financial identity is immutable' using errcode='42501';
  end if;
  if old.status='allocated' and new.status='reversed' then return new; end if;
  if old.status is distinct from new.status or old.reversal_ledger_transaction_id is distinct from new.reversal_ledger_transaction_id
    or old.reversed_by_case_id is distinct from new.reversed_by_case_id
    or old.reversed_by_subscription_refund_case_id is distinct from new.reversed_by_subscription_refund_case_id
    or old.reversed_at is distinct from new.reversed_at then
    raise exception 'Unsupported commercial allocation transition' using errcode='22023';
  end if;
  return new;
end;$function$;

create or replace function public.prevent_unvalidated_subscription_invoice_earning_release()
returns trigger language plpgsql security definer set search_path to '' as $function$
declare invoice_source uuid;
begin
  if new.status is not distinct from old.status then return new; end if;
  select allocation.subscription_invoice_id into invoice_source
    from public.learning_commercial_allocations allocation where allocation.id=old.allocation_id;
  if invoice_source is not null then
    if new.status in ('available','reserved','paid') then
      raise exception 'Subscription invoice earnings remain held until payout controls are validated'
        using errcode='22023';
    end if;
    if new.status in ('reversed','recoverable') and not exists (
      select 1 from public.learning_subscription_refund_cases refund_case
      where refund_case.invoice_id=invoice_source and refund_case.status='processed'
    ) then
      raise exception 'A verified processed invoice refund is required to reverse subscription earnings'
        using errcode='22023';
    end if;
  end if;
  return new;
end;$function$;

create or replace function public.prevent_learning_subscription_refund_case_identity_change()
returns trigger language plpgsql security definer set search_path to '' as $function$
begin
  if old.invoice_id is distinct from new.invoice_id or old.amount_minor is distinct from new.amount_minor
    or old.currency is distinct from new.currency or old.reason_code is distinct from new.reason_code
    or old.idempotency_key is distinct from new.idempotency_key or old.initiated_by is distinct from new.initiated_by
    or old.provider_transaction_id is distinct from new.provider_transaction_id
    or old.provider_transaction_reference is distinct from new.provider_transaction_reference
    or (old.provider_case_id is not null and old.provider_case_id is distinct from new.provider_case_id) then
    raise exception 'Subscription refund financial identity is immutable' using errcode='42501';
  end if;
  if old.status is distinct from new.status and not (
    (old.status='requested' and new.status in ('submitting','cancelled'))
    or (old.status='submitting' and new.status in ('pending','processing','needs_attention','failed'))
    or (old.status='pending' and new.status in ('processing','needs_attention','processed','failed'))
    or (old.status='processing' and new.status in ('needs_attention','processed','failed'))
    or (old.status='needs_attention' and new.status in ('processing','processed','failed'))
  ) then raise exception 'Unsupported subscription refund case transition' using errcode='22023'; end if;
  new.updated_at:=now();
  return new;
end;$function$;

create trigger prevent_learning_subscription_refund_case_identity
before update on public.learning_subscription_refund_cases
for each row execute function public.prevent_learning_subscription_refund_case_identity_change();

create or replace function public.request_paystack_live_subscription_full_refund(
  p_invoice_reference text,p_operator_id uuid,p_idempotency_key uuid,p_confirmation text,
  p_reason_code text,p_operator_note text
) returns table(case_id bigint,status text,amount_minor bigint,currency text,
  provider_transaction_id text,provider_transaction_reference text)
language plpgsql security definer set search_path to '' as $function$
declare invoice_row public.learning_subscription_invoices%rowtype; existing_case public.learning_subscription_refund_cases%rowtype; case_key bigint;
begin
  if not exists(select 1 from public.account_capabilities capability
    where capability.user_id=p_operator_id and capability.capability='admin' and capability.status='active') then
    raise exception 'Active administrator required' using errcode='42501';
  end if;
  if p_invoice_reference is null or p_invoice_reference !~ '^GS-[A-F0-9]{32}$'
    or p_confirmation is distinct from p_invoice_reference
    or p_idempotency_key is null or p_reason_code is null or p_reason_code !~ '^[a-z][a-z0-9_]{1,60}$'
    or p_operator_note is null or char_length(btrim(p_operator_note)) not between 3 and 2000 then
    raise exception 'Invalid subscription refund request' using errcode='22023';
  end if;
  select * into invoice_row from public.learning_subscription_invoices invoice
    where invoice.provider_reference=p_invoice_reference for update;
  if not found or invoice_row.payment_domain<>'live' or invoice_row.status<>'paid'
    or invoice_row.provider_transaction_id is null or invoice_row.provider_transaction_reference is null
    or not exists(select 1 from public.learning_subscriptions subscription
      where subscription.id=invoice_row.subscription_id and subscription.learner_id is not null
        and subscription.payment_domain='live') then
    raise exception 'A verified paid Live subscription invoice is required' using errcode='22023';
  end if;
  select * into existing_case from public.learning_subscription_refund_cases refund_case
    where refund_case.idempotency_key=p_idempotency_key;
  if found then
    if existing_case.invoice_id<>invoice_row.id or existing_case.initiated_by is distinct from p_operator_id then
      raise exception 'Subscription refund idempotency key conflicts with another request' using errcode='23505';
    end if;
    return query select existing_case.id,existing_case.status,existing_case.amount_minor,existing_case.currency,
      existing_case.provider_transaction_id,existing_case.provider_transaction_reference;
    return;
  end if;
  insert into public.learning_subscription_refund_cases(
    invoice_id,amount_minor,currency,reason_code,operator_note,idempotency_key,initiated_by,
    provider_transaction_id,provider_transaction_reference
  ) values (
    invoice_row.id,invoice_row.amount_minor,invoice_row.currency,p_reason_code,btrim(p_operator_note),p_idempotency_key,p_operator_id,
    invoice_row.provider_transaction_id,invoice_row.provider_transaction_reference
  ) returning id into case_key;
  insert into public.learning_subscription_refund_case_events(refund_case_id,event_type,to_status,actor_user_id,metadata)
    values(case_key,'refund.requested','requested',p_operator_id,
      jsonb_build_object('invoice_reference',invoice_row.provider_reference,'amount_minor',invoice_row.amount_minor));
  insert into public.learning_audit_events(actor_user_id,actor_role,action,entity_type,entity_id,metadata)
    values(p_operator_id,'admin_operator','subscription_refund.requested','subscription_refund_case',case_key::text,
      jsonb_build_object('invoice_id',invoice_row.id,'amount_minor',invoice_row.amount_minor,'currency',invoice_row.currency));
  return query select case_key,'requested'::text,invoice_row.amount_minor,invoice_row.currency,
    invoice_row.provider_transaction_id,invoice_row.provider_transaction_reference;
end;$function$;

create or replace function public.mark_paystack_live_subscription_refund_submitting(p_case_id bigint,p_operator_id uuid)
returns text language plpgsql security definer set search_path to '' as $function$
declare case_row public.learning_subscription_refund_cases%rowtype;
begin
  if not exists(select 1 from public.account_capabilities where user_id=p_operator_id and capability='admin' and status='active') then
    raise exception 'Active administrator required' using errcode='42501';
  end if;
  select * into case_row from public.learning_subscription_refund_cases where id=p_case_id for update;
  if not found then raise exception 'Subscription refund case not found' using errcode='P0002'; end if;
  if case_row.status<>'requested' then
    return case when case_row.status='submitting' then 'already_submitting' else case_row.status end;
  end if;
  update public.learning_subscription_refund_cases set status='submitting' where id=p_case_id;
  insert into public.learning_subscription_refund_case_events(refund_case_id,event_type,from_status,to_status,actor_user_id)
    values(p_case_id,'refund.submitting','requested','submitting',p_operator_id);
  return 'submitting';
end;$function$;

create or replace function public.record_paystack_live_subscription_refund_submission(
  p_case_id bigint,p_provider_case_id text,p_provider_status text,p_provider_reference text,
  p_operator_id uuid,p_failure_message text default null
) returns text language plpgsql security definer set search_path to '' as $function$
declare case_row public.learning_subscription_refund_cases%rowtype; normalized text; next_status text;
begin
  if not exists(select 1 from public.account_capabilities where user_id=p_operator_id and capability='admin' and status='active') then
    raise exception 'Active administrator required' using errcode='42501';
  end if;
  normalized:=replace(lower(trim(p_provider_status)),'_','-');
  if normalized not in ('pending','processing','needs-attention','failed','processed')
    or (p_provider_case_id is not null and p_provider_case_id !~ '^[0-9]{1,40}$')
    or (p_provider_reference is not null and char_length(p_provider_reference)>160)
    or (p_failure_message is not null and char_length(p_failure_message)>2000) then
    raise exception 'Invalid subscription refund submission result' using errcode='22023';
  end if;
  select * into case_row from public.learning_subscription_refund_cases where id=p_case_id for update;
  if not found then raise exception 'Subscription refund case not found' using errcode='P0002'; end if;
  if case_row.status not in ('submitting','pending','processing','needs_attention') then return case_row.status; end if;
  -- The create-response status is not enough to terminally resolve a refund.
  -- Keep even a provider-reported failure reviewable until Fetch Refund confirms it.
  next_status:=case normalized when 'pending' then 'pending' when 'processing' then 'processing'
    when 'needs-attention' then 'needs_attention' when 'failed' then 'needs_attention' else 'processing' end;
  update public.learning_subscription_refund_cases set status=next_status,provider_case_id=coalesce(provider_case_id,p_provider_case_id),
    provider_case_reference=coalesce(provider_case_reference,p_provider_reference),provider_status=normalized,
    provider_submitted_at=coalesce(provider_submitted_at,now()),failed_at=case when next_status='failed' then now() else failed_at end,
    resolved_at=case when next_status='failed' then now() else null end,failure_message=p_failure_message
  where id=p_case_id;
  insert into public.learning_subscription_refund_case_events(refund_case_id,event_type,from_status,to_status,actor_user_id,metadata)
    values(p_case_id,'refund.'||replace(normalized,'-','_'),case_row.status,next_status,p_operator_id,
      jsonb_build_object('provider_refund_id',p_provider_case_id,'provider_status',normalized));
  return next_status;
end;$function$;

create or replace function public.receive_paystack_live_subscription_refund_verification(
  p_case_id bigint,p_provider_event_id text,p_payload_digest text,p_verification_source text,
  p_provider_case_id text,p_provider_reference text,p_provider_status text,p_amount_minor bigint,
  p_currency text,p_domain text,p_transaction_id text,p_transaction_reference text,
  p_payload jsonb,p_operator_id uuid
) returns bigint language plpgsql security definer set search_path to '' as $function$
declare case_row public.learning_subscription_refund_cases%rowtype; invoice_row public.learning_subscription_invoices%rowtype;
  subscription_key uuid; event_key bigint; normalized text;
begin
  if not exists(select 1 from public.account_capabilities where user_id=p_operator_id and capability='admin' and status='active') then
    raise exception 'Active administrator required' using errcode='42501';
  end if;
  normalized:=replace(lower(trim(p_provider_status)),'_','-');
  if p_provider_event_id is null or char_length(btrim(p_provider_event_id)) not between 1 and 160
    or p_payload_digest !~ '^[a-f0-9]{64}$' or p_verification_source<>'provider_api'
    or normalized not in ('pending','processing','needs-attention','failed','processed')
    or p_currency<>'NGN' or p_domain<>'live' or p_payload is null or jsonb_typeof(p_payload)<>'object' then
    raise exception 'Invalid Live subscription refund verification evidence' using errcode='22023';
  end if;
  select * into case_row from public.learning_subscription_refund_cases where id=p_case_id for update;
  if not found or case_row.status not in ('submitting','pending','processing','needs_attention') then
    raise exception 'Subscription refund case is not awaiting provider verification' using errcode='22023';
  end if;
  select * into invoice_row from public.learning_subscription_invoices where id=case_row.invoice_id for update;
  select subscription_id into subscription_key from public.learning_subscription_invoices where id=invoice_row.id;
  if invoice_row.status<>'paid' or invoice_row.payment_domain<>'live'
    or (normalized='processed' and (p_provider_case_id is null or p_provider_case_id !~ '^[0-9]{1,40}$'))
    or p_provider_case_id is distinct from case_row.provider_case_id
    or p_transaction_id is distinct from case_row.provider_transaction_id
    or p_transaction_reference is distinct from case_row.provider_transaction_reference
    or p_amount_minor is distinct from case_row.amount_minor
    or p_payload->>'domain' is distinct from 'live' or p_payload->>'currency' is distinct from 'NGN'
    or replace(lower(coalesce(p_payload->>'status','')),'_','-') is distinct from normalized
    or (p_payload->>'transaction_id') is distinct from case_row.provider_transaction_id
    or (p_payload->>'transaction_reference') is distinct from case_row.provider_transaction_reference
    or (p_payload->>'refund_id') is distinct from p_provider_case_id
    or (p_provider_reference is not null and p_payload->>'refund_reference' is distinct from p_provider_reference)
    or nullif(p_payload->>'amount_minor','')::bigint is distinct from case_row.amount_minor then
    raise exception 'Refund verification does not match the paid invoice and exact provider charge' using errcode='23514';
  end if;
  insert into public.learning_subscription_provider_events(
    provider_event_id,event_type,payload_digest,sanitized_payload,signature_valid,payment_domain,
    subscription_id,invoice_id,processing_status,verification_source,subscription_refund_case_id
  ) values (
    p_provider_event_id,'refund.'||normalized,p_payload_digest,p_payload,false,'live',
    subscription_key,invoice_row.id,'received','provider_api',p_case_id
  ) returning id into event_key;
  update public.learning_subscription_refund_cases set provider_status=normalized,
    provider_refunded_amount_minor=p_amount_minor,last_verified_at=now(),
    status=case when normalized='failed' then 'failed' else case when normalized='pending' then 'pending'
      when normalized='needs-attention' then 'needs_attention' else 'processing' end end,
    failed_at=case when normalized='failed' then now() else failed_at end,
    resolved_at=case when normalized='failed' then now() else null end
  where id=p_case_id;
  insert into public.learning_subscription_refund_case_events(refund_case_id,event_type,from_status,to_status,
    provider_event_id,actor_user_id,metadata)
  values(p_case_id,'refund.'||replace(normalized,'-','_'),case_row.status,
    case when normalized='failed' then 'failed' when normalized='pending' then 'pending'
      when normalized='needs-attention' then 'needs_attention' else 'processing' end,
    event_key,p_operator_id,jsonb_build_object('verification_source','provider_api','provider_refund_id',p_provider_case_id));
  return event_key;
end;$function$;

create or replace function public.reverse_learning_subscription_invoice_allocation(
  p_invoice_id uuid,p_refund_case_id bigint,p_reason text,p_actor_user_id uuid default null
) returns bigint language plpgsql security definer set search_path to '' as $function$
declare allocation_row public.learning_commercial_allocations%rowtype; earning_row public.learning_instructor_earnings%rowtype;
  refund_row public.learning_subscription_refund_cases%rowtype; ledger_key bigint; instructor_account text;
begin
  select * into refund_row from public.learning_subscription_refund_cases
    where id=p_refund_case_id and invoice_id=p_invoice_id and status='processed' for update;
  if not found then raise exception 'Verified processed invoice refund case is required' using errcode='42501'; end if;
  select * into allocation_row from public.learning_commercial_allocations
    where subscription_invoice_id=p_invoice_id for update;
  if not found then raise exception 'Subscription invoice commercial allocation is missing' using errcode='23514'; end if;
  if allocation_row.status='reversed' then
    if allocation_row.reversed_by_subscription_refund_case_id=p_refund_case_id then return allocation_row.reversal_ledger_transaction_id; end if;
    raise exception 'Subscription invoice allocation was reversed by another case' using errcode='23514';
  end if;
  select * into earning_row from public.learning_instructor_earnings where allocation_id=allocation_row.id for update;
  if not found then raise exception 'Subscription invoice allocation has no instructor earning' using errcode='23514'; end if;
  instructor_account:=case earning_row.status when 'held' then 'liability.instructor_earnings_held'
    when 'available' then 'liability.instructor_earnings_available'
    when 'reserved' then 'liability.instructor_earnings_reserved'
    when 'paid' then 'asset.instructor_earnings_recoverable' else null end;
  if instructor_account is null then raise exception 'Subscription instructor earning is not reversible from its current state' using errcode='22023'; end if;
  insert into public.learning_ledger_transactions(subscription_invoice_id,subscription_refund_case_id,
    transaction_type,currency,description,created_by)
  values(p_invoice_id,p_refund_case_id,'instructor_earnings_reversal',allocation_row.currency,
    'Compensating subscription commercial allocation reversal: '||left(trim(p_reason),900),p_actor_user_id)
  returning id into ledger_key;
  insert into public.learning_ledger_entries(transaction_id,line_number,account_code,amount_minor,currency,counterparty_type,counterparty_reference) values
    (ledger_key,1,'revenue.platform_commission',allocation_row.platform_commission_minor,allocation_row.currency,'commercial_allocation',allocation_row.id::text),
    (ledger_key,2,instructor_account,allocation_row.instructor_gross_minor,allocation_row.currency,'instructor_earning',earning_row.id::text),
    (ledger_key,3,'liability.marketplace_sales_unallocated',-allocation_row.gross_amount_minor,allocation_row.currency,'subscription_refund_case',p_refund_case_id::text);
  update public.learning_commercial_allocations set status='reversed',reversal_ledger_transaction_id=ledger_key,
    reversed_at=now(),reversed_by_subscription_refund_case_id=p_refund_case_id where id=allocation_row.id;
  if earning_row.status='paid' then
    update public.learning_instructor_earnings set status='recoverable',reversed_at=now(),
      recoverable_amount_minor=earning_row.gross_amount_minor,hold_reason='Subscription invoice refund after payout' where id=earning_row.id;
    insert into public.learning_instructor_earning_events(earning_id,event_type,from_status,to_status,
      ledger_transaction_id,actor_user_id,metadata,subscription_refund_case_id)
    values(earning_row.id,'earning.recoverable','paid','recoverable',ledger_key,p_actor_user_id,
      jsonb_build_object('reason',p_reason,'source','subscription_invoice'),p_refund_case_id);
  else
    update public.learning_instructor_earnings set status='reversed',reversed_at=now(),hold_reason='Subscription invoice refund' where id=earning_row.id;
    insert into public.learning_instructor_earning_events(earning_id,event_type,from_status,to_status,
      ledger_transaction_id,actor_user_id,metadata,subscription_refund_case_id)
    values(earning_row.id,'earning.reversed',earning_row.status,'reversed',ledger_key,p_actor_user_id,
      jsonb_build_object('reason',p_reason,'source','subscription_invoice'),p_refund_case_id);
  end if;
  insert into public.learning_audit_events(actor_user_id,actor_role,action,entity_type,entity_id,metadata)
    values(p_actor_user_id,case when p_actor_user_id is null then 'payment_system' else 'admin_operator' end,
      'subscription_commercial_allocation.reversed','commercial_allocation',allocation_row.id::text,
      jsonb_build_object('subscription_invoice_id',p_invoice_id,'refund_case_id',p_refund_case_id,'ledger_transaction_id',ledger_key));
  return ledger_key;
end;$function$;

create or replace function public.process_paystack_live_subscription_refund_event(p_event_id bigint)
returns table(outcome text,refund_case_id bigint,invoice_id uuid,ledger_transaction_id bigint)
language plpgsql security definer set search_path to '' as $function$
declare event_row public.learning_subscription_provider_events%rowtype; case_row public.learning_subscription_refund_cases%rowtype;
  invoice_row public.learning_subscription_invoices%rowtype; subscription_row public.learning_subscriptions%rowtype;
  refund_ledger_key bigint; amount_minor bigint;
begin
  select * into event_row from public.learning_subscription_provider_events where id=p_event_id for update;
  if not found then raise exception 'Subscription refund provider evidence was not found' using errcode='P0002'; end if;
  if event_row.processing_status='processed' then
    select * into case_row from public.learning_subscription_refund_cases where id=event_row.subscription_refund_case_id;
    select id into refund_ledger_key from public.learning_ledger_transactions
      where subscription_refund_case_id=case_row.id and transaction_type='refund';
    return query select 'already_processed',case_row.id,case_row.invoice_id,refund_ledger_key;
    return;
  end if;
  if event_row.subscription_refund_case_id is null or event_row.invoice_id is null
    or event_row.payment_domain<>'live' or event_row.event_type<>'refund.processed'
    or not (event_row.signature_valid or event_row.verification_source='provider_api') then
    raise exception 'Only exact verified Live processed-refund evidence can finalize a subscription refund' using errcode='42501';
  end if;
  select refund_case.* into case_row from public.learning_subscription_refund_cases refund_case
    where refund_case.id=event_row.subscription_refund_case_id
      and refund_case.invoice_id=event_row.invoice_id for update;
  if not found then raise exception 'Refund evidence does not match a subscription refund case' using errcode='23514'; end if;
  select * into invoice_row from public.learning_subscription_invoices where id=case_row.invoice_id for update;
  select * into subscription_row from public.learning_subscriptions where id=invoice_row.subscription_id for share;
  amount_minor:=nullif(event_row.sanitized_payload->>'amount_minor','')::bigint;
  if case_row.status not in ('processing','pending','needs_attention') or case_row.provider_status<>'processed'
    or event_row.sanitized_payload->>'domain'<>'live' or event_row.sanitized_payload->>'currency'<>'NGN'
    or event_row.sanitized_payload->>'transaction_reference' is distinct from case_row.provider_transaction_reference
    or event_row.sanitized_payload->>'transaction_id' is distinct from case_row.provider_transaction_id
    or event_row.sanitized_payload->>'refund_id' is distinct from case_row.provider_case_id
    or amount_minor is distinct from case_row.amount_minor or amount_minor is distinct from invoice_row.amount_minor
    or invoice_row.status<>'paid' or invoice_row.payment_domain<>'live'
    or subscription_row.payment_domain<>'live' then
    raise exception 'Processed refund evidence does not exactly match its paid Live invoice' using errcode='23514';
  end if;
  if exists(select 1 from public.learning_ledger_transactions where subscription_refund_case_id=case_row.id and transaction_type='refund') then
    raise exception 'Subscription refund already has a financial reversal' using errcode='23505';
  end if;
  update public.learning_subscription_refund_cases refund_case set status='processed',provider_status='processed',
    provider_refunded_amount_minor=case_row.amount_minor,processed_at=coalesce(refund_case.processed_at,now()),
    resolved_at=coalesce(refund_case.resolved_at,now()),last_verified_at=now() where refund_case.id=case_row.id;
  perform public.reverse_learning_subscription_invoice_allocation(invoice_row.id,case_row.id,
    'processed Paystack full subscription invoice refund',case_row.initiated_by);
  insert into public.learning_ledger_transactions(subscription_invoice_id,subscription_refund_case_id,
    transaction_type,currency,description,created_by)
  values(invoice_row.id,case_row.id,'refund',invoice_row.currency,'Processed full subscription invoice refund',case_row.initiated_by)
  returning id into refund_ledger_key;
  insert into public.learning_ledger_entries(transaction_id,line_number,account_code,amount_minor,currency,counterparty_type,counterparty_reference) values
    (refund_ledger_key,1,'liability.marketplace_sales_unallocated',amount_minor,invoice_row.currency,'subscription_refund_case',case_row.case_reference::text),
    (refund_ledger_key,2,'asset.paystack_receivable',-amount_minor,invoice_row.currency,'payment_provider',coalesce(case_row.provider_case_id,case_row.provider_case_reference));
  update public.learning_subscription_invoices set status='refunded',terminal_at=coalesce(terminal_at,now())
    where id=invoice_row.id and status='paid';
  if not found then raise exception 'Paid invoice could not be transitioned to refunded' using errcode='23514'; end if;
  update public.learning_subscription_provider_events set processing_status='processed',processed_at=now()
    where id=p_event_id;
  insert into public.learning_subscription_refund_case_events(refund_case_id,event_type,from_status,to_status,
    provider_event_id,actor_user_id,metadata)
  values(case_row.id,'refund.processed',case_row.status,'processed',p_event_id,case_row.initiated_by,
    jsonb_build_object('invoice_id',invoice_row.id,'amount_minor',amount_minor,'ledger_transaction_id',refund_ledger_key));
  insert into public.learning_audit_events(actor_user_id,actor_role,action,entity_type,entity_id,metadata)
  values(case_row.initiated_by,case when case_row.initiated_by is null then 'payment_system' else 'admin_operator' end,
    'subscription_refund.processed','subscription_refund_case',case_row.id::text,
    jsonb_build_object('invoice_id',invoice_row.id,'amount_minor',amount_minor,'ledger_transaction_id',refund_ledger_key));
  return query select 'refunded',case_row.id,invoice_row.id,refund_ledger_key;
end;$function$;

create or replace function public.list_learning_live_subscription_refund_operations(
  p_operator_id uuid,p_query text default null,p_limit integer default 50
) returns table(
  invoice_id uuid,invoice_reference text,subscription_id uuid,learner_email text,plan_name text,
  amount_minor bigint,currency text,invoice_status text,provider_transaction_id text,
  provider_transaction_reference text,paid_at timestamptz,created_at timestamptz,
  refund_case_id bigint,refund_case_reference uuid,refund_status text,refund_provider_status text,
  refund_provider_case_id text,refund_provider_case_reference text,refund_requested_at timestamptz
) language plpgsql stable security definer set search_path to '' as $function$
declare search_term text:=nullif(btrim(p_query),'');
begin
  if not exists(select 1 from public.account_capabilities capability where capability.user_id=p_operator_id
    and capability.capability='admin' and capability.status='active') then
    raise exception 'Active administrator required' using errcode='42501';
  end if;
  if (search_term is not null and char_length(search_term)>200) or p_limit is null or p_limit not between 1 and 100 then
    raise exception 'Invalid subscription refund operations query' using errcode='22023';
  end if;
  return query
    select invoice.id,invoice.provider_reference,invoice.subscription_id,profile.email,
      invoice.plan_name_snapshot,invoice.amount_minor,invoice.currency,invoice.status,
      invoice.provider_transaction_id,invoice.provider_transaction_reference,invoice.paid_at,invoice.created_at,
      latest_case.id,latest_case.case_reference,latest_case.status,latest_case.provider_status,
      latest_case.provider_case_id,latest_case.provider_case_reference,latest_case.requested_at
    from public.learning_subscription_invoices invoice
    join public.learning_subscriptions subscription on subscription.id=invoice.subscription_id
    left join public.profiles profile on profile.id=subscription.learner_id
    left join lateral (
      select refund_case.id,refund_case.case_reference,refund_case.status,refund_case.provider_status,
        refund_case.provider_case_id,refund_case.provider_case_reference,refund_case.requested_at
      from public.learning_subscription_refund_cases refund_case
      where refund_case.invoice_id=invoice.id
      order by refund_case.requested_at desc,refund_case.id desc limit 1
    ) latest_case on true
    where invoice.payment_domain='live' and invoice.provider_transaction_id is not null
      and invoice.provider_transaction_reference is not null
      and (search_term is null or invoice.provider_reference ilike '%'||search_term||'%'
        or invoice.provider_transaction_reference ilike '%'||search_term||'%'
        or coalesce(profile.email,'') ilike '%'||search_term||'%'
        or invoice.plan_name_snapshot ilike '%'||search_term||'%')
    order by coalesce(invoice.paid_at,invoice.created_at) desc,invoice.id desc
    limit p_limit;
end;$function$;

create or replace function public.list_learning_live_subscription_refund_case_events(
  p_operator_id uuid,p_case_ids bigint[] default null
) returns table(
  event_id bigint,refund_case_id bigint,event_type text,from_status text,to_status text,
  actor_user_id uuid,provider_event_id bigint,metadata jsonb,occurred_at timestamptz
) language plpgsql stable security definer set search_path to '' as $function$
begin
  if not exists(select 1 from public.account_capabilities capability where capability.user_id=p_operator_id
    and capability.capability='admin' and capability.status='active') then
    raise exception 'Active administrator required' using errcode='42501';
  end if;
  if p_case_ids is not null and cardinality(p_case_ids)>100 then
    raise exception 'Too many subscription refund cases requested' using errcode='22023';
  end if;
  return query select event_row.id,event_row.refund_case_id,event_row.event_type,event_row.from_status,
    event_row.to_status,event_row.actor_user_id,event_row.provider_event_id,event_row.metadata,event_row.occurred_at
  from public.learning_subscription_refund_case_events event_row
  where p_case_ids is null or event_row.refund_case_id=any(p_case_ids)
  order by event_row.refund_case_id,event_row.occurred_at,event_row.id;
end;$function$;

