create function public.begin_learning_instructor_live_payout_batch_transfer(
  p_batch_id bigint,p_actor_user_id uuid,p_idempotency_key text
)
returns table(attempt_id bigint,attempt_reference text,recipient_code text,amount_minor bigint,currency text,
  transfer_submission_needed boolean)
language plpgsql security definer set search_path to '' as $function$
declare batch_row public.learning_instructor_payout_batches%rowtype;
        profile_row public.learning_instructor_payout_profiles%rowtype;
        prior_attempt public.learning_instructor_payout_batch_attempts%rowtype;
        member_row record; next_number integer; new_attempt_id bigint; new_reference text;
        checked_total bigint:=0; actual_total bigint;
begin
  if p_batch_id is null or p_actor_user_id is null or p_idempotency_key is null
    or p_idempotency_key !~ '^[a-z][a-z0-9:_-]{2,120}$'
    or not exists(select 1 from public.account_capabilities c
      where c.user_id=p_actor_user_id and c.capability='admin' and c.status='active') then
    raise exception 'Valid administrator and payout batch required' using errcode='42501';
  end if;
  select * into batch_row from public.learning_instructor_payout_batches b
    where b.id=p_batch_id for update;
  if not found then raise exception 'Payout batch not found' using errcode='P0002'; end if;
  select * into prior_attempt from public.learning_instructor_payout_batch_attempts a
    where a.idempotency_key=p_idempotency_key;
  if found then
    if prior_attempt.batch_id<>batch_row.id then
      raise exception 'Payout attempt idempotency conflict' using errcode='23505';
    end if;
    if prior_attempt.status<>'submitting' or prior_attempt.provider_transfer_id is not null then
      raise exception 'Payout attempt was already submitted or resolved; verify its reference' using errcode='22023';
    end if;
    return query select prior_attempt.id,prior_attempt.attempt_reference,
      prior_attempt.recipient_code,prior_attempt.amount_minor,prior_attempt.currency,false;
    return;
  end if;
  if batch_row.status not in ('assembled','failed') then
    raise exception 'Payout batch is not available for a new transfer attempt' using errcode='22023';
  end if;
  select * into prior_attempt from public.learning_instructor_payout_batch_attempts a
    where a.batch_id=batch_row.id order by a.attempt_number desc limit 1 for update;
  if found and prior_attempt.status not in ('failed') then
    raise exception 'Previous payout attempt has no safe retry status; verify before retry' using errcode='22023';
  end if;
  if found and prior_attempt.attempt_number>=100 then
    raise exception 'Payout retry limit reached; manual review required' using errcode='22023';
  end if;
  next_number:=coalesce(prior_attempt.attempt_number,0)+1;
  new_reference:='lpb-live-batch-'||batch_row.id::text||'-a'||next_number::text;

  select * into profile_row from public.learning_instructor_payout_profiles p
    where p.id=batch_row.payout_profile_id for update;
  if not found or profile_row.instructor_id<>batch_row.instructor_id
    or profile_row.provider<>'paystack' or profile_row.provider_domain<>'live'
    or profile_row.status<>'active' or profile_row.currency<>batch_row.currency then
    raise exception 'Active matching Live payout profile required' using errcode='22023';
  end if;
  if not exists(select 1 from public.learning_instructor_payout_batch_members m
    where m.batch_id=batch_row.id) then
    raise exception 'Payout batch has no members' using errcode='23514';
  end if;
  lock table public.learning_payment_cases in share row exclusive mode;
  for member_row in
    select m.earning_id,m.reservation_id,m.amount_minor,r.status reservation_status,
      r.future_payout_item_reference,e.status earning_status,e.instructor_id earning_instructor,
      e.gross_amount_minor,e.currency earning_currency,a.id allocation_id,a.status allocation_status,
      a.instructor_id allocation_instructor,a.instructor_gross_minor,a.currency allocation_currency,
      o.id order_id,o.status order_status,o.gross_amount_minor order_gross,o.currency order_currency
    from public.learning_instructor_payout_batch_members m
    join public.learning_instructor_earning_reservations r on r.id=m.reservation_id
    join public.learning_instructor_earnings e on e.id=m.earning_id
    join public.learning_commercial_allocations a on a.id=e.allocation_id
    join public.learning_orders o on o.id=a.order_id
    where m.batch_id=batch_row.id order by m.earning_id
  loop
    perform 1 from public.learning_instructor_earning_reservations r
      where r.id=member_row.reservation_id for update;
    perform 1 from public.learning_instructor_earnings e
      where e.id=member_row.earning_id for update;
    perform 1 from public.learning_commercial_allocations a
      where a.id=member_row.allocation_id for update;
    perform 1 from public.learning_orders o where o.id=member_row.order_id for update;
    if member_row.reservation_status<>'reserved'
      or member_row.future_payout_item_reference<>'lpb-'||batch_row.id::text||'-earning-'||member_row.earning_id::text
      or member_row.earning_status<>'reserved'
      or member_row.earning_instructor<>batch_row.instructor_id
      or member_row.gross_amount_minor<>member_row.amount_minor
      or member_row.earning_currency<>batch_row.currency
      or member_row.allocation_status<>'allocated'
      or member_row.allocation_instructor<>batch_row.instructor_id
      or member_row.instructor_gross_minor<>member_row.amount_minor
      or member_row.allocation_currency<>batch_row.currency
      or member_row.order_status<>'paid' or member_row.order_currency<>batch_row.currency
      or (select count(*) from public.learning_payment_attempts p
          where p.order_id=member_row.order_id and p.status='succeeded')<>1
      or not exists(select 1 from public.learning_payment_attempts p
          where p.order_id=member_row.order_id and p.status='succeeded'
            and p.provider='paystack' and p.paystack_domain='live'
            and p.amount_minor=member_row.order_gross and p.currency=member_row.order_currency)
      or exists(select 1 from public.learning_payment_cases c
          where c.order_id=member_row.order_id and c.status in
            ('requested','submitting','pending','processing','needs_attention',
             'opened','action_required','submitted','under_review','processed','succeeded','lost')) then
      raise exception 'Payout batch member is no longer eligible for Live transfer' using errcode='22023';
    end if;
    checked_total:=checked_total+member_row.amount_minor;
  end loop;
  select coalesce(sum(m.amount_minor),0)::bigint into actual_total
    from public.learning_instructor_payout_batch_members m where m.batch_id=batch_row.id;
  if checked_total<>batch_row.amount_minor or actual_total<>batch_row.amount_minor
    or checked_total<100000 then
    raise exception 'Payout batch total no longer matches eligible members' using errcode='23514';
  end if;
  insert into public.learning_instructor_payout_batch_attempts(
    batch_id,attempt_number,attempt_reference,idempotency_key,payout_profile_id,
    recipient_code,provider_recipient_id,amount_minor,currency,initiated_by
  ) values(
    batch_row.id,next_number,new_reference,p_idempotency_key,profile_row.id,
    profile_row.recipient_code,profile_row.provider_recipient_id,batch_row.amount_minor,
    batch_row.currency,p_actor_user_id
  ) returning id into new_attempt_id;
  update public.learning_instructor_payout_batches b set status='submitting' where b.id=batch_row.id;
  insert into public.learning_instructor_payout_batch_attempt_events(
    attempt_id,event_type,from_status,to_status,provenance,actor_user_id,metadata
  ) values(new_attempt_id,'payout_batch_attempt.submitting',null,'submitting','admin',p_actor_user_id,
    jsonb_build_object('batch_reference',batch_row.batch_reference,'amount_minor',batch_row.amount_minor,
      'member_count',(select count(*) from public.learning_instructor_payout_batch_members m where m.batch_id=batch_row.id)));
  return query select new_attempt_id,new_reference,profile_row.recipient_code,
    batch_row.amount_minor,batch_row.currency,true;
end;$function$;

create function public.record_learning_instructor_live_payout_batch_transfer(
  p_attempt_id bigint,p_transfer_id text,p_transfer_code text,p_provider_status text,p_actor_user_id uuid
) returns void language plpgsql security definer set search_path to '' as $function$
declare attempt public.learning_instructor_payout_batch_attempts%rowtype;
begin
  if p_actor_user_id is null or not exists(select 1 from public.account_capabilities c
    where c.user_id=p_actor_user_id and c.capability='admin' and c.status='active')
    or p_transfer_id is null or p_transfer_id !~ '^[0-9]+$'
    or p_transfer_code is null or p_transfer_code !~ '^TRF_[A-Za-z0-9]+$'
    or p_provider_status not in ('otp','pending') then
    raise exception 'Valid administrator and transfer identity required' using errcode='42501';
  end if;
  select * into attempt from public.learning_instructor_payout_batch_attempts a
    where a.id=p_attempt_id for update;
  if not found or attempt.status<>'submitting' or attempt.provider_transfer_id is not null then
    raise exception 'Submitting batch transfer attempt required' using errcode='22023';
  end if;
  update public.learning_instructor_payout_batch_attempts a set status='pending',
    provider_transfer_id=p_transfer_id,provider_transfer_code=p_transfer_code,
    provider_status=p_provider_status,provider_received_at=now() where a.id=attempt.id;
  update public.learning_instructor_payout_batches b set status='pending' where b.id=attempt.batch_id;
  insert into public.learning_instructor_payout_batch_attempt_events(
    attempt_id,event_type,from_status,to_status,provenance,actor_user_id,metadata
  ) values(attempt.id,'payout_batch_attempt.pending','submitting','pending','provider_api',p_actor_user_id,
    jsonb_build_object('provider_transfer_id',p_transfer_id,'provider_transfer_code',p_transfer_code,
      'provider_status',p_provider_status));
end;$function$;

create function public.mark_learning_instructor_live_payout_batch_recovery_required(
