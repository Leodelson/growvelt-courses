create function public.begin_learning_instructor_live_payout_batch_otp_finalization(
  p_attempt_id bigint,p_actor_user_id uuid
) returns table(otp_attempt_id bigint,attempt_reference text,transfer_code text,transfer_id text,
  amount_minor bigint,currency text)
language plpgsql security definer set search_path to '' as $function$
declare attempt public.learning_instructor_payout_batch_attempts%rowtype;
        batch_row public.learning_instructor_payout_batches%rowtype;
        otp_id bigint;
begin
  if p_actor_user_id is null or not exists(select 1 from public.account_capabilities c
    where c.user_id=p_actor_user_id and c.capability='admin' and c.status='active') then
    raise exception 'Active administrator required' using errcode='42501';
  end if;
  select * into attempt from public.learning_instructor_payout_batch_attempts a
    where a.id=p_attempt_id for update;
  select * into batch_row from public.learning_instructor_payout_batches b
    where b.id=attempt.batch_id for update;
  if not found or attempt.status<>'pending' or attempt.provider_status<>'otp'
    or attempt.provider_transfer_code is null or attempt.provider_transfer_id is null
    or attempt.initiated_at < now()-interval '25 minutes'
    or exists(select 1 from public.learning_instructor_payout_batch_otp_attempts o where o.attempt_id=attempt.id) then
    raise exception 'Live batch OTP finalization is not available; verify the transfer' using errcode='22023';
  end if;
  lock table public.learning_payment_cases in share row exclusive mode;
  if exists(
    select 1 from public.learning_instructor_payout_batch_members m
    join public.learning_commercial_allocations a on a.id=(select e.allocation_id from public.learning_instructor_earnings e where e.id=m.earning_id)
    join public.learning_orders o on o.id=a.order_id
    join public.learning_payment_cases c on c.order_id=o.id
    where m.batch_id=batch_row.id and c.status in
      ('requested','submitting','pending','processing','needs_attention','opened','action_required','submitted','under_review')
  ) then raise exception 'Active financial protection blocks batch OTP finalization' using errcode='22023'; end if;
  insert into public.learning_instructor_payout_batch_otp_attempts(attempt_id,transfer_code,initiated_by)
    values(attempt.id,attempt.provider_transfer_code,p_actor_user_id) returning id into otp_id;
  insert into public.learning_instructor_payout_batch_attempt_events(
    attempt_id,event_type,from_status,to_status,provenance,actor_user_id,metadata
  ) values(attempt.id,'payout_batch_attempt.otp_finalization_started','pending','pending','admin',p_actor_user_id,
    jsonb_build_object('otp_attempt_id',otp_id));
  return query select otp_id,attempt.attempt_reference,attempt.provider_transfer_code,
    attempt.provider_transfer_id,attempt.amount_minor,attempt.currency;
end;$function$;

create function public.complete_learning_instructor_live_payout_batch_otp_finalization(
  p_otp_attempt_id bigint,p_outcome text,p_actor_user_id uuid
) returns void language plpgsql security definer set search_path to '' as $function$
declare otp_row public.learning_instructor_payout_batch_otp_attempts%rowtype;
begin
  if p_actor_user_id is null or p_outcome not in ('submitted','needs_attention')
    or not exists(select 1 from public.account_capabilities c
      where c.user_id=p_actor_user_id and c.capability='admin' and c.status='active') then
    raise exception 'Valid administrator and OTP outcome required' using errcode='42501';
  end if;
  select * into otp_row from public.learning_instructor_payout_batch_otp_attempts o
    where o.id=p_otp_attempt_id for update;
  if not found or otp_row.status<>'started' then raise exception 'Open OTP attempt required' using errcode='22023'; end if;
  update public.learning_instructor_payout_batch_otp_attempts o
    set status=p_outcome,completed_at=now() where o.id=otp_row.id;
  insert into public.learning_instructor_payout_batch_attempt_events(
    attempt_id,event_type,from_status,to_status,provenance,actor_user_id,metadata
  ) values(otp_row.attempt_id,'payout_batch_attempt.otp_finalization_'||p_outcome,
    'pending','pending','provider_api',p_actor_user_id,jsonb_build_object('otp_attempt_id',otp_row.id));
end;$function$;

