create table public.learning_company_sale_ledger_transactions (
  id bigint generated by default as identity primary key,
  purchase_id bigint not null references public.learning_company_paid_course_purchases(id) on delete restrict,
  transaction_type text not null check (transaction_type in ('payment_capture','commercial_allocation')),
  amount_minor bigint not null check (amount_minor > 0),
  currency text not null check (currency = 'NGN'),
  created_at timestamptz not null default now(),
  unique(purchase_id,transaction_type)
);

create table public.learning_company_sale_ledger_entries (
  id bigint generated by default as identity primary key,
  transaction_id bigint not null references public.learning_company_sale_ledger_transactions(id) on delete restrict,
