create or replace function public.post_learning_company_commercial_sale(p_purchase_id bigint)
returns bigint language plpgsql security definer set search_path to '' as $function$
declare purchase_row public.learning_company_paid_course_purchases%rowtype;
  attempt_row public.learning_company_paid_course_purchase_attempts%rowtype;
  terms_row public.learning_commercial_terms%rowtype;
  captured_count integer; sale_key bigint; capture_key bigint; allocation_key bigint;
  commission_per_seat bigint; seller_per_seat bigint; commission_total bigint; seller_total bigint;
begin
  if p_purchase_id is null then raise exception 'Company purchase is required' using errcode = '22023'; end if;
  select * into purchase_row from public.learning_company_paid_course_purchases
  where id = p_purchase_id for update;
  if not found or purchase_row.status <> 'paid' then
    raise exception 'Verified paid company purchase is required' using errcode = '22023';
  end if;
  select sale.purchase_id into sale_key from public.learning_company_commercial_sales sale
  where sale.purchase_id = purchase_row.id;
  if found then return sale_key; end if;
  -- Older Test Mode purchases intentionally have no seller/terms snapshot.
  -- They require a reviewed historical backfill, not today's terms.
  if purchase_row.seller_payee_id is null or purchase_row.seller_instructor_id is null
     or purchase_row.commercial_terms_version is null then return null; end if;
  select * into attempt_row from public.learning_company_paid_course_purchase_attempts attempt
  where attempt.purchase_id = purchase_row.id and attempt.provider = 'paystack'
    and attempt.status = 'succeeded' for share;
  if not found or attempt_row.provider_transaction_id is null
     or attempt_row.amount_minor <> purchase_row.total_amount_minor
     or attempt_row.currency <> purchase_row.currency then
    raise exception 'Verified company charge does not match its purchase' using errcode = '22023';
  end if;
  if purchase_row.unit_amount_minor * purchase_row.seat_count <> purchase_row.total_amount_minor then
    raise exception 'Company seat amounts do not match the charge' using errcode = '22023';
  end if;
  select count(*) into captured_count from public.learning_company_paid_course_purchase_seats seat
  where seat.purchase_id = purchase_row.id;
  if captured_count <> purchase_row.seat_count then
    raise exception 'Company seat count changed after purchase preparation' using errcode = '22023';
  end if;
  select * into terms_row from public.learning_commercial_terms terms
  where terms.version = purchase_row.commercial_terms_version;
  if not found then raise exception 'Commercial terms snapshot is unavailable' using errcode = '22023'; end if;
  commission_per_seat := round(purchase_row.unit_amount_minor * terms_row.commission_basis_points / 10000.0)::bigint;
  seller_per_seat := purchase_row.unit_amount_minor - commission_per_seat;
  commission_total := commission_per_seat * purchase_row.seat_count;
  seller_total := seller_per_seat * purchase_row.seat_count;

  insert into public.learning_company_sale_ledger_transactions(purchase_id,transaction_type,amount_minor,currency)
  values(purchase_row.id,'payment_capture',purchase_row.total_amount_minor,purchase_row.currency)
  returning id into capture_key;
  insert into public.learning_company_sale_ledger_entries(transaction_id,line_number,account_code,amount_minor,currency)
  values(capture_key,1,'asset.paystack_receivable',purchase_row.total_amount_minor,purchase_row.currency),
        (capture_key,2,'liability.company_sales_unallocated',-purchase_row.total_amount_minor,purchase_row.currency);

  insert into public.learning_company_sale_ledger_transactions(purchase_id,transaction_type,amount_minor,currency)
  values(purchase_row.id,'commercial_allocation',purchase_row.total_amount_minor,purchase_row.currency)
  returning id into allocation_key;
  insert into public.learning_company_sale_ledger_entries(transaction_id,line_number,account_code,amount_minor,currency)
  values(allocation_key,1,'liability.company_sales_unallocated',purchase_row.total_amount_minor,purchase_row.currency);
  if commission_total > 0 then
    insert into public.learning_company_sale_ledger_entries(transaction_id,line_number,account_code,amount_minor,currency)
    values(allocation_key,2,'revenue.platform_commission',-commission_total,purchase_row.currency);
  end if;
  if seller_total > 0 then
    insert into public.learning_company_sale_ledger_entries(transaction_id,line_number,account_code,amount_minor,currency)
    values(allocation_key,3,'liability.company_seller_earnings_held',-seller_total,purchase_row.currency);
  end if;
  if exists(
    select 1 from public.learning_company_sale_ledger_transactions ledger
    join public.learning_company_sale_ledger_entries entry on entry.transaction_id = ledger.id
    where ledger.id in (capture_key,allocation_key)
    group by ledger.id having sum(entry.amount_minor) <> 0 or count(*) < 2
  ) then raise exception 'Company commercial ledger is not balanced' using errcode = '23514'; end if;

  insert into public.learning_company_commercial_sales(
    purchase_id,attempt_id,paystack_domain,provider_reference,provider_transaction_id,
    seller_instructor_id,seller_organization_id,seller_payee_id,commercial_terms_version,
    gross_amount_minor,platform_commission_minor,seller_gross_minor,currency,seat_count,
    capture_ledger_transaction_id,allocation_ledger_transaction_id)
  values(purchase_row.id,attempt_row.id,attempt_row.paystack_domain,attempt_row.provider_reference,
    attempt_row.provider_transaction_id,purchase_row.seller_instructor_id,purchase_row.seller_organization_id,
    purchase_row.seller_payee_id,purchase_row.commercial_terms_version,purchase_row.total_amount_minor,
    commission_total,seller_total,purchase_row.currency,purchase_row.seat_count,capture_key,allocation_key);
  insert into public.learning_company_commercial_sale_lines(
    purchase_id,assigned_user_id,course_id,unit_amount_minor,platform_commission_minor,seller_gross_minor,currency)
  select purchase_row.id,seat.assigned_user_id,purchase_row.course_id,purchase_row.unit_amount_minor,
    commission_per_seat,seller_per_seat,purchase_row.currency
  from public.learning_company_paid_course_purchase_seats seat where seat.purchase_id = purchase_row.id;
  insert into public.learning_audit_events(actor_user_id,actor_role,action,entity_type,entity_id,metadata)
  values(null,'payment_system','company_paid_course.sale_posted','learning_company_paid_course_purchase',purchase_row.id::text,
    jsonb_build_object('seat_count',purchase_row.seat_count,'gross_amount_minor',purchase_row.total_amount_minor,
      'seller_organization_id',purchase_row.seller_organization_id,'paystack_domain',attempt_row.paystack_domain));
  return purchase_row.id;
end;$function$;

create or replace function public.post_learning_company_commercial_sale_after_charge()
returns trigger language plpgsql security definer set search_path to '' as $function$
begin
  if new.status = 'succeeded' and old.status is distinct from new.status then
    perform public.post_learning_company_commercial_sale(new.purchase_id);
  end if;
  return new;
end;$function$;

create trigger post_learning_company_commercial_sale_after_charge
after update of status on public.learning_company_paid_course_purchase_attempts
for each row execute function public.post_learning_company_commercial_sale_after_charge();

create or replace function public.reconcile_learning_company_commercial_sales()
returns table(purchase_id bigint,issue_type text)
language sql stable security definer set search_path to '' as $function$
  select purchase.id,'paid_purchase_missing_commercial_sale'::text
  from public.learning_company_paid_course_purchases purchase
  where purchase.status = 'paid' and not exists(
    select 1 from public.learning_company_commercial_sales sale where sale.purchase_id = purchase.id)
  union all
  select sale.purchase_id,'company_sale_amount_or_seat_mismatch'::text
  from public.learning_company_commercial_sales sale
  join public.learning_company_paid_course_purchases purchase on purchase.id = sale.purchase_id
  where sale.gross_amount_minor <> purchase.total_amount_minor
    or sale.gross_amount_minor <> sale.platform_commission_minor + sale.seller_gross_minor
    or sale.seat_count <> (select count(*) from public.learning_company_commercial_sale_lines line where line.purchase_id = sale.purchase_id)
    or sale.gross_amount_minor <> coalesce((select sum(line.unit_amount_minor) from public.learning_company_commercial_sale_lines line where line.purchase_id = sale.purchase_id),0)
    or sale.platform_commission_minor <> coalesce((select sum(line.platform_commission_minor) from public.learning_company_commercial_sale_lines line where line.purchase_id = sale.purchase_id),0)
    or sale.seller_gross_minor <> coalesce((select sum(line.seller_gross_minor) from public.learning_company_commercial_sale_lines line where line.purchase_id = sale.purchase_id),0)
  union all
  select sale.purchase_id,'company_sale_ledger_identity_mismatch'::text
  from public.learning_company_commercial_sales sale
  join public.learning_company_sale_ledger_transactions capture on capture.id = sale.capture_ledger_transaction_id
  join public.learning_company_sale_ledger_transactions allocation on allocation.id = sale.allocation_ledger_transaction_id
  where capture.purchase_id <> sale.purchase_id or capture.transaction_type <> 'payment_capture'
    or capture.amount_minor <> sale.gross_amount_minor
    or allocation.purchase_id <> sale.purchase_id or allocation.transaction_type <> 'commercial_allocation'
    or allocation.amount_minor <> sale.gross_amount_minor
  union all
  select ledger.purchase_id,'company_ledger_unbalanced'::text
  from public.learning_company_sale_ledger_transactions ledger
  left join public.learning_company_sale_ledger_entries entry on entry.transaction_id = ledger.id
  group by ledger.purchase_id,ledger.id having coalesce(sum(entry.amount_minor),0) <> 0 or count(entry.id) < 2;
$function$;

