create or replace function public.snapshot_learning_company_sale_terms()
returns trigger language plpgsql security definer set search_path to '' as $function$
declare course_row record; owner_key uuid;
begin
  select course.instructor_id,course.organization_id into course_row
  from public.learning_courses course where course.id = new.course_id;
  if not found or course_row.instructor_id is null then
    raise exception 'Company sale requires an instructor-owned course' using errcode = '22023';
  end if;
  new.seller_instructor_id := course_row.instructor_id;
  new.seller_organization_id := course_row.organization_id;
  if course_row.organization_id is null then
    new.seller_payee_id := course_row.instructor_id;
  else
    select membership.user_id into owner_key
    from public.learning_provider_organization_memberships membership
    where membership.organization_id = course_row.organization_id
      and membership.role = 'owner' and membership.status = 'active';
    if owner_key is null then
      raise exception 'Organization course has no active owner for the sale' using errcode = '22023';
    end if;
    new.seller_payee_id := owner_key;
  end if;
  new.commercial_terms_version := public.resolve_learning_commercial_terms_version(new.course_id,new.seller_payee_id);
  return new;
end;$function$;

create trigger snapshot_learning_company_sale_terms
before insert on public.learning_company_paid_course_purchases
for each row execute function public.snapshot_learning_company_sale_terms();

create or replace function public.protect_learning_company_purchase_sale_snapshot()
returns trigger language plpgsql security definer set search_path to '' as $function$
begin
  if old.workspace_id is distinct from new.workspace_id or old.course_id is distinct from new.course_id
     or old.requested_by is distinct from new.requested_by
     or old.course_title_snapshot is distinct from new.course_title_snapshot
     or old.provider_name_snapshot is distinct from new.provider_name_snapshot
     or old.unit_amount_minor is distinct from new.unit_amount_minor
     or old.total_amount_minor is distinct from new.total_amount_minor
     or old.currency is distinct from new.currency or old.seat_count is distinct from new.seat_count
     or old.seller_instructor_id is distinct from new.seller_instructor_id
     or old.seller_organization_id is distinct from new.seller_organization_id
     or old.seller_payee_id is distinct from new.seller_payee_id
     or old.commercial_terms_version is distinct from new.commercial_terms_version then
    raise exception 'Company sale identity and commercial snapshot are immutable' using errcode = '42501';
  end if;
  return new;
end;$function$;

create trigger protect_learning_company_purchase_sale_snapshot
