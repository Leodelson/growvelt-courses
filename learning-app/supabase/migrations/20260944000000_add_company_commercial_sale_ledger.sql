-- Phase 3C: record a company charge as one capture and immutable per-seat sales.
-- This is separate from learner orders/earnings/payouts. It does not assert
-- live-accounting readiness or enable Live Mode. Apply only after migration 43.
-- Forward-fix rollback: disable the posting trigger in a reviewed follow-up
-- migration, retain immutable capture/seat history, and reconcile affected
-- purchases. Never drop or rewrite posted financial rows to roll this back.
