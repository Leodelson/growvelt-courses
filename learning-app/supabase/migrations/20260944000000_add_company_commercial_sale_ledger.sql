create table public.learning_company_commercial_sales (
  purchase_id bigint primary key references public.learning_company_paid_course_purchases(id) on delete restrict,
  attempt_id bigint not null unique references public.learning_company_paid_course_purchase_attempts(id) on delete restrict,
  paystack_domain text not null check (paystack_domain in ('test','live')),
  provider_reference text not null unique,
  provider_transaction_id text not null,
  seller_instructor_id uuid not null references public.profiles(id) on delete restrict,
  seller_organization_id bigint references public.learning_provider_organizations(id) on delete restrict,
  seller_payee_id uuid not null references public.profiles(id) on delete restrict,
  commercial_terms_version text not null references public.learning_commercial_terms(version) on delete restrict,
  gross_amount_minor bigint not null check (gross_amount_minor > 0),
  platform_commission_minor bigint not null check (platform_commission_minor >= 0),
  seller_gross_minor bigint not null check (seller_gross_minor >= 0),
  currency text not null check (currency = 'NGN'),
  seat_count integer not null check (seat_count > 0),
  capture_ledger_transaction_id bigint not null unique references public.learning_company_sale_ledger_transactions(id) on delete restrict,
  allocation_ledger_transaction_id bigint not null unique references public.learning_company_sale_ledger_transactions(id) on delete restrict,
  posted_at timestamptz not null default now(),
  unique(paystack_domain,provider_transaction_id),
  check(gross_amount_minor = platform_commission_minor + seller_gross_minor)
);

