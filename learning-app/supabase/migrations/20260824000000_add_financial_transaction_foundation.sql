-- Phase 0E: payment-provider-neutral financial transaction foundation.
-- This migration creates no checkout, accepts no payment, publishes no paid
-- course, and does not modify existing application rows.

drop policy if exists "Allow public course registrations" on public.course_registrations;
revoke all on table public.course_registrations from anon, authenticated;
grant select, insert, update, delete on table public.course_registrations to postgres, service_role;

create table public.learning_orders (
  id bigint generated by default as identity primary key,
  order_reference text not null unique default ('GL-' || upper(replace(gen_random_uuid()::text, '-', ''))),
  learner_id uuid references public.profiles(id) on delete set null,
  course_id bigint references public.learning_courses(id) on delete set null,
  instructor_id uuid references public.profiles(id) on delete set null,
  learner_reference uuid not null default gen_random_uuid(),
  course_title_snapshot text not null,
  instructor_name_snapshot text,
  gross_amount_minor bigint not null check (gross_amount_minor > 0),
  currency text not null check (currency = 'NGN'),
  status text not null default 'created'
    check (status in ('created', 'payment_pending', 'paid', 'cancelled', 'partially_refunded', 'refunded', 'chargeback')),
  commercial_terms_version text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  paid_at timestamptz,
  cancelled_at timestamptz,
  constraint learning_orders_reference_format_check
    check (order_reference ~ '^GL-[A-F0-9]{32}$'),
  constraint learning_orders_status_timestamp_check check (
    (status in ('paid', 'partially_refunded', 'refunded', 'chargeback') and paid_at is not null and cancelled_at is null)
    or (status = 'cancelled' and cancelled_at is not null and paid_at is null)
    or (status in ('created', 'payment_pending') and paid_at is null and cancelled_at is null)
  )
);

create index learning_orders_learner_created_idx on public.learning_orders (learner_id, created_at desc, id desc);
create index learning_orders_course_created_idx on public.learning_orders (course_id, created_at desc, id desc);
create index learning_orders_status_created_idx on public.learning_orders (status, created_at desc, id desc);

create table public.learning_payment_attempts (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.learning_orders(id) on delete restrict,
  idempotency_key uuid not null unique default gen_random_uuid(),
  provider text not null check (provider ~ '^[a-z][a-z0-9_]{1,30}$'),
  provider_reference text,
  amount_minor bigint not null check (amount_minor > 0),
  currency text not null check (currency = 'NGN'),
  status text not null default 'initialized'
    check (status in ('initialized', 'pending', 'succeeded', 'failed', 'abandoned')),
  initialized_at timestamptz not null default now(),
  verified_at timestamptz,
  failed_at timestamptz,
  failure_code text,
  failure_message text,
  constraint learning_payment_attempts_provider_reference_key unique (provider, provider_reference),
  constraint learning_payment_attempts_failure_message_length_check
    check (failure_message is null or char_length(failure_message) <= 1000),
  constraint learning_payment_attempts_status_timestamp_check check (
    (status = 'succeeded' and verified_at is not null and failed_at is null)
    or (status = 'failed' and failed_at is not null and verified_at is null)
    or (status in ('initialized', 'pending', 'abandoned') and verified_at is null and failed_at is null)
  )
);

create index learning_payment_attempts_order_idx on public.learning_payment_attempts (order_id, initialized_at desc, id desc);
create index learning_payment_attempts_status_idx on public.learning_payment_attempts (status, initialized_at desc, id desc);

create table public.learning_payment_provider_events (
  id bigint generated by default as identity primary key,
  provider text not null check (provider ~ '^[a-z][a-z0-9_]{1,30}$'),
  provider_event_id text not null,
  event_type text not null check (event_type ~ '^[a-zA-Z0-9_.:-]{2,100}$'),
  payload_digest text not null check (payload_digest ~ '^[a-f0-9]{64}$'),
  payload jsonb not null default '{}'::jsonb check (jsonb_typeof(payload) = 'object'),
  signature_valid boolean not null,
  processing_status text not null default 'received'
    check (processing_status in ('received', 'processed', 'ignored', 'failed')),
  order_id bigint references public.learning_orders(id) on delete restrict,
  payment_attempt_id bigint references public.learning_payment_attempts(id) on delete restrict,
  received_at timestamptz not null default now(),
  processed_at timestamptz,
  processing_error text,
  constraint learning_payment_provider_events_provider_event_key unique (provider, provider_event_id),
  constraint learning_payment_provider_events_error_length_check
    check (processing_error is null or char_length(processing_error) <= 2000),
  constraint learning_payment_provider_events_processing_check
    check ((processing_status = 'received' and processed_at is null) or (processing_status <> 'received' and processed_at is not null))
);

create index learning_payment_provider_events_status_idx on public.learning_payment_provider_events (processing_status, received_at, id);
create index learning_payment_provider_events_order_idx on public.learning_payment_provider_events (order_id, received_at desc, id desc);

