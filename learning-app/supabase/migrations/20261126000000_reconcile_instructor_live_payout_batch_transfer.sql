for each row execute function public.prevent_learning_instructor_payout_batch_reconciliation_history_mutation();
create trigger prevent_learning_instructor_payout_batch_finding_mutation
before update or delete on public.learning_instructor_payout_batch_reconciliation_findings
for each row execute function public.prevent_learning_instructor_payout_batch_reconciliation_history_mutation();
create trigger prevent_learning_instructor_payout_batch_finding_event_mutation
