create function public.open_learning_instructor_payout_batch_finding(
  p_finding_key text,p_attempt_id bigint,p_provider_event_id bigint,p_finding_type text,p_detail text
) returns void language plpgsql security definer set search_path to '' as $function$
declare finding_id bigint;
begin
  insert into public.learning_instructor_payout_batch_reconciliation_findings(
    finding_key,attempt_id,provider_event_id,finding_type,detail
  ) values(p_finding_key,p_attempt_id,p_provider_event_id,p_finding_type,left(p_detail,500))
  on conflict(finding_key) do nothing;
  select f.id into finding_id from public.learning_instructor_payout_batch_reconciliation_findings f
    where f.finding_key=p_finding_key;
  insert into public.learning_instructor_payout_batch_finding_events(finding_id,event_type,detail)
    values(finding_id,'opened',left(p_detail,500))
    on conflict on constraint learning_ipb_finding_event_unique do nothing;
end;$function$;

create function public.receive_paystack_live_instructor_payout_batch_event(
  p_provenance text,p_provider_event_id text,p_payload_digest text,p_reference text,
  p_transfer_id text,p_transfer_code text,p_status text,p_amount_minor bigint,p_currency text,
  p_actor_user_id uuid default null
) returns table(outcome text,provider_event_id bigint)
language plpgsql security definer set search_path to '' as $function$
declare event_id bigint; existing public.learning_instructor_payout_batch_provider_events%rowtype;
        attempt_id bigint;
begin
  if p_provenance not in ('provider_webhook','provider_api')
    or p_provider_event_id is null or char_length(p_provider_event_id) not between 1 and 200
    or p_payload_digest is null or p_payload_digest !~ '^[a-f0-9]{64}$'
    or p_reference is null or p_reference !~ '^lpb-live-batch-[0-9]+-a[0-9]+$'
    or char_length(p_reference) not between 16 and 50
    or p_transfer_id is null or p_transfer_id !~ '^[0-9]+$'
    or (p_transfer_code is not null and p_transfer_code !~ '^TRF_[A-Za-z0-9]+$')
    or p_status not in ('succeeded','failed','reversed','pending')
    or p_amount_minor is null or p_amount_minor<=0 or p_currency<>'NGN' then
    raise exception 'Invalid Paystack Live payout batch event' using errcode='22023';
  end if;
  if p_provenance='provider_api' and (p_actor_user_id is null or not exists(
    select 1 from public.account_capabilities c where c.user_id=p_actor_user_id
      and c.capability='admin' and c.status='active'
  )) then raise exception 'Active administrator required' using errcode='42501'; end if;
  insert into public.learning_instructor_payout_batch_provider_events(
    provenance,provider_event_id,payload_digest,attempt_reference,provider_transfer_id,
    provider_transfer_code,provider_status,amount_minor,currency
  ) values(p_provenance,p_provider_event_id,p_payload_digest,p_reference,p_transfer_id,
    p_transfer_code,p_status,p_amount_minor,p_currency)
  on conflict on constraint learning_ipb_provider_event_id_unique
  do nothing returning id into event_id;
  if event_id is null then
    select * into existing from public.learning_instructor_payout_batch_provider_events e
      where e.provider_event_id=p_provider_event_id for update;
    if existing.payload_digest is distinct from p_payload_digest
      or existing.attempt_reference is distinct from p_reference
      or existing.provider_transfer_id is distinct from p_transfer_id
      or existing.provider_transfer_code is distinct from p_transfer_code
      or existing.provider_status is distinct from p_status
      or existing.amount_minor is distinct from p_amount_minor
      or existing.currency is distinct from p_currency
      or existing.provenance is distinct from p_provenance then
      select a.id into attempt_id from public.learning_instructor_payout_batch_attempts a
        where a.attempt_reference=existing.attempt_reference;
      perform public.open_learning_instructor_payout_batch_finding(
        'payout-batch-event-duplicate-conflict:'||existing.id,attempt_id,existing.id,
        'duplicate_event_conflict','A duplicate provider event ID contained conflicting normalized transfer data'
      );
      return query select 'duplicate_conflict',existing.id; return;
    end if;
    return query select 'already_received',existing.id; return;
  end if;
  return query select 'received',event_id;
end;$function$;

create function public.process_paystack_live_instructor_payout_batch_event(p_provider_event_id bigint)
returns table(outcome text,batch_id bigint)
language plpgsql security definer set search_path to '' as $function$
declare ev public.learning_instructor_payout_batch_provider_events%rowtype;
        attempt public.learning_instructor_payout_batch_attempts%rowtype;
        batch_row public.learning_instructor_payout_batches%rowtype;
        member_row record; settlement_count bigint; member_count bigint;
        checked_total bigint:=0; actual_total bigint; active_protection boolean;
        item_ineligible boolean:=false; ledger_key bigint; event_outcome text;
begin
  select * into ev from public.learning_instructor_payout_batch_provider_events e
    where e.id=p_provider_event_id for update;
  if not found then raise exception 'Payout batch provider event not found' using errcode='P0002'; end if;
  if exists(select 1 from public.learning_instructor_payout_batch_event_processing_attempts p
    where p.provider_event_id=ev.id and p.outcome in
      ('settled','failed','reversed','recorded','conflict','already_processed')) then
    return query select 'already_processed',p.batch_id
      from public.learning_instructor_payout_batch_event_processing_attempts p
      where p.provider_event_id=ev.id and p.outcome in
        ('settled','failed','reversed','recorded','conflict','already_processed') order by p.id desc limit 1;
    return;
  end if;
  select a.* into attempt from public.learning_instructor_payout_batch_attempts a
    where a.attempt_reference=ev.attempt_reference;
  if not found then
    perform public.open_learning_instructor_payout_batch_finding(
      'payout-batch-event-unmatched:'||ev.id,null,ev.id,'unmatched_provider_event',
      'Signed Live transfer event does not match an approved payout batch attempt'
    );
    insert into public.learning_instructor_payout_batch_event_processing_attempts(provider_event_id,outcome,detail)
      values(ev.id,'deferred','Batch attempt is not available yet');
    return query select 'deferred',null::bigint; return;
  end if;
  select b.* into batch_row from public.learning_instructor_payout_batches b
    where b.id=attempt.batch_id for update;
  select a.* into attempt from public.learning_instructor_payout_batch_attempts a
    where a.id=attempt.id for update;
  if attempt.amount_minor<>ev.amount_minor or attempt.currency<>ev.currency
    or (attempt.provider_transfer_id is not null and attempt.provider_transfer_id<>ev.provider_transfer_id)
    or (attempt.provider_transfer_code is not null and ev.provider_transfer_code is not null
      and attempt.provider_transfer_code<>ev.provider_transfer_code) then
    perform public.open_learning_instructor_payout_batch_finding(
      'payout-batch-event-identity:'||ev.id,attempt.id,ev.id,
      case when attempt.amount_minor<>ev.amount_minor or attempt.currency<>ev.currency
        then 'provider_amount_currency_mismatch' else 'provider_identity_mismatch' end,
      'Provider event amount, currency, or transfer identity does not match the immutable batch attempt'
    );
    insert into public.learning_instructor_payout_batch_event_processing_attempts(provider_event_id,batch_id,outcome,detail)
      values(ev.id,batch_row.id,'conflict','Provider transfer identity or amount mismatch');
    return query select 'conflict',batch_row.id; return;
  end if;
  if attempt.payout_profile_id<>batch_row.payout_profile_id
    or attempt.recipient_code !~ '^RCP_[A-Za-z0-9]+$'
    or attempt.provider_recipient_id !~ '^[0-9]+$'
    or attempt.initiated_by is null then
    perform public.open_learning_instructor_payout_batch_finding(
      'payout-batch-event-member-identity:'||attempt.id,attempt.id,ev.id,
      'member_financial_identity_mismatch','Immutable batch recipient or actor identity is inconsistent'
    );
    insert into public.learning_instructor_payout_batch_event_processing_attempts(provider_event_id,batch_id,outcome,detail)
      values(ev.id,batch_row.id,'conflict','Immutable batch attempt identity is inconsistent');
    return query select 'conflict',batch_row.id; return;
  end if;

  -- A webhook can race the provider-response write. It may bind the transfer
  -- identity, but it may not bypass the amount/reference checks above.
  if attempt.status='submitting' then
    if ev.provider_transfer_code is null then
      insert into public.learning_instructor_payout_batch_event_processing_attempts(provider_event_id,batch_id,outcome,detail)
        values(ev.id,batch_row.id,'deferred','Provider response is still needed to complete transfer identity');
      return query select 'deferred',batch_row.id; return;
    end if;
    update public.learning_instructor_payout_batch_attempts a set status='pending',
      provider_transfer_id=ev.provider_transfer_id,provider_transfer_code=ev.provider_transfer_code,
      provider_status='pending',provider_received_at=now() where a.id=attempt.id;
    update public.learning_instructor_payout_batches b set status='pending' where b.id=batch_row.id;
    select a.* into attempt from public.learning_instructor_payout_batch_attempts a where a.id=attempt.id;
    select b.* into batch_row from public.learning_instructor_payout_batches b where b.id=batch_row.id;
  elsif attempt.provider_transfer_id is null then
    if ev.provider_transfer_code is null then
      insert into public.learning_instructor_payout_batch_event_processing_attempts(provider_event_id,batch_id,outcome,detail)
        values(ev.id,batch_row.id,'deferred','Provider transfer identity is incomplete; manual verification required');
      return query select 'deferred',batch_row.id; return;
    end if;
    update public.learning_instructor_payout_batch_attempts a set
      provider_transfer_id=ev.provider_transfer_id,provider_transfer_code=ev.provider_transfer_code,
      provider_status=case when ev.provider_status='pending' then 'pending' else a.provider_status end,
      provider_received_at=now() where a.id=attempt.id;
    select a.* into attempt from public.learning_instructor_payout_batch_attempts a where a.id=attempt.id;
  end if;

  if ev.provider_status='pending' then
    if attempt.status in ('pending','financially_blocked') then
      insert into public.learning_instructor_payout_batch_attempt_events(
        attempt_id,event_type,from_status,to_status,provenance,provider_event_id,payload_digest,metadata
      ) values(attempt.id,'paystack.pending',attempt.status,attempt.status,
        case when ev.provenance='provider_webhook' then 'provider_webhook' else 'provider_api' end,
        ev.provider_event_id,ev.payload_digest,jsonb_build_object('provider_transfer_id',ev.provider_transfer_id));
      insert into public.learning_instructor_payout_batch_event_processing_attempts(provider_event_id,batch_id,outcome,detail)
        values(ev.id,batch_row.id,'recorded','Provider transfer remains pending');
      return query select 'recorded',batch_row.id; return;
    end if;
    perform public.open_learning_instructor_payout_batch_finding(
      'payout-batch-pending-conflict:'||ev.id,attempt.id,ev.id,
      'provider_outcome_conflict','Delayed pending event conflicts with the batch attempt state'
    );
    insert into public.learning_instructor_payout_batch_event_processing_attempts(provider_event_id,batch_id,outcome,detail)
      values(ev.id,batch_row.id,'conflict','Pending event conflicts with terminal attempt');
    return query select 'conflict',batch_row.id; return;
  end if;

  if ev.provider_status='reversed' then
    if attempt.status in ('failed','reversed') then
      perform public.open_learning_instructor_payout_batch_finding(
        'payout-batch-reversed-conflict:'||ev.id,attempt.id,ev.id,'provider_outcome_conflict',
        'Reversal event conflicts with a previously failed or reversed batch attempt'
      );
      insert into public.learning_instructor_payout_batch_event_processing_attempts(provider_event_id,batch_id,outcome,detail)
        values(ev.id,batch_row.id,'conflict','Conflicting terminal provider outcome');
      return query select 'conflict',batch_row.id; return;
    end if;
    if attempt.status='succeeded' then
      perform public.open_learning_instructor_payout_batch_finding(
        'settled-payout-batch-reversed:'||attempt.id,attempt.id,ev.id,
        'terminal_payout_inconsistent_state','A settled aggregate payout was reversed; prior ledger settlements are retained for controlled recovery'
      );
    else
      perform public.open_learning_instructor_payout_batch_finding(
        'payout-batch-reversed:'||attempt.id,attempt.id,ev.id,
        'terminal_payout_inconsistent_state','Provider reversed the transfer before verified batch settlement; reservations remain held'
      );
    end if;
    update public.learning_instructor_payout_batch_attempts a set status='reversed',
      provider_transfer_id=coalesce(a.provider_transfer_id,ev.provider_transfer_id),
      provider_transfer_code=coalesce(a.provider_transfer_code,ev.provider_transfer_code),
      provider_status='reversed',provider_received_at=now() where a.id=attempt.id;
    update public.learning_instructor_payout_batches b set status='reversed' where b.id=batch_row.id;
    insert into public.learning_instructor_payout_batch_attempt_events(
      attempt_id,event_type,from_status,to_status,provenance,provider_event_id,payload_digest,metadata
    ) values(attempt.id,'paystack.reversed',attempt.status,'reversed',
      case when ev.provenance='provider_webhook' then 'provider_webhook' else 'provider_api' end,
      ev.provider_event_id,ev.payload_digest,jsonb_build_object('provider_transfer_id',ev.provider_transfer_id));
    insert into public.learning_instructor_payout_batch_event_processing_attempts(provider_event_id,batch_id,outcome,detail)
      values(ev.id,batch_row.id,'reversed','Authoritative reversal retained; no ledger history was rewritten');
    return query select 'reversed',batch_row.id; return;
  end if;

  if ev.provider_status='failed' then
    if attempt.status in ('succeeded','reversed','failed') then
      perform public.open_learning_instructor_payout_batch_finding(
        'payout-batch-failed-conflict:'||ev.id,attempt.id,ev.id,'provider_outcome_conflict',
        'Failed event conflicts with an existing terminal payout state'
      );
      insert into public.learning_instructor_payout_batch_event_processing_attempts(provider_event_id,batch_id,outcome,detail)
        values(ev.id,batch_row.id,'conflict','Conflicting terminal provider outcome');
      return query select 'conflict',batch_row.id; return;
    end if;
    lock table public.learning_payment_cases in share row exclusive mode;
    for member_row in
      select m.earning_id,m.reservation_id,m.amount_minor,r.status reservation_status,
        r.future_payout_item_reference,e.status earning_status,e.instructor_id earning_instructor,
        e.gross_amount_minor,e.currency earning_currency,a.id allocation_id,a.status allocation_status,
        a.instructor_id allocation_instructor,a.instructor_gross_minor,a.currency allocation_currency,
        o.id order_id,o.status order_status,o.gross_amount_minor order_gross,o.currency order_currency
      from public.learning_instructor_payout_batch_members m
      join public.learning_instructor_earning_reservations r on r.id=m.reservation_id
      join public.learning_instructor_earnings e on e.id=m.earning_id
      join public.learning_commercial_allocations a on a.id=e.allocation_id
      join public.learning_orders o on o.id=a.order_id
      where m.batch_id=batch_row.id order by m.earning_id
    loop
      perform 1 from public.learning_instructor_earning_reservations r where r.id=member_row.reservation_id for update;
      perform 1 from public.learning_instructor_earnings e where e.id=member_row.earning_id for update;
      perform 1 from public.learning_commercial_allocations a where a.id=member_row.allocation_id for update;
      perform 1 from public.learning_orders o where o.id=member_row.order_id for update;
      checked_total:=checked_total+member_row.amount_minor;
      if member_row.reservation_status<>'reserved'
        or member_row.future_payout_item_reference<>'lpb-'||batch_row.id::text||'-earning-'||member_row.earning_id::text
        or member_row.earning_status<>'reserved' or member_row.earning_instructor<>batch_row.instructor_id
        or member_row.gross_amount_minor<>member_row.amount_minor or member_row.earning_currency<>batch_row.currency
        or member_row.allocation_status<>'allocated' or member_row.allocation_instructor<>batch_row.instructor_id
        or member_row.instructor_gross_minor<>member_row.amount_minor or member_row.allocation_currency<>batch_row.currency
        or member_row.order_status<>'paid' or member_row.order_currency<>batch_row.currency
        or exists(select 1 from public.learning_instructor_payout_settlements s
          where s.earning_id=member_row.earning_id or s.reservation_id=member_row.reservation_id)
        or exists(select 1 from public.learning_instructor_payout_items i
          where i.earning_id=member_row.earning_id or i.reservation_id=member_row.reservation_id)
        or (select count(*) from public.learning_payment_attempts p where p.order_id=member_row.order_id and p.status='succeeded')<>1
        or not exists(select 1 from public.learning_payment_attempts p where p.order_id=member_row.order_id
          and p.status='succeeded' and p.provider='paystack' and p.paystack_domain='live'
          and p.amount_minor=member_row.order_gross and p.currency=member_row.order_currency)
        or exists(select 1 from public.learning_payment_cases c where c.order_id=member_row.order_id
          and c.status in ('requested','submitting','pending','processing','needs_attention','opened',
            'action_required','submitted','under_review','processed','succeeded','lost')) then
        item_ineligible:=true;
      end if;
    end loop;
    select count(*),coalesce(sum(m.amount_minor),0)::bigint into member_count,actual_total
      from public.learning_instructor_payout_batch_members m where m.batch_id=batch_row.id;
    if member_count=0 or checked_total<>batch_row.amount_minor or actual_total<>batch_row.amount_minor
      or ev.amount_minor<>batch_row.amount_minor then item_ineligible:=true; end if;
    if item_ineligible then
      update public.learning_instructor_payout_batch_attempts a set status='financially_blocked',
        provider_transfer_id=coalesce(a.provider_transfer_id,ev.provider_transfer_id),
        provider_transfer_code=coalesce(a.provider_transfer_code,ev.provider_transfer_code),
        provider_status='failed',provider_received_at=now(),failure_code='financial_protection'
        where a.id=attempt.id and a.status<>'financially_blocked';
      update public.learning_instructor_payout_batches b set status='financially_blocked' where b.id=batch_row.id;
      perform public.open_learning_instructor_payout_batch_finding(
        'payout-batch-failed-blocked:'||attempt.id,attempt.id,ev.id,
        'provider_outcome_financially_blocked','Failed transfer retained with reservations pending financial and member review'
      );
      insert into public.learning_instructor_payout_batch_event_processing_attempts(provider_event_id,batch_id,outcome,detail)
        values(ev.id,batch_row.id,'deferred','Failed transfer is not retryable until financial protection and member state are reviewed');
      return query select 'deferred',batch_row.id; return;
    end if;
    update public.learning_instructor_payout_batch_attempts a set status='failed',
      provider_transfer_id=coalesce(a.provider_transfer_id,ev.provider_transfer_id),
      provider_transfer_code=coalesce(a.provider_transfer_code,ev.provider_transfer_code),
      provider_status='failed',provider_received_at=now(),failure_code='provider_failed' where a.id=attempt.id;
    update public.learning_instructor_payout_batches b set status='failed' where b.id=batch_row.id;
    insert into public.learning_instructor_payout_batch_attempt_events(
      attempt_id,event_type,from_status,to_status,provenance,provider_event_id,payload_digest,metadata
    ) values(attempt.id,'paystack.failed',attempt.status,'failed',
      case when ev.provenance='provider_webhook' then 'provider_webhook' else 'provider_api' end,
      ev.provider_event_id,ev.payload_digest,jsonb_build_object('provider_transfer_id',ev.provider_transfer_id,
        'reservations_retained_for_exact_retry',true));
    insert into public.learning_instructor_payout_batch_event_processing_attempts(provider_event_id,batch_id,outcome,detail)
      values(ev.id,batch_row.id,'failed','Authoritative failure recorded; reservations remain attached for exact safe retry');
    return query select 'failed',batch_row.id; return;
  end if;

  -- Repeated success events after a completed batch are harmless and never
  -- create duplicate ledger entries.
  select count(*) into settlement_count from public.learning_instructor_payout_batch_settlements s
    where s.batch_id=batch_row.id;
  select count(*) into member_count from public.learning_instructor_payout_batch_members m
    where m.batch_id=batch_row.id;
  if settlement_count>0 then
    if settlement_count=member_count and attempt.status='succeeded' then
      insert into public.learning_instructor_payout_batch_event_processing_attempts(provider_event_id,batch_id,outcome,detail)
        values(ev.id,batch_row.id,'already_processed','Batch already has one settlement for every member');
      return query select 'already_processed',batch_row.id; return;
    end if;
    perform public.open_learning_instructor_payout_batch_finding(
      'payout-batch-partial-settlement:'||batch_row.id,attempt.id,ev.id,
      'partial_batch_settlement','Existing batch settlements do not match the immutable member count'
    );
    insert into public.learning_instructor_payout_batch_event_processing_attempts(provider_event_id,batch_id,outcome,detail)
      values(ev.id,batch_row.id,'conflict','Partial or inconsistent settlement state requires manual recovery');
    return query select 'conflict',batch_row.id; return;
  end if;
  if attempt.status in ('failed','reversed') then
    perform public.open_learning_instructor_payout_batch_finding(
      'payout-batch-success-conflict:'||ev.id,attempt.id,ev.id,'provider_outcome_conflict',
      'Success event conflicts with a prior failed or reversed provider outcome'
    );
    insert into public.learning_instructor_payout_batch_event_processing_attempts(provider_event_id,batch_id,outcome,detail)
      values(ev.id,batch_row.id,'conflict','Conflicting terminal provider outcome');
    return query select 'conflict',batch_row.id; return;
  end if;
  if ev.amount_minor<>batch_row.amount_minor then
    perform public.open_learning_instructor_payout_batch_finding(
      'payout-batch-success-amount:'||ev.id,attempt.id,ev.id,'provider_amount_currency_mismatch',
      'Successful provider amount does not equal the approved batch total'
    );
    insert into public.learning_instructor_payout_batch_event_processing_attempts(provider_event_id,batch_id,outcome,detail)
      values(ev.id,batch_row.id,'conflict','Successful provider amount mismatch');
    return query select 'conflict',batch_row.id; return;
  end if;
  lock table public.learning_payment_cases in share row exclusive mode;
  checked_total:=0;
  item_ineligible:=false;
  for member_row in
    select m.earning_id,m.reservation_id,m.amount_minor,r.status reservation_status,
      r.future_payout_item_reference,e.status earning_status,e.instructor_id earning_instructor,
      e.gross_amount_minor,e.currency earning_currency,a.id allocation_id,a.status allocation_status,
      a.instructor_id allocation_instructor,a.instructor_gross_minor,a.currency allocation_currency,
      o.id order_id,o.status order_status,o.gross_amount_minor order_gross,o.currency order_currency
    from public.learning_instructor_payout_batch_members m
    join public.learning_instructor_earning_reservations r on r.id=m.reservation_id
    join public.learning_instructor_earnings e on e.id=m.earning_id
    join public.learning_commercial_allocations a on a.id=e.allocation_id
    join public.learning_orders o on o.id=a.order_id
    where m.batch_id=batch_row.id order by m.earning_id
  loop
    perform 1 from public.learning_instructor_earning_reservations r where r.id=member_row.reservation_id for update;
    perform 1 from public.learning_instructor_earnings e where e.id=member_row.earning_id for update;
    perform 1 from public.learning_commercial_allocations a where a.id=member_row.allocation_id for update;
    perform 1 from public.learning_orders o where o.id=member_row.order_id for update;
    checked_total:=checked_total+member_row.amount_minor;
    if member_row.reservation_status<>'reserved'
      or member_row.future_payout_item_reference<>'lpb-'||batch_row.id::text||'-earning-'||member_row.earning_id::text
      or member_row.earning_status<>'reserved' or member_row.earning_instructor<>batch_row.instructor_id
      or member_row.gross_amount_minor<>member_row.amount_minor or member_row.earning_currency<>batch_row.currency
      or member_row.allocation_status<>'allocated' or member_row.allocation_instructor<>batch_row.instructor_id
      or member_row.instructor_gross_minor<>member_row.amount_minor or member_row.allocation_currency<>batch_row.currency
      or member_row.order_status<>'paid' or member_row.order_currency<>batch_row.currency
      or exists(select 1 from public.learning_instructor_payout_settlements s
        where s.earning_id=member_row.earning_id or s.reservation_id=member_row.reservation_id)
      or exists(select 1 from public.learning_instructor_payout_items i
        where i.earning_id=member_row.earning_id or i.reservation_id=member_row.reservation_id)
      or (select count(*) from public.learning_payment_attempts p where p.order_id=member_row.order_id and p.status='succeeded')<>1
      or not exists(select 1 from public.learning_payment_attempts p where p.order_id=member_row.order_id
        and p.status='succeeded' and p.provider='paystack' and p.paystack_domain='live'
        and p.amount_minor=member_row.order_gross and p.currency=member_row.order_currency)
      or exists(select 1 from public.learning_payment_cases c where c.order_id=member_row.order_id
        and c.status in ('requested','submitting','pending','processing','needs_attention','opened',
          'action_required','submitted','under_review','processed','succeeded','lost')) then
      item_ineligible:=true;
    end if;
  end loop;
  select coalesce(sum(m.amount_minor),0)::bigint into actual_total
    from public.learning_instructor_payout_batch_members m where m.batch_id=batch_row.id;
  if member_count=0 or checked_total<>batch_row.amount_minor or actual_total<>batch_row.amount_minor then
    item_ineligible:=true;
  end if;
  if item_ineligible then
    update public.learning_instructor_payout_batch_attempts a set status='financially_blocked',
      provider_transfer_id=coalesce(a.provider_transfer_id,ev.provider_transfer_id),
      provider_transfer_code=coalesce(a.provider_transfer_code,ev.provider_transfer_code),
      provider_status='success',provider_received_at=now(),failure_code='financial_protection'
      where a.id=attempt.id and a.status<>'financially_blocked';
    update public.learning_instructor_payout_batches b set status='financially_blocked' where b.id=batch_row.id;
    perform public.open_learning_instructor_payout_batch_finding(
      'payout-batch-success-blocked:'||attempt.id,attempt.id,ev.id,
      'provider_outcome_financially_blocked','Provider success retained, but no members were settled because financial validation failed'
    );
    insert into public.learning_instructor_payout_batch_event_processing_attempts(provider_event_id,batch_id,outcome,detail)
      values(ev.id,batch_row.id,'deferred','Provider success needs controlled member and protection review');
    return query select 'deferred',batch_row.id; return;
  end if;

  -- Per-earning ledger pairs preserve course/order attribution while the
  -- provider transfer itself remains a single, batch-level movement.
  for member_row in
    select m.earning_id,m.reservation_id,m.amount_minor,e.allocation_id,a.order_id,
      e.instructor_id,e.status earning_status,e.currency
    from public.learning_instructor_payout_batch_members m
    join public.learning_instructor_earnings e on e.id=m.earning_id
    join public.learning_commercial_allocations a on a.id=e.allocation_id
    where m.batch_id=batch_row.id order by m.earning_id
  loop
    insert into public.learning_ledger_transactions(order_id,transaction_type,currency,description)
      values(member_row.order_id,'instructor_payout_settlement',member_row.currency,
        'Authoritative Paystack Live instructor payout batch settlement') returning id into ledger_key;
    insert into public.learning_ledger_entries(
      transaction_id,line_number,account_code,amount_minor,currency,counterparty_type,counterparty_reference
    ) values
      (ledger_key,1,'liability.instructor_earnings_available',member_row.amount_minor,member_row.currency,
        'instructor_earning',member_row.earning_id::text),
      (ledger_key,2,'asset.paystack_transfer_clearing',-member_row.amount_minor,member_row.currency,
        'learning_instructor_payout_batch',batch_row.batch_reference||':'||member_row.earning_id::text);
    update public.learning_instructor_earnings e set status='paid',paid_at=now(),
      hold_reason='Paid through an authoritative Paystack Live payout batch'
      where e.id=member_row.earning_id and e.status='reserved';
    if not found then raise exception 'Reserved batch earning cannot be settled' using errcode='40001'; end if;
    insert into public.learning_instructor_payout_batch_settlements(
      batch_id,attempt_id,provider_event_id,earning_id,reservation_id,ledger_transaction_id,amount_minor,currency
    ) values(batch_row.id,attempt.id,ev.id,member_row.earning_id,member_row.reservation_id,
      ledger_key,member_row.amount_minor,member_row.currency);
    insert into public.learning_instructor_earning_events(
      earning_id,event_type,from_status,to_status,ledger_transaction_id,metadata
    ) values(member_row.earning_id,'earning.paid','reserved','paid',ledger_key,
      jsonb_build_object('batch_reference',batch_row.batch_reference,'provider_event_id',ev.provider_event_id,
        'provider_transfer_id',ev.provider_transfer_id,'provenance',ev.provenance));
  end loop;
  update public.learning_instructor_payout_batch_attempts a set status='succeeded',
    provider_transfer_id=coalesce(a.provider_transfer_id,ev.provider_transfer_id),
    provider_transfer_code=coalesce(a.provider_transfer_code,ev.provider_transfer_code),
    provider_status='success',provider_received_at=now(),failure_code=null where a.id=attempt.id;
  update public.learning_instructor_payout_batches b set status='succeeded' where b.id=batch_row.id;
  insert into public.learning_instructor_payout_batch_attempt_events(
    attempt_id,event_type,from_status,to_status,provenance,provider_event_id,payload_digest,metadata
  ) values(attempt.id,'paystack.succeeded',attempt.status,'succeeded',
    case when ev.provenance='provider_webhook' then 'provider_webhook' else 'provider_api' end,
    ev.provider_event_id,ev.payload_digest,jsonb_build_object('provider_transfer_id',ev.provider_transfer_id,
      'settlement_count',member_count,'batch_amount_minor',batch_row.amount_minor));
  insert into public.learning_instructor_payout_batch_event_processing_attempts(provider_event_id,batch_id,outcome,detail)
    values(ev.id,batch_row.id,'settled','All payout batch members settled exactly once with balanced ledger entries');
  insert into public.learning_instructor_payout_batch_finding_events(finding_id,event_type,detail)
    select f.id,'resolved','Resolved by authoritative successful batch settlement'
    from public.learning_instructor_payout_batch_reconciliation_findings f
    where f.attempt_id=attempt.id
      and not exists(select 1 from public.learning_instructor_payout_batch_finding_events fe
        where fe.finding_id=f.id and fe.event_type='resolved')
    on conflict on constraint learning_ipb_finding_event_unique do nothing;
  return query select 'settled',batch_row.id;
end;$function$;

create function public.list_learning_instructor_payout_batch_reconciliation_findings(
  p_operator_id uuid,p_limit integer default 100
) returns table(finding_id bigint,attempt_reference text,finding_type text,detail text,status text,created_at timestamptz)
language plpgsql stable security definer set search_path to '' as $function$
begin
  if p_operator_id is null or not exists(select 1 from public.account_capabilities c
    where c.user_id=p_operator_id and c.capability='admin' and c.status='active') then
    raise exception 'Active administrator required' using errcode='42501';
  end if;
  return query select f.id,a.attempt_reference,f.finding_type,f.detail,
    case when exists(select 1 from public.learning_instructor_payout_batch_finding_events fe
      where fe.finding_id=f.id and fe.event_type='resolved') then 'resolved' else 'open' end,
    f.created_at
    from public.learning_instructor_payout_batch_reconciliation_findings f
    left join public.learning_instructor_payout_batch_attempts a on a.id=f.attempt_id
    order by f.created_at desc,f.id desc limit least(greatest(coalesce(p_limit,100),1),200);
end;$function$;

