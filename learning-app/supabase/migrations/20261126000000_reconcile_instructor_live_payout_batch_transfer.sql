-- Phase 3: receive and reconcile one authoritative Live transfer for an
-- instructor payout batch. All member settlements commit atomically.
begin;

create table public.learning_instructor_payout_batch_provider_events (
  id bigint generated by default as identity primary key,
  provenance text not null check (provenance in ('provider_webhook','provider_api')),
  provider_event_id text not null check (char_length(provider_event_id) between 1 and 200),
  payload_digest text not null check (payload_digest ~ '^[a-f0-9]{64}$'),
  attempt_reference text not null check (
    attempt_reference ~ '^lpb-live-batch-[0-9]+-a[0-9]+$'
    and char_length(attempt_reference) between 16 and 50
  ),
  provider_transfer_id text not null check (provider_transfer_id ~ '^[0-9]+$'),
  provider_transfer_code text check (provider_transfer_code is null or provider_transfer_code ~ '^TRF_[A-Za-z0-9]+$'),
  provider_status text not null check (provider_status in ('succeeded','failed','reversed','pending')),
  amount_minor bigint not null check (amount_minor>0),
  currency text not null check (currency='NGN'),
  received_at timestamptz not null default now(),
  constraint learning_ipb_provider_event_id_unique unique(provider_event_id)
);
create index learning_instructor_payout_batch_provider_events_reference_idx
  on public.learning_instructor_payout_batch_provider_events(attempt_reference,received_at,id);

create table public.learning_instructor_payout_batch_event_processing_attempts (
  id bigint generated by default as identity primary key,
  provider_event_id bigint not null references public.learning_instructor_payout_batch_provider_events(id) on delete restrict,
  batch_id bigint references public.learning_instructor_payout_batches(id) on delete restrict,
  outcome text not null check (outcome in ('settled','failed','reversed','recorded','deferred','conflict','already_processed')),
  detail text not null check (length(detail)<=500),
  processed_at timestamptz not null default now()
);
create unique index learning_instructor_payout_batch_event_terminal_key
  on public.learning_instructor_payout_batch_event_processing_attempts(provider_event_id)
  where outcome in ('settled','failed','reversed','recorded','conflict','already_processed');

create table public.learning_instructor_payout_batch_settlements (
  id bigint generated by default as identity primary key,
  batch_id bigint not null references public.learning_instructor_payout_batches(id) on delete restrict,
  attempt_id bigint not null references public.learning_instructor_payout_batch_attempts(id) on delete restrict,
  provider_event_id bigint not null references public.learning_instructor_payout_batch_provider_events(id) on delete restrict,
  earning_id bigint not null unique references public.learning_instructor_earnings(id) on delete restrict,
  reservation_id bigint not null unique references public.learning_instructor_earning_reservations(id) on delete restrict,
  ledger_transaction_id bigint not null unique references public.learning_ledger_transactions(id) on delete restrict,
  amount_minor bigint not null check (amount_minor>0),
  currency text not null check (currency='NGN'),
  settled_at timestamptz not null default now(),
  unique(batch_id,earning_id)
);
create index learning_instructor_payout_batch_settlements_attempt_idx
  on public.learning_instructor_payout_batch_settlements(attempt_id,earning_id);

create table public.learning_instructor_payout_batch_reconciliation_findings (
  id bigint generated by default as identity primary key,
  finding_key text not null unique check (finding_key ~ '^[a-z][a-z0-9:_-]{3,180}$'),
  attempt_id bigint references public.learning_instructor_payout_batch_attempts(id) on delete restrict,
  provider_event_id bigint references public.learning_instructor_payout_batch_provider_events(id) on delete restrict,
  finding_type text not null check (finding_type in (
    'unmatched_provider_event','duplicate_event_conflict','provider_identity_mismatch',
    'provider_amount_currency_mismatch','provider_outcome_conflict',
    'provider_outcome_financially_blocked','terminal_payout_inconsistent_state',
    'partial_batch_settlement','member_financial_identity_mismatch'
  )),
  detail text not null check (length(detail)<=500),
  created_at timestamptz not null default now()
);
create index learning_instructor_payout_batch_findings_attempt_idx
  on public.learning_instructor_payout_batch_reconciliation_findings(attempt_id,created_at desc,id desc);

create table public.learning_instructor_payout_batch_finding_events (
  id bigint generated by default as identity primary key,
  finding_id bigint not null references public.learning_instructor_payout_batch_reconciliation_findings(id) on delete restrict,
  event_type text not null check (event_type in ('opened','resolved')),
  detail text not null check (length(detail)<=500),
  occurred_at timestamptz not null default now(),
  constraint learning_ipb_finding_event_unique unique(finding_id,event_type)
);

alter table public.learning_instructor_payout_batch_provider_events enable row level security;
alter table public.learning_instructor_payout_batch_event_processing_attempts enable row level security;
alter table public.learning_instructor_payout_batch_settlements enable row level security;
alter table public.learning_instructor_payout_batch_reconciliation_findings enable row level security;
alter table public.learning_instructor_payout_batch_finding_events enable row level security;
revoke all on public.learning_instructor_payout_batch_provider_events,
  public.learning_instructor_payout_batch_event_processing_attempts,
  public.learning_instructor_payout_batch_settlements,
  public.learning_instructor_payout_batch_reconciliation_findings,
  public.learning_instructor_payout_batch_finding_events from public,anon,authenticated,service_role;
grant select on public.learning_instructor_payout_batch_provider_events,
  public.learning_instructor_payout_batch_event_processing_attempts,
  public.learning_instructor_payout_batch_settlements,
  public.learning_instructor_payout_batch_reconciliation_findings,
  public.learning_instructor_payout_batch_finding_events to postgres,service_role;

