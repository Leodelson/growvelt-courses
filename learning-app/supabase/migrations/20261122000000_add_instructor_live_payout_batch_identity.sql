-- Inert, additive identity foundation for future multi-earning Live payouts.
-- No approval, submission, or settlement function is created here. Existing
-- one-earning payout items and their historical reconciliation are untouched.
begin;

create table public.learning_instructor_payout_batches (
  id bigint generated by default as identity primary key,
  batch_reference text not null unique check (batch_reference ~ '^LPB-[0-9]+$'),
  idempotency_key text not null unique check (idempotency_key ~ '^[a-z][a-z0-9:_-]{2,120}$'),
  instructor_id uuid not null references public.profiles(id) on delete restrict,
  payout_profile_id bigint not null references public.learning_instructor_payout_profiles(id) on delete restrict,
  amount_minor bigint not null check (amount_minor >= 100000),
  currency text not null check (currency = 'NGN'),
  status text not null default 'assembled' check (status = 'assembled'),
  assembled_by uuid not null references public.profiles(id) on delete restrict,
  assembled_at timestamptz not null default now()
);
create index learning_instructor_payout_batches_instructor_idx
  on public.learning_instructor_payout_batches(instructor_id,assembled_at desc,id desc);

create table public.learning_instructor_payout_batch_members (
  batch_id bigint not null references public.learning_instructor_payout_batches(id) on delete restrict,
  reservation_id bigint not null unique references public.learning_instructor_earning_reservations(id) on delete restrict,
  earning_id bigint not null unique references public.learning_instructor_earnings(id) on delete restrict,
  amount_minor bigint not null check (amount_minor > 0),
  created_at timestamptz not null default now(),
  primary key (batch_id,reservation_id)
);

alter table public.learning_instructor_payout_batches enable row level security;
alter table public.learning_instructor_payout_batch_members enable row level security;
revoke all on public.learning_instructor_payout_batches,
  public.learning_instructor_payout_batch_members from public,anon,authenticated;
-- The later guarded writer will be a SECURITY DEFINER function. Direct
-- service-role table mutation is intentionally unavailable in this slice.
grant select on public.learning_instructor_payout_batches,
  public.learning_instructor_payout_batch_members to postgres,service_role;

create function public.prevent_learning_instructor_payout_batch_mutation()
returns trigger language plpgsql security definer set search_path to '' as $function$
begin
  raise exception 'Payout batch financial identity is immutable' using errcode='42501';
end;$function$;
create trigger prevent_learning_instructor_payout_batch_mutation
before update or delete on public.learning_instructor_payout_batches
for each row execute function public.prevent_learning_instructor_payout_batch_mutation();
create trigger prevent_learning_instructor_payout_batch_member_mutation
before update or delete on public.learning_instructor_payout_batch_members
for each row execute function public.prevent_learning_instructor_payout_batch_mutation();

create function public.validate_learning_instructor_payout_batch_member()
returns trigger language plpgsql security definer set search_path to '' as $function$
declare
  reservation_row public.learning_instructor_earning_reservations%rowtype;
  batch_row public.learning_instructor_payout_batches%rowtype;
  profile_row public.learning_instructor_payout_profiles%rowtype;
begin
  -- The legacy one-item writer also locks this reservation. The lock and the
  -- reciprocal item trigger below make cross-path membership exclusion atomic.
  select * into reservation_row from public.learning_instructor_earning_reservations
    where id=new.reservation_id for update;
  select * into batch_row from public.learning_instructor_payout_batches
    where id=new.batch_id;
  select * into profile_row from public.learning_instructor_payout_profiles
    where id=batch_row.payout_profile_id;
  if reservation_row.id is null or batch_row.id is null or profile_row.id is null
    or reservation_row.earning_id<>new.earning_id
    or reservation_row.instructor_id<>batch_row.instructor_id
    or reservation_row.currency<>batch_row.currency
    or reservation_row.amount_minor<>new.amount_minor
    or reservation_row.future_payout_item_reference is not null
    or profile_row.instructor_id<>batch_row.instructor_id
    or profile_row.currency<>batch_row.currency
    or profile_row.provider<>'paystack' or profile_row.provider_domain<>'live'
    or profile_row.status<>'active'
    or not exists(select 1 from public.learning_instructor_earnings e
      where e.id=new.earning_id and e.status='reserved'
        and e.instructor_id=batch_row.instructor_id and e.currency=batch_row.currency
        and e.gross_amount_minor=new.amount_minor)
    or exists(select 1 from public.learning_instructor_payout_items item
      where item.reservation_id=new.reservation_id or item.earning_id=new.earning_id)
  then
    raise exception 'Ineligible or already allocated batch member' using errcode='22023';
  end if;
  return new;
end;$function$;
create trigger validate_learning_instructor_payout_batch_member
before insert on public.learning_instructor_payout_batch_members
for each row execute function public.validate_learning_instructor_payout_batch_member();

create function public.prevent_learning_single_payout_batch_overlap()
returns trigger language plpgsql security definer set search_path to '' as $function$
begin
  perform 1 from public.learning_instructor_earning_reservations
    where id=new.reservation_id for update;
  if exists(select 1 from public.learning_instructor_payout_batch_members member
    where member.reservation_id=new.reservation_id or member.earning_id=new.earning_id)
  then
    raise exception 'Earning already allocated to a payout batch' using errcode='23505';
  end if;
  return new;
end;$function$;
create trigger prevent_learning_single_payout_batch_overlap
before insert on public.learning_instructor_payout_items
for each row execute function public.prevent_learning_single_payout_batch_overlap();

create function public.check_learning_instructor_payout_batch_total()
returns trigger language plpgsql security definer set search_path to '' as $function$
declare
  batch_id_value bigint;
  batch_amount bigint;
  member_amount bigint;
  member_count bigint;
begin
  if tg_table_name='learning_instructor_payout_batches' then
    batch_id_value := new.id;
  else
    batch_id_value := new.batch_id;
  end if;
  select b.amount_minor into batch_amount from public.learning_instructor_payout_batches b
    where b.id=batch_id_value;
  select count(*),coalesce(sum(m.amount_minor),0)
    into member_count,member_amount
    from public.learning_instructor_payout_batch_members m where m.batch_id=batch_id_value;
  if member_count=0 or member_amount<>batch_amount then
    raise exception 'Payout batch amount must equal its exact members' using errcode='23514';
  end if;
  return null;
end;$function$;
create constraint trigger check_learning_instructor_payout_batch_total_on_batch
after insert on public.learning_instructor_payout_batches
deferrable initially deferred for each row
execute function public.check_learning_instructor_payout_batch_total();
create constraint trigger check_learning_instructor_payout_batch_total_on_member
after insert on public.learning_instructor_payout_batch_members
deferrable initially deferred for each row
execute function public.check_learning_instructor_payout_batch_total();

revoke all on function public.prevent_learning_instructor_payout_batch_mutation(),
  public.validate_learning_instructor_payout_batch_member(),
  public.prevent_learning_single_payout_batch_overlap(),
  public.check_learning_instructor_payout_batch_total() from public,anon,authenticated;

commit;
