-- Phase 4: private register of enterprise agreements already executed outside Growvelt.
-- This stores administrative reference metadata only. It does not alter billing,
-- company seats, course access, checkout, or seller proceeds.
begin;

create table public.learning_company_enterprise_contract_records (
  id bigint generated by default as identity primary key,
  workspace_id bigint not null references public.learning_company_workspaces(id) on delete restrict,
  contract_reference text not null check (
    contract_reference = btrim(contract_reference)
    and contract_reference ~ '^[A-Za-z0-9][A-Za-z0-9._/-]{2,99}$'
  ),
  starts_on date not null,
  ends_on date,
  seat_cap integer not null check (seat_cap between 1 and 100000),
  scope_summary text not null check (char_length(btrim(scope_summary)) between 10 and 500),
  recorded_by uuid not null references public.profiles(id) on delete restrict,
  recorded_at timestamptz not null default now(),
  constraint learning_company_enterprise_contract_term_check
    check (ends_on is null or ends_on >= starts_on)
);

create unique index learning_company_enterprise_contract_reference_idx
  on public.learning_company_enterprise_contract_records(workspace_id, lower(contract_reference));
create index learning_company_enterprise_contract_workspace_idx
  on public.learning_company_enterprise_contract_records(workspace_id, recorded_at desc, id desc);

alter table public.learning_company_enterprise_contract_records enable row level security;
revoke all on public.learning_company_enterprise_contract_records from public, anon, authenticated, service_role;
grant select, insert on public.learning_company_enterprise_contract_records to postgres;
revoke all on sequence public.learning_company_enterprise_contract_records_id_seq from public, anon, authenticated, service_role;
grant usage, select on sequence public.learning_company_enterprise_contract_records_id_seq to postgres;

create or replace function public.prevent_learning_enterprise_contract_mutation()
returns trigger
language plpgsql
security definer
set search_path to ''
as $function$
begin
  raise exception 'Enterprise contract records are append-only' using errcode = '42501';
end;
$function$;

revoke all on function public.prevent_learning_enterprise_contract_mutation() from public, anon, authenticated, service_role;
grant execute on function public.prevent_learning_enterprise_contract_mutation() to postgres;

create trigger learning_enterprise_contract_records_immutable
before update or delete on public.learning_company_enterprise_contract_records
for each row execute function public.prevent_learning_enterprise_contract_mutation();

create or replace function public.list_learning_enterprise_contract_workspaces_for_admin()
returns table(workspace_id bigint, workspace_name text, workspace_slug text, seat_limit integer)
language plpgsql
stable
security definer
set search_path to ''
as $function$
begin
  if auth.uid() is null or not public.is_growvelt_learning_admin() then
    raise exception 'Learning Admin access required' using errcode = '42501';
  end if;

  return query
    select workspace.id, workspace.name, workspace.slug, workspace.seat_limit
    from public.learning_company_workspaces workspace
    where workspace.status = 'active'
    order by workspace.name, workspace.id;
end;
$function$;

create or replace function public.list_learning_enterprise_contract_records_for_admin()
returns table(
  contract_id bigint,
  workspace_id bigint,
  workspace_name text,
  contract_reference text,
  starts_on date,
  ends_on date,
  seat_cap integer,
  scope_summary text,
  recorded_at timestamptz,
  contract_state text
)
language plpgsql
stable
security definer
set search_path to ''
as $function$
begin
  if auth.uid() is null or not public.is_growvelt_learning_admin() then
    raise exception 'Learning Admin access required' using errcode = '42501';
  end if;

  return query
    select contract.id, contract.workspace_id, workspace.name, contract.contract_reference,
      contract.starts_on, contract.ends_on, contract.seat_cap, contract.scope_summary,
      contract.recorded_at,
      case
        when current_date < contract.starts_on then 'scheduled'
        when contract.ends_on is not null and current_date > contract.ends_on then 'ended'
        else 'in_term'
      end
    from public.learning_company_enterprise_contract_records contract
    join public.learning_company_workspaces workspace on workspace.id = contract.workspace_id
    order by contract.recorded_at desc, contract.id desc;
end;
$function$;

create or replace function public.record_learning_enterprise_contract_for_admin(
  p_workspace_id bigint,
  p_contract_reference text,
  p_starts_on date,
  p_ends_on date,
  p_seat_cap integer,
  p_scope_summary text,
  p_executed_externally boolean
)
returns table(contract_id bigint, contract_reference text, recorded_at timestamptz)
language plpgsql
security definer
set search_path to ''
as $function$
declare
  normalized_reference text := btrim(p_contract_reference);
  normalized_summary text := btrim(p_scope_summary);
  inserted_contract_id bigint;
begin
  if auth.uid() is null or not public.is_growvelt_learning_admin() then
    raise exception 'Learning Admin access required' using errcode = '42501';
  end if;
  if p_executed_externally is distinct from true then
    raise exception 'Only agreements already executed outside Growvelt may be recorded' using errcode = '42501';
  end if;
  if p_workspace_id is null or not exists (
    select 1 from public.learning_company_workspaces workspace
    where workspace.id = p_workspace_id and workspace.status = 'active'
  ) then
    raise exception 'Choose an active company workspace' using errcode = '22023';
  end if;
  if normalized_reference is null
    or normalized_reference !~ '^[A-Za-z0-9][A-Za-z0-9._/-]{2,99}$'
    or p_starts_on is null
    or (p_ends_on is not null and p_ends_on < p_starts_on)
    or p_seat_cap is null or p_seat_cap not between 1 and 100000
    or normalized_summary is null or char_length(normalized_summary) not between 10 and 500 then
    raise exception 'Invalid enterprise contract record' using errcode = '22023';
  end if;

  insert into public.learning_company_enterprise_contract_records(
    workspace_id, contract_reference, starts_on, ends_on, seat_cap, scope_summary, recorded_by
  ) values (
    p_workspace_id, normalized_reference, p_starts_on, p_ends_on, p_seat_cap, normalized_summary, auth.uid()
  ) returning id into inserted_contract_id;

  insert into public.learning_audit_events(actor_user_id, actor_role, action, entity_type, entity_id, metadata)
  values(
    auth.uid(), 'admin_operator', 'company.enterprise_contract.recorded',
    'learning_company_enterprise_contract', inserted_contract_id::text,
    jsonb_build_object('workspace_id', p_workspace_id, 'seat_cap', p_seat_cap, 'starts_on', p_starts_on, 'ends_on', p_ends_on)
  );

  return query
    select contract.id, contract.contract_reference, contract.recorded_at
    from public.learning_company_enterprise_contract_records contract
    where contract.id = inserted_contract_id;
end;
$function$;

revoke all on function public.list_learning_enterprise_contract_workspaces_for_admin() from public, anon, authenticated, service_role;
revoke all on function public.list_learning_enterprise_contract_records_for_admin() from public, anon, authenticated, service_role;
revoke all on function public.record_learning_enterprise_contract_for_admin(bigint, text, date, date, integer, text, boolean) from public, anon, authenticated, service_role;
grant execute on function public.list_learning_enterprise_contract_workspaces_for_admin() to authenticated, postgres;
grant execute on function public.list_learning_enterprise_contract_records_for_admin() to authenticated, postgres;
grant execute on function public.record_learning_enterprise_contract_for_admin(bigint, text, date, date, integer, text, boolean) to authenticated, postgres;

commit;
