-- One founder-supervised OTP finalization attempt per Live payout item.
-- OTP values are never persisted. Ambiguous outcomes require verification.
begin;

create table if not exists public.learning_instructor_payout_live_otp_attempts (
  id bigint generated by default as identity primary key,
  payout_item_id bigint not null unique references public.learning_instructor_payout_items(id) on delete restrict,
  transfer_code text not null check (transfer_code ~ '^TRF_[A-Za-z0-9]+$'),
  initiated_by uuid not null references public.profiles(id) on delete restrict,
  status text not null default 'started' check (status in ('started','submitted','needs_attention')),
  created_at timestamptz not null default now(),
  completed_at timestamptz,
  constraint learning_instructor_payout_live_otp_attempt_completion_check
    check ((status='started' and completed_at is null) or (status<>'started' and completed_at is not null))
);
alter table public.learning_instructor_payout_live_otp_attempts enable row level security;
revoke all on public.learning_instructor_payout_live_otp_attempts from public,anon,authenticated;
grant select,insert,update on public.learning_instructor_payout_live_otp_attempts to postgres,service_role;

create or replace function public.prevent_learning_instructor_payout_live_otp_attempt_mutation()
returns trigger language plpgsql security definer set search_path to '' as $function$
begin
  if tg_op='DELETE' then raise exception 'OTP attempt history is retained' using errcode='42501'; end if;
  if old.payout_item_id is distinct from new.payout_item_id or old.transfer_code is distinct from new.transfer_code
    or old.initiated_by is distinct from new.initiated_by or old.created_at is distinct from new.created_at
    or old.status<>'started' or new.status not in ('submitted','needs_attention')
    or new.completed_at is null then
    raise exception 'Unsupported OTP attempt change' using errcode='22023';
  end if;
  return new;
end;$function$;
do $trigger$
begin
  if not exists(select 1 from pg_trigger where tgrelid='public.learning_instructor_payout_live_otp_attempts'::regclass
    and tgname='prevent_learning_instructor_payout_live_otp_attempt_mutation' and not tgisinternal) then
    create trigger prevent_learning_instructor_payout_live_otp_attempt_mutation
      before update or delete on public.learning_instructor_payout_live_otp_attempts for each row
      execute function public.prevent_learning_instructor_payout_live_otp_attempt_mutation();
  end if;
end $trigger$;

create or replace function public.begin_learning_instructor_live_otp_finalization(p_payout_item_id bigint,p_actor_user_id uuid)
returns table(attempt_id bigint,payout_item_reference text,transfer_code text,transfer_id text,amount_minor bigint,currency text)
language plpgsql security definer set search_path to '' as $function$
declare item public.learning_instructor_payout_items%rowtype;
        earning public.learning_instructor_earnings%rowtype;
        allocation public.learning_commercial_allocations%rowtype;
        learning_order public.learning_orders%rowtype;
        new_id bigint;
begin
  if p_actor_user_id is null or not exists(select 1 from public.account_capabilities capability
    where capability.user_id=p_actor_user_id and capability.capability='admin' and capability.status='active') then
    raise exception 'Active administrator required' using errcode='42501';
  end if;
  select * into item from public.learning_instructor_payout_items payout_item where payout_item.id=p_payout_item_id for update;
  if not found or item.provider_domain<>'live' or item.status<>'pending' or item.provider_status<>'otp'
    or item.provider_transfer_code is null or item.provider_transfer_id is null or item.initiated_at is null
    or item.initiated_at < now()-interval '25 minutes'
    or exists(select 1 from public.learning_instructor_payout_live_otp_attempts attempt where attempt.payout_item_id=item.id) then
    raise exception 'Live OTP finalization is not available; verify the transfer' using errcode='22023';
  end if;
  select * into earning from public.learning_instructor_earnings e where e.id=item.earning_id for update;
  select * into allocation from public.learning_commercial_allocations a where a.id=item.allocation_id for update;
  select * into learning_order from public.learning_orders o where o.id=allocation.order_id for update;
  if earning.id is null or allocation.id is null or learning_order.id is null
    or earning.status<>'reserved' or allocation.status<>'allocated' or learning_order.status<>'paid' then
    raise exception 'Live OTP finalization is financially blocked' using errcode='22023';
  end if;
  lock table public.learning_payment_cases in share row exclusive mode;
  if exists(select 1 from public.learning_payment_cases payment_case where payment_case.order_id=learning_order.id
    and payment_case.status in ('requested','submitting','pending','processing','needs_attention','opened','action_required','submitted','under_review')) then
    raise exception 'Active financial protection blocks Live OTP finalization' using errcode='22023';
  end if;
  insert into public.learning_instructor_payout_live_otp_attempts(payout_item_id,transfer_code,initiated_by)
    values(item.id,item.provider_transfer_code,p_actor_user_id) returning id into new_id;
  insert into public.learning_instructor_payout_item_events(payout_item_id,event_type,from_status,to_status,provenance,actor_user_id,metadata)
    values(item.id,'payout_item.otp_finalization_started','pending','pending','admin',p_actor_user_id,
      jsonb_build_object('attempt_id',new_id));
  return query select new_id,item.payout_item_reference,item.provider_transfer_code,item.provider_transfer_id,
    item.amount_minor,item.currency;
end;$function$;

create or replace function public.complete_learning_instructor_live_otp_finalization(
  p_attempt_id bigint,p_outcome text,p_actor_user_id uuid)
returns void language plpgsql security definer set search_path to '' as $function$
declare attempt public.learning_instructor_payout_live_otp_attempts%rowtype;
begin
  if p_actor_user_id is null or not exists(select 1 from public.account_capabilities capability
    where capability.user_id=p_actor_user_id and capability.capability='admin' and capability.status='active')
    or p_outcome not in ('submitted','needs_attention') then
    raise exception 'Valid administrator and OTP outcome required' using errcode='42501';
  end if;
  select * into attempt from public.learning_instructor_payout_live_otp_attempts row where row.id=p_attempt_id for update;
  if not found or attempt.status<>'started' then
    raise exception 'Open OTP attempt required' using errcode='22023';
  end if;
  update public.learning_instructor_payout_live_otp_attempts set status=p_outcome,completed_at=now() where id=attempt.id;
  insert into public.learning_instructor_payout_item_events(payout_item_id,event_type,from_status,to_status,provenance,actor_user_id,metadata)
    values(attempt.payout_item_id,'payout_item.otp_finalization_'||p_outcome,'pending','pending','provider_api',p_actor_user_id,
      jsonb_build_object('attempt_id',attempt.id));
end;$function$;

revoke all on function public.prevent_learning_instructor_payout_live_otp_attempt_mutation(),
  public.begin_learning_instructor_live_otp_finalization(bigint,uuid),
  public.complete_learning_instructor_live_otp_finalization(bigint,text,uuid) from public,anon,authenticated;
grant execute on function public.prevent_learning_instructor_payout_live_otp_attempt_mutation(),
  public.begin_learning_instructor_live_otp_finalization(bigint,uuid),
  public.complete_learning_instructor_live_otp_finalization(bigint,text,uuid) to postgres,service_role;
commit;
