on public.profiles
for select
to authenticated
using (auth.uid() = id);

create policy "Profiles are created by owner"
on public.profiles
for insert
to authenticated
with check (auth.uid() = id);

create policy "Profiles are updated by owner"
on public.profiles
for update
to authenticated
using (auth.uid() = id)
with check (auth.uid() = id);

