create policy "Published courses are public"
on public.learning_courses
for select
to anon, authenticated
using (status = 'published');

create policy "Published course modules are public"
on public.course_modules
for select
to anon, authenticated
using (
  exists (
    select 1 from public.learning_courses
    where learning_courses.id = course_modules.course_id
      and learning_courses.status = 'published'
  )
);

create policy "Published course preview lessons are public"
on public.lessons
for select
to anon, authenticated
using (
  is_preview = true
  and exists (
    select 1 from public.learning_courses
    where learning_courses.id = lessons.course_id
      and learning_courses.status = 'published'
  )
);

