to authenticated
using (
  exists (
    select 1 from public.enrollments
    where enrollments.id = lesson_progress.enrollment_id
      and enrollments.learner_id = auth.uid()
  )
)
with check (
  exists (
    select 1 from public.enrollments
    where enrollments.id = lesson_progress.enrollment_id
      and enrollments.learner_id = auth.uid()
  )
);

