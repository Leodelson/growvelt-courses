-- Growvelt Learning platform tables.
-- These extend the current marketing/registration site into a learning platform.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  email text,
  account_type text not null default 'learner'
    check (account_type in ('learner', 'instructor', 'admin')),
  avatar_url text,
  onboarding_status text not null default 'pending'
    check (onboarding_status in ('pending', 'complete')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.instructor_profiles (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references public.profiles(id) on delete cascade,
  headline text,
  bio text,
  expertise text[],
  approval_status text not null default 'pending'
    check (approval_status in ('pending', 'approved', 'rejected')),
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.learning_courses (
  id bigint generated by default as identity primary key,
  instructor_id uuid references public.profiles(id) on delete set null,
  title text not null,
  slug text not null unique,
  summary text,
  description text,
  level text,
  category text,
  thumbnail_url text,
  price_amount numeric(10, 2),
  price_currency text default 'NGN',
  is_free boolean not null default false,
  is_limited_time_free boolean not null default false,
  status text not null default 'draft'
    check (status in ('draft', 'pending_review', 'published', 'archived')),
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.course_modules (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.learning_courses(id) on delete cascade,
  title text not null,
  position int not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.lessons (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.learning_courses(id) on delete cascade,
  module_id bigint references public.course_modules(id) on delete cascade,
  title text not null,
  lesson_type text not null default 'video'
    check (lesson_type in ('video', 'text', 'quiz', 'project')),
  content text,
  video_url text,
  duration_minutes int,
  is_preview boolean not null default false,
  position int not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.lesson_resources (
  id bigint generated by default as identity primary key,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  title text not null,
  resource_url text not null,
  resource_type text,
  created_at timestamptz not null default now()
);

create table if not exists public.enrollments (
  id bigint generated by default as identity primary key,
  learner_id uuid not null references public.profiles(id) on delete cascade,
  course_id bigint not null references public.learning_courses(id) on delete cascade,
  status text not null default 'active'
    check (status in ('active', 'completed', 'cancelled')),
  enrolled_at timestamptz not null default now(),
  completed_at timestamptz,
  unique (learner_id, course_id)
);

create table if not exists public.lesson_progress (
  id bigint generated by default as identity primary key,
  enrollment_id bigint not null references public.enrollments(id) on delete cascade,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  completed_at timestamptz,
  progress_percent int not null default 0 check (progress_percent between 0 and 100),
  unique (enrollment_id, lesson_id)
);

create table if not exists public.course_reviews (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.learning_courses(id) on delete cascade,
  learner_id uuid references public.profiles(id) on delete set null,
  rating int not null check (rating between 1 and 5),
  review text,
  status text not null default 'published'
    check (status in ('pending', 'published', 'hidden')),
  created_at timestamptz not null default now()
);

create table if not exists public.certificates (
  id bigint generated by default as identity primary key,
  learner_id uuid not null references public.profiles(id) on delete cascade,
  course_id bigint not null references public.learning_courses(id) on delete cascade,
  certificate_code text not null unique,
  issued_at timestamptz not null default now(),
  certificate_url text,
  unique (learner_id, course_id)
);

