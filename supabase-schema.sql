-- Growvelt Courses website database schema.
-- Run this in a separate Supabase project for courses.growvelt.com.

create table if not exists public.course_contacts (
  id bigint generated by default as identity primary key,
  name text,
  email text not null,
  phone text,
  type text,
  message text,
  source_page text,
  created_at timestamptz not null default now()
);

create table if not exists public.newsletter_subscribers (
  id bigint generated by default as identity primary key,
  email text not null unique,
  source_page text,
  created_at timestamptz not null default now()
);

create table if not exists public.partner_requests (
  id bigint generated by default as identity primary key,
  full_name text,
  email text not null,
  phone text,
  partnership_type text,
  idea text,
  source_page text,
  created_at timestamptz not null default now()
);

create table if not exists public.course_registrations (
  id bigint generated by default as identity primary key,
  registration_ref text unique,
  full_name text not null,
  email text not null,
  phone text,
  course text not null,
  learning_mode text,
  experience_level text,
  message text,
  payment_status text not null default 'pending',
  payment_amount numeric(10, 2),
  payment_currency text,
  paystack_reference text unique,
  paystack_access_code text,
  paystack_transaction_id text,
  payer_email text,
  paid_at timestamptz,
  email_sent_at timestamptz,
  admin_notified_at timestamptz,
  source_page text,
  created_at timestamptz not null default now()
);

alter table public.course_registrations
